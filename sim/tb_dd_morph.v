// tb_dd_morph.v  ——  dd_morph（二值闭运算）的 testbench。
//   **故意不放进 Vivado 工程**，放在 PROJECT\tb\ 下单独跑。
//
//   --------------------------------------------------------------------
//   黄金参考怎么算 —— 整幅二维闭运算，和 RTL 的流水结构毫无共同代码
//   --------------------------------------------------------------------
//   RTL 走的是"膨胀级 3×3 窗口 → 腐蚀级 3×3 窗口"这条**两条流水线串联**的路；
//   tb 直接把这帧当成一张 2D 图，按定义算：
//       dil(r,c) = in(r-1..r+1, c-1..c+1) 这 9 个的**或**
//       ero(r,c) = dil(r-1..r+1, c-1..c+1) 这 9 个的**与**
//   ⇒ 合成起来就是"3×3 结构元的闭运算"。
//   两者结构完全不同 ⇒ RTL 里任何**行缓冲深度错**、**窗口取错边**、
//   **OR/AND 写反**、**延迟算错**都会立刻对不上。
//
//   --------------------------------------------------------------------
//   ★ 边界处理：**零填充数组**（把图塞进带 1 圈 0 的大数组里）
//   --------------------------------------------------------------------
//   第一版用 `in_at(rr,cc)` 这种"越界就返回 0"的**函数**做边界判断，
//   结果整个腐蚀图恒为 0（膨胀图却是对的）—— 是个纯粹的 tb 写法坑。
//   现在改成：把图像存在 `(ROWS+2) × (W+2)` 的数组里，四周那圈恒为 0，
//   内层循环就**不需要任何边界判断**了。既躲开那个坑，也更快。
//
//   --------------------------------------------------------------------
//   ★ 输出位置与拍数的换算（RTL 约定，推导见 dd_morph.v 文件头）
//   --------------------------------------------------------------------
//   输入像素 (R,C) 在第 k 拍进来 ⇒ 第 k+2 拍输出的是**位置 (R-2, C-2)** 的结果。
//   （两级各 1 拍；行缓冲那"2 行"是**空间**延迟，不落在拍数上。）
//   ⇒ 有效输出位置：R-2 ≥ 2 且 C-2 ≥ 2，即 **R ≥ 4 且 C ≥ 4**。
//   ⇒ 本 tb 用 8 行 × 972 列 ⇒ 有效输出 4 行（2..5）× 968 列（2..969）。
//
//   --------------------------------------------------------------------
//   覆盖的用例
//   --------------------------------------------------------------------
//     ① 全 0            —— 闭运算不许凭空造出白点
//     ② 全 1            —— 闭运算不许吃掉成片白区
//     ③ 1 像素宽竖线     —— ★ 闭运算**不许把它加宽**（这正是"闭"而不是"开"）
//     ④ ★ 两条相距 1 像素的平行竖线 —— 闭运算**必须把它们连起来**（核心价值）
//     ⑤a ★ 实心块上挖掉**中心 1 个像素** —— 闭运算**必须把这个 1 像素洞填上**
//     ⑤b ★ 空心 5×5 框（洞是 3×3）—— 闭运算**填不上**，这是结构元的尺寸上限
//     ⑥ 孤立单点         —— 闭运算**必须保留它**（开运动会删掉 ⇒ 所以不能用开运算）
//     ⑦ 四个伪随机图     —— 全图逐像素比对
//     ⑧ ★ cfg_en=0 旁路  —— 输出必须**逐像素等于原始掩膜**（验证旁路与闭运算严格对齐）
//     ⑨ 中途插空拍       —— 不许错位
//
//   --------------------------------------------------------------------
//   注释规范（项目要求，2026-09-24）
//   --------------------------------------------------------------------
//       每一行有实际功能的代码，行尾都跟一条中文注释。
//       本文件以 **UTF-8（无 BOM）** 编码保存。
//////////////////////////////////////////////////////////////////////////////
`timescale 1ns / 1ps

module tb_dd_morph;

    //=====================================================================
    // 帧几何
    //   ★ 行数必须 ≥6（有效输出要从第 2 行到第 5 行）
    //   ★ 列数用 972，和真实行宽一致 —— 行缓冲深度是按 972/970 写死的，
    //     用别的列数就验不出"970 vs 972"这个最容易错的地方
    //=====================================================================
    localparam integer W    = 972;          // 每行像素数（= dd_morph 的 H_ACTIVE）
    localparam integer ROWS = 8;            // 帧的行数
    localparam integer N    = W * ROWS;     // 一帧的总像素数（不填充）

    localparam integer PW   = W + 2;                // 填充后的行宽（左右各 1 圈 0）
    localparam integer PN   = (ROWS + 2) * PW;      // 填充后的总格子数

    //=====================================================================
    // 时钟与复位
    //=====================================================================
    reg clk   = 1'b0;                   // 时钟
    reg rst_n = 1'b0;                   // 低有效复位

    always #5 clk = ~clk;               // 10ns = 100MHz

    //=====================================================================
    // DUT 端口
    //=====================================================================
    reg  in_hit   = 1'b0;               // 二值输入
    reg  in_valid = 1'b0;               // 输入有效
    reg  in_sof   = 1'b0;               // 帧首
    reg  in_eol   = 1'b0;               // 行尾
    reg  in_eof   = 1'b0;               // 帧尾
    reg  cfg_en   = 1'b1;               // 形态学使能（1 = 闭运算 / 0 = 旁路）

    wire out_hit;                       // 输出掩膜
    wire out_valid, out_sof, out_eol, out_eof;   // 输出 sideband

    dd_morph #(
        .H_ACTIVE (W)                   // 把行宽传下去（行缓冲深度按它推导）
    ) dut (
        .clk       (clk),               // 100MHz
        .rst_n     (rst_n),             // 低有效复位
        .in_hit    (in_hit),            // 二值输入
        .in_valid  (in_valid),          // 输入有效
        .in_sof    (in_sof),            // 帧首
        .in_eol    (in_eol),            // 行尾
        .in_eof    (in_eof),            // 帧尾
        .cfg_en    (cfg_en),            // 形态学使能
        .out_hit   (out_hit),           // 输出掩膜
        .out_valid (out_valid),         // 输出有效
        .out_sof   (out_sof),           // 帧首
        .out_eol   (out_eol),           // 行尾
        .out_eof   (out_eof)            // 帧尾
    );

    //=====================================================================
    // 图像数组（**带 1 圈零填充**）
    //   pin / pdil / pero 都用"填充坐标"索引：(r+1)*PW + (c+1)
    //   最外那圈永远保持 0 ⇒ 内层循环不需要任何边界判断
    //=====================================================================
    reg pin  [0:PN-1];                  // 输入掩膜（带零边）
    reg pdil [0:PN-1];                  // 膨胀结果（带零边）
    reg pero [0:PN-1];                  // 腐蚀结果 = 闭运算（带零边）

    //=====================================================================
    // 黄金参考：整幅二维闭运算 = 先膨胀、后腐蚀（3×3 结构元）
    //   ★ 结构上和 RTL 的"两级 3×3 流水窗口"完全不同
    //   ★ 边界就是那圈恒 0，所以不需要判越界
    //=====================================================================
    task golden_build;
        integer r, c;                   // 填充坐标下的循环变量（1..ROWS / 1..W）
        begin
            // ---- 第一步：膨胀 = 3×3 邻域取或 ----
            for (r = 1; r <= ROWS; r = r + 1)                       // 只遍历图像本体
                for (c = 1; c <= W; c = c + 1)                      // …
                    pdil[r*PW + c] =                                    // 本位置的膨胀值 =
                          pin[(r-1)*PW + (c-1)] | pin[(r-1)*PW + c] | pin[(r-1)*PW + (c+1)]  // 上行的三个
                        | pin[(r  )*PW + (c-1)] | pin[(r  )*PW + c] | pin[(r  )*PW + (c+1)]  // 本行的三个
                        | pin[(r+1)*PW + (c-1)] | pin[(r+1)*PW + c] | pin[(r+1)*PW + (c+1)]; // 下行的三个
            // ---- 第二步：腐蚀 = 对膨胀图再做 3×3 邻域取与 ----
            for (r = 1; r <= ROWS; r = r + 1)                       // 只遍历图像本体
                for (c = 1; c <= W; c = c + 1)                      // …
                    pero[r*PW + c] =                                    // 本位置的闭运算值 =
                          pdil[(r-1)*PW + (c-1)] & pdil[(r-1)*PW + c] & pdil[(r-1)*PW + (c+1)]  // 上行的三个
                        & pdil[(r  )*PW + (c-1)] & pdil[(r  )*PW + c] & pdil[(r  )*PW + (c+1)]  // 本行的三个
                        & pdil[(r+1)*PW + (c-1)] & pdil[(r+1)*PW + c] & pdil[(r+1)*PW + (c+1)]; // 下行的三个
        end
    endtask

    //=====================================================================
    // 图案构造子（全部写在**填充坐标**上：(r+1)*PW + (c+1)）
    //=====================================================================
    task pat_clear;                     // 整帧清 0（含填充圈）
        integer k;                      // 循环变量
        begin
            for (k = 0; k < PN; k = k + 1) pin[k] = 1'b0;       // 全部清 0
        end
    endtask

    task pat_fill;                      // 图像本体置 1（填充圈保持 0）
        integer r, c;                   // 循环变量
        begin
            for (r = 1; r <= ROWS; r = r + 1)                   // 逐行
                for (c = 1; c <= W; c = c + 1)                  // 逐列
                    pin[r*PW + c] = 1'b1;                       // 置 1
        end
    endtask

    task pat_vline (input integer c0);  // 原图坐标下的一整列置 1
        integer r;                      // 循环变量
        begin
            for (r = 0; r < ROWS; r = r + 1)                    // 从上到下
                pin[(r+1)*PW + (c0+1)] = 1'b1;                  // 该列整列点亮
        end
    endtask

    task pat_rect (input integer r0, input integer c0, input integer r1, input integer c1);
        integer r, c;                   // 循环变量
        begin
            for (r = r0; r <= r1; r = r + 1)                    // 逐行
                for (c = c0; c <= c1; c = c + 1)                // 逐列
                    pin[(r+1)*PW + (c+1)] = 1'b1;               // 整块填实
        end
    endtask

    // ---- LFSR 伪随机（16 位最大长度，抽头 16/14/13/11）----
    reg [15:0] lfsr = 16'hBEEF;         // 非零种子

    function rnd1 (input integer dummy);    // ★ Verilog 函数至少要有一个入参，留个占位
        begin
            lfsr = {lfsr[14:0], lfsr[15] ^ lfsr[13] ^ lfsr[12] ^ lfsr[10]};  // 推进一步
            rnd1 = lfsr[0];                                                 // 取最低位当随机位
        end
    endfunction

    task pat_random (input integer density);   // 随机图案，density 是 0..255 的阈值
        integer r, c;                   // 循环变量
        reg [7:0] rv;                   // 8 位随机数
        begin
            for (r = 1; r <= ROWS; r = r + 1)                   // 逐行
                for (c = 1; c <= W; c = c + 1) begin            // 逐列
                    rv = {rnd1(0),rnd1(0),rnd1(0),rnd1(0),      // 用 8 次单比特随机拼一个 8 位随机数
                          rnd1(0),rnd1(0),rnd1(0),rnd1(0)};     // …
                    pin[r*PW + c] = (rv < density[7:0]);        // 小于阈值就置 1 ⇒ 密度 ≈ density/256
                end
        end
    endtask

    //=====================================================================
    // 历史环形缓冲（4 深）：记下每一拍"期望的输出"，2 拍后拿来比对
    //   延迟 2 拍 ⇒ 第 k 拍查的是第 k-2 拍记下的槽位，
    //   即槽位 (k-2) mod 4 = (k+2) mod 4。
    //=====================================================================
    reg h_val [0:3];                    // 该拍是否应当有有效输出
    reg h_hit [0:3];                    // 该拍期望的 out_hit
    reg h_sof [0:3];                    // 该拍期望的 out_sof
    reg h_eol [0:3];                    // 该拍期望的 out_eol
    reg h_eof [0:3];                    // 该拍期望的 out_eof
    integer h_or [0:3];                 // 该拍输出对应的**行**（原图坐标）
    integer h_oc [0:3];                 // 该拍输出对应的**列**（原图坐标）

    // ★★ 把 RTL 输出的整帧**抓下来**，后面就能对 RTL 的图直接下断言 ★★
    //    只跟黄金参考逐像素比是不够的：那样"设计性质"（能不能连、会不会加宽）
    //    只被验在**模型**上，验不到 RTL。抓成图之后 chk_cell 查的就是 RTL 本身。
    reg out_img [0:N-1];                // RTL 输出掩膜，按**原图坐标** r*W+c 存放

    integer cyc    = 0;                 // 已发出的输入拍数
    integer checks = 0;                 // 比对次数
    integer errors = 0;                 // 错误次数

    //=====================================================================
    // 发一个像素拍：驱动 + 比对 2 拍前的期望
    //   ★ 所有输入在**同一个时刻**一起赋值
    // ====================================================================
    task beat (input v, input integer rr, input integer cc, input s, input e, input f);
        integer sc, sn;                 // 比对槽位 / 记录槽位
        integer orr, occ;               // 输出位置（原图坐标）= 输入位置 - 2 行 2 列
        reg     ev;                     // 本拍是否应当产生有效输出
        begin
            @(posedge clk); #1;                             // 对齐到本拍起点

            // ---------- 1) 先比对"2 拍前那一拍"的期望 ----------
            sc = (cyc + 2) % 4;                             // 2 拍前那一拍所在的环形槽位
            if (h_val[sc]) begin                            // 只在该拍应当有有效输出时才查
                checks = checks + 1;                        // 累计比对次数
                out_img[h_or[sc]*W + h_oc[sc]] = out_hit;   // ★ 把 RTL 的输出存回图里（供 chk_cell 用）
                if (out_hit !== h_hit[sc]) begin            // 逐像素比对掩膜
                    errors = errors + 1;                    // 记错
                    $display("[ERR] t=%0t pos=(%0d,%0d) out_hit=%b 期望=%b",
                             $time, h_or[sc], h_oc[sc], out_hit, h_hit[sc]);
                end
            end
            // valid 与三条 sideband 必须逐拍对齐（不能只对数据）
            checks = checks + 4;                            // 本拍查 4 根 sideband
            if (out_valid !== h_val[sc]) begin              // valid 错位 = 整条流水线错位
                errors = errors + 1;                        // 记错
                $display("[ERR] t=%0t out_valid=%b 期望=%b", $time, out_valid, h_val[sc]);
            end
            if (out_sof !== h_sof[sc]) begin                // sof 错位 = 下游控制全乱
                errors = errors + 1;                        // 记错
                $display("[ERR] t=%0t out_sof=%b 期望=%b", $time, out_sof, h_sof[sc]);
            end
            if (out_eol !== h_eol[sc]) begin                // eol 错位 = 行计数全乱
                errors = errors + 1;                        // 记错
                $display("[ERR] t=%0t out_eol=%b 期望=%b", $time, out_eol, h_eol[sc]);
            end
            if (out_eof !== h_eof[sc]) begin                // eof 错位 = 帧计数全乱
                errors = errors + 1;                        // 记错
                $display("[ERR] t=%0t out_eof=%b 期望=%b", $time, out_eof, h_eof[sc]);
            end

            // ---------- 2) 驱动本拍 ----------
            in_valid = v;                                   // 本拍是否有效
            in_hit   = (rr >= 0 && rr < ROWS && cc >= 0 && cc < W) ? pin[(rr+1)*PW + (cc+1)] : 1'b0;  // 输入位
            in_sof   = s;                                   // 帧首
            in_eol   = e;                                   // 行尾
            in_eof   = f;                                   // 帧尾

            // ---------- 3) 算本拍的期望，记进环形缓冲 ----------
            orr = rr - 2;                                   // 输出行（原图坐标）
            occ = cc - 2;                                   // 输出列（原图坐标）
            ev  = v && (orr >= 2) && (occ >= 2);            // ★ 与 RTL 的屏蔽范围一致（R≥4, C≥4）
            sn  = cyc % 4;                                  // 本拍写进的环形槽位
            h_val[sn] = ev;                                 // 记下本拍是否应有有效输出
            h_hit[sn] = ev ? (cfg_en ? pero[(orr+1)*PW + (occ+1)]      // cfg_en=1 ⇒ 期望闭运算结果
                                    : pin [(orr+1)*PW + (occ+1)])      // cfg_en=0 ⇒ 期望原始掩膜
                           : 1'b0;                          // 无效拍不比对
            h_sof[sn] = ev & (rr == 4) & (cc == 4);         // ★ 帧首 = 本帧第一个有效输出（位置 (2,2)）
            h_eol[sn] = ev & (cc == W-1);                   // ★ 行尾 = 本行最后一个有效输出列
            h_eof[sn] = ev & (rr == ROWS-1) & (cc == W-1);  // ★ 帧尾 = 本帧最后一个
            h_or[sn]  = orr;                                // 记下输出位置的行（供存图用）
            h_oc[sn]  = occ;                                // 记下输出位置的列
            cyc = cyc + 1;                                  // 拍数 +1
        end
    endtask

    //=====================================================================
    // 发一整帧
    //=====================================================================
    integer r, c;                       // 循环变量（主流程用）

    task send_frame;
        begin
            for (r = 0; r < ROWS; r = r + 1)                // 逐行
                for (c = 0; c < W; c = c + 1)               // 逐列
                    beat(1'b1, r, c,                        // 有效像素
                         (r == 0) && (c == 0),              // 帧首（输入侧的 sof）
                         (c == W-1),                        // 行尾
                         (r == ROWS-1) && (c == W-1));      // 帧尾
        end
    endtask

    //=====================================================================
    // 空拍
    //=====================================================================
    task idle (input integer n);
        integer i;                      // 循环变量
        begin
            for (i = 0; i < n; i = i + 1)
                beat(1'b0, -1, -1, 1'b0, 1'b0, 1'b0);       // 空拍：valid=0
        end
    endtask

    //=====================================================================
    // 单点断言：**直接查 RTL 抓下来的输出图**，并把黄金参考当第二道保险
    //   nm 只用 ASCII（中文走 %0s 会被工具串成乱码，已实测）
    //   ★ 顺序要紧：先查 RTL（那才是被测对象），再查模型（防止模型本身写错）
    // ====================================================================
    task chk_cell (input [127:0] nm, input integer rr, input integer cc, input exp);
        begin
            checks = checks + 2;                                            // 两个用例：RTL + 模型
            if (out_img[rr*W + cc] !== exp) begin                           // ① RTL 的实际输出
                errors = errors + 1;                                        // 记错
                $display("  FAIL  [%0s] RTL 输出(%0d,%0d)=%b 期望=%b",
                         nm, rr, cc, out_img[rr*W+cc], exp);
            end else begin                                                  // 相符
                $display("  ok    [%0s] RTL 输出(%0d,%0d)=%b", nm, rr, cc, out_img[rr*W+cc]);
            end
            if (pero[(rr+1)*PW + (cc+1)] !== exp) begin                     // ② 黄金参考也得对
                errors = errors + 1;                                        // 记错
                $display("  FAIL  [%0s] 黄金参考(%0d,%0d)=%b 期望=%b（模型本身有问题）",
                         nm, rr, cc, pero[(rr+1)*PW+(cc+1)], exp);
            end
        end
    endtask

    //=====================================================================
    // 主测试流程
    //=====================================================================
    integer k;                          // 循环变量
    integer seed_i;                     // 随机图案计数

    initial begin
        $display("==== tb_dd_morph 开始（二值闭运算：先膨胀、后腐蚀）====");

        for (k = 0; k < 4; k = k + 1) begin                 // 初始化环形缓冲
            h_val[k] = 1'b0; h_hit[k] = 1'b0;               // 期望全 0（复位后正好对上）
            h_sof[k] = 1'b0; h_eol[k] = 1'b0; h_eof[k] = 1'b0;   // sideband 也全 0
            h_or[k]  = 0;    h_oc[k]  = 0;                  // 输出位置占位
        end
        pat_clear;                                          // 先给 pin 一个确定值（含填充圈）

        rst_n = 1'b0;                                       // 按住复位
        repeat (5) @(negedge clk);                          // 等 5 拍
        rst_n = 1'b1;                                       // 放开复位

        //=================================================================
        // ① 全 0：闭运算不许凭空造出白点
        //=================================================================
        $display("-- 1 all-zero frame (cfg_en=1) --");
        pat_clear;                                          // 整帧清 0
        golden_build;                                       // 算黄金参考
        cfg_en = 1'b1;                                      // 打开闭运算
        send_frame;                                         // 发整帧
        idle(8);                                            // 收尾
        chk_cell("all0:center", 3, 500, 1'b0);              // 中心处必须是 0
        chk_cell("all0:first",  2, 2,   1'b0);              // 本帧第一个有效输出点也必须是 0

        //=================================================================
        // ② 全 1：闭运算不许吃掉成片白区
        //=================================================================
        $display("-- 2 all-one frame (cfg_en=1) --");
        pat_fill;                                           // 整帧置 1
        golden_build;                                       // 黄金参考
        send_frame;                                         // 发整帧
        idle(8);                                            // 收尾
        chk_cell("all1:center", 3, 500, 1'b1);              // 中心处必须是 1
        chk_cell("all1:corner", 5, 900, 1'b1);              // 靠右下也必须是 1

        //=================================================================
        // ③ ★ 1 像素宽竖线：闭运算**不许把它加宽**
        //   列 200 整列点亮 ⇒ 闭运算后仍然只有第 200 列是 1
        //   （如果左右两列也变白，就说明膨胀之后没腐蚀回去 = 变成了"只膨胀"）
        //=================================================================
        $display("-- 3 one-pixel vertical line @col200 (closing must NOT widen) --");
        pat_clear;                                          // 清 0
        pat_vline(200);                                     // 点亮一整列
        golden_build;                                       // 黄金参考
        send_frame;                                         // 发整帧
        idle(8);                                            // 收尾
        chk_cell("vline:on",   3, 200, 1'b1);               // 线上必须是 1（没被吃掉）
        chk_cell("vline:left", 3, 199, 1'b0);               // 左侧**不许**变白
        chk_cell("vline:right",3, 201, 1'b0);               // 右侧**不许**变白

        //=================================================================
        // ④ ★★ 两条相距 1 像素的平行竖线：闭运算**必须把它们连起来** ★★
        //   列 400 和列 402 各一条，中间列 401 是空的。
        //   膨胀一次后三条都变白 ⇒ 腐蚀后第 401 列**必须变成 1**。
        //   ★ 这正是"支路 B 报的两条轮廓要合成一条"的那个动作。
        //   ★ 同时验证外面不许扩：399 和 403 必须还是 0（说明确实腐蚀回去了）。
        //=================================================================
        $display("-- 4 two parallel lines 1px apart @col400/402 (closing MUST connect) --");
        pat_clear;                                          // 清 0
        pat_vline(400);                                     // 左轮廓
        pat_vline(402);                                     // 右轮廓
        golden_build;                                       // 黄金参考
        send_frame;                                         // 发整帧
        idle(8);                                            // 收尾
        chk_cell("gap:left",  3, 400, 1'b1);                // 左轮廓还在
        chk_cell("gap:mid",   3, 401, 1'b1);                // ★ 中间的空隙被连上了
        chk_cell("gap:right", 3, 402, 1'b1);                // 右轮廓还在
        chk_cell("gap:outL",  3, 399, 1'b0);                // 再往外不许扩
        chk_cell("gap:outR",  3, 403, 1'b0);                // 再往外不许扩

        //=================================================================
        // ⑤a ★ 实心块上挖掉中心 1 个像素 ⇒ 闭运算**必须把这个洞填上**
        //   块范围 rows 2..6 × cols 600..604（5×5），只把中心 (4,602) 清 0。
        //   中心像素的 3×3 邻域全是实心 ⇒ 膨胀后中心变白 ⇒ 腐蚀后仍是白 ✓
        //=================================================================
        $display("-- 5a solid 5x5 block with 1-pixel hole (closing MUST fill) --");
        pat_clear;                                          // 清 0
        pat_rect(2, 600, 6, 604);                           // 先填成实心 5×5
        pin[(4+1)*PW + (602+1)] = 1'b0;                     // ★ 再挖掉中心 1 个像素
        golden_build;                                       // 黄金参考
        send_frame;                                         // 发整帧
        idle(8);                                            // 收尾
        chk_cell("hole1:filled", 4, 602, 1'b1);             // ★ 1 像素洞被填上了
        chk_cell("hole1:body",   2, 602, 1'b1);             // 块本体还在
        chk_cell("hole1:out",    4, 598, 1'b0);             // 外面不许扩

        //=================================================================
        // ⑤b ★ 反向用例：空心 5×5 框（洞是 **3×3**）⇒ 闭运算**填不上**
        //   这不是 bug，是结构元的尺寸上限：3×3 的闭运算只能填比结构元小的洞。
        //   把这个"填不上"也写成断言，免得以后有人以为能填。
        //=================================================================
        $display("-- 5b hollow 5x5 frame (3x3 hole) => closing must NOT fill --");
        pat_clear;                                          // 清 0
        pat_rect(2, 600, 6, 604);                           // 先填实心
        for (r = 3; r <= 5; r = r + 1)                      // 再挖掉 3×3 的内部
            for (c = 601; c <= 603; c = c + 1)              // …
                pin[(r+1)*PW + (c+1)] = 1'b0;               // 挖空
        golden_build;                                       // 黄金参考
        send_frame;                                         // 发整帧
        idle(8);                                            // 收尾
        chk_cell("hole3:notfill", 4, 602, 1'b0);            // ★ 3×3 的洞填不上（结构元上限）
        chk_cell("hole3:frame",   2, 602, 1'b1);            // 外框还在

        //=================================================================
        // ⑥ 孤立单点：闭运算**必须保留它**（开运动会把它删掉）
        //=================================================================
        $display("-- 6 isolated single pixel @(4,800) (closing MUST keep it) --");
        pat_clear;                                          // 清 0
        pin[(4+1)*PW + (800+1)] = 1'b1;                     // 点一个孤立的 1
        golden_build;                                       // 黄金参考
        send_frame;                                         // 发整帧
        idle(8);                                            // 收尾
        chk_cell("dot:on",   4, 800, 1'b1);                 // ★ 还在（开运动会删掉它）
        chk_cell("dot:left", 4, 799, 1'b0);                 // 没被加宽
        chk_cell("dot:up",   3, 800, 1'b0);                 // 没被加宽

        //=================================================================
        // ⑦ 四个伪随机图：全图逐像素比对（最广的覆盖）
        //=================================================================
        for (seed_i = 0; seed_i < 4; seed_i = seed_i + 1) begin     // 四个不同密度
            $display("-- 7 random pattern, density threshold = %0d / 256 --", 40 + seed_i*30);
            pat_random(40 + seed_i * 30);                   // 随机密度
            golden_build;                                   // 黄金参考
            send_frame;                                     // 发整帧
            idle(8);                                        // 收尾
        end

        //=================================================================
        // ⑧ ★ cfg_en=0 旁路：输出必须逐像素等于**原始掩膜**
        //   图案仍是第 ④ 个（两条平行线）—— 旁路时中间列 401 必须还是 0。
        //   如果它在旁路下也变成 1，说明旁路没生效（或者旁路数据接错了）；
        //   如果它的位置整体偏了，说明旁路和闭运算没对齐（逐像素比对会全线报错）。
        //=================================================================
        $display("-- 8 same two lines, cfg_en=0 (bypass => output == raw mask) --");
        pat_clear;                                          // 清 0
        pat_vline(400);                                     // 左轮廓
        pat_vline(402);                                     // 右轮廓
        golden_build;                                       // 黄金参考（这里用来对比"没连接"）
        cfg_en = 1'b0;                                      // ★ 关掉形态学
        send_frame;                                         // 发整帧
        idle(8);                                            // 收尾
        // ★ 三条断言：① 原始掩膜里中间列是空 ② 黄金参考里它被连上 ③ **RTL 在旁路下必须还是空**
        checks = checks + 3;                                // 三个用例
        if (pin[(3+1)*PW + (401+1)] !== 1'b0) begin         // 原始掩膜里中间列是空
            errors = errors + 1; $display("  FAIL  图案本身有问题：原始掩膜中间列不该是 1");
        end else if (pero[(3+1)*PW + (401+1)] !== 1'b1) begin   // 闭运算参考图里它是 1
            errors = errors + 1; $display("  FAIL  黄金参考有问题：闭运算后中间列该是 1");
        end else if (out_img[3*W + 401] !== 1'b0) begin     // ★ 旁路下 RTL 输出必须还是空
            errors = errors + 1;                            // 记错
            $display("  FAIL  旁路下 RTL 输出(3,401)=%b 期望=0 ⇒ 旁路没生效或旁路数据接错了",
                     out_img[3*W+401]);
        end else begin                                      // 三条全对
            $display("  ok    bypass works: raw(3,401)=0, closing-ref(3,401)=1, RTL-bypass(3,401)=0");
        end

        //=================================================================
        // ⑨ 中途插空拍：不许错位
        //=================================================================
        $display("-- 9 two lines + 2 idle beats injected mid-frame (no misalignment) --");
        pat_clear;                                          // 清 0
        pat_vline(700);                                     // 左轮廓
        pat_vline(702);                                     // 右轮廓
        golden_build;                                       // 黄金参考
        cfg_en = 1'b1;                                      // 重新打开闭运算
        for (r = 0; r < ROWS; r = r + 1) begin              // 逐行
            for (c = 0; c < W; c = c + 1) begin             // 逐列
                if (r == 5 && c == 400) idle(2);            // ★ 第 5 行中间插 2 拍空拍
                beat(1'b1, r, c,                            // 发这个像素
                     (r == 0) && (c == 0),                  // 帧首
                     (c == W-1),                            // 行尾
                     (r == ROWS-1) && (c == W-1));          // 帧尾
            end
        end
        idle(8);                                            // 收尾
        chk_cell("gap-air:mid", 4, 701, 1'b1);              // 空拍之后仍然连上了

        // ---- 汇总 ----
        $display("==== tb_dd_morph 结束：比对 %0d 次，错误 %0d 处 ====", checks, errors);
        if (errors == 0) $display("RESULT: PASS");
        else             $display("RESULT: FAIL");
        $finish;                                            // 结束仿真
    end

    //=====================================================================
    // 超时保护
    //=====================================================================
    initial begin
        #20000000;                                          // 20ms 上限（9 帧 × 7776 拍 ≈ 700us）
        $display("[ERR] 仿真超时，强制结束");
        $finish;
    end

endmodule
