//////////////////////////////////////////////////////////////////////////////
// tb_dd_win3x3.v
//
//   dd_win3x3（3×3 窗口生成器）的 testbench。
//   **故意不放进 Vivado 工程**（避免污染综合文件集），放在 PROJECT\tb\ 下单独跑。
//
//   --------------------------------------------------------------------
//   怎么验 —— 用"闭式图案"当黄金参考，而不是抄一遍 RTL
//   --------------------------------------------------------------------
//   像素值取一个**只跟 (行号, 列号) 有关**的解析式：
//       第 0 帧： pix(r,c) = (r × 32 + (c & 3)) & 0xFF      // 0..227
//       第 1 帧： pix(r,c) = ((7-r) × 32 + (c & 3)) & 0xFF  // 第 2 帧内容故意不同
//   这样窗口里 9 个数的**期望值可以直接算出来**（见 exp_win），
//   不需要在 tb 里再建一套行缓冲模型。
//   好处：RTL 和参考模型没有共同的代码，行/列/旋转只要错一个就必然对不上。
//
//   为什么两帧要用不同的图案：帧首 2 行是靠 out_valid 屏蔽掉的，
//   如果行缓冲里还残留上一帧的内容、而屏蔽又写错了，
//   用**同一个图案**是抓不出来的（残留值和正确值恰好一样）。
//   换成 (7-r) 之后，第 1 帧第 r 行和第 2 帧同一行的值必然不同 ⇒ 一错就露。
//
//   --------------------------------------------------------------------
//   时序约定（和 tb_defect_detect.v 一致）
//   --------------------------------------------------------------------
//       · 输入在 **posedge 之后 1ns** 驱动 —— 离下一个沿还有 9ns，绝不和沿抢
//       · 驱动前先查"2 拍前输入对应的期望输出"，因为本模块固定晚 2 拍
//         （第 1 级窗口寄存器 + 第 2 级输出寄存器，见 dd_win3x3.v 文件头）
//       · 每个用例都回头查上一条：out_valid 该 0 时必须 0（抓虚假 valid）
//
//   --------------------------------------------------------------------
//   覆盖的用例
//   --------------------------------------------------------------------
//       1) 正常两帧 × 8 行 × 972 列（走满一整行宽度，地址一直用到 971）
//       2) 帧首 2 行整行屏蔽（out_valid 必须为 0）
//       3) 行首 2 列屏蔽
//       4) 行间空拍（模拟消隐）—— 空拍必须不推进任何计数器
//       5) 行内空拍（第 0 帧第 3 行，第 100 / 500 列前各插 2 拍）
//       6) 第二帧帧首不能用到第一帧的行缓冲残留
//       7) out_sof 只落在本帧第一个有效窗口上；out_eol / out_eof 的位置
//
//   --------------------------------------------------------------------
//   注释规范（项目要求，2026-09-24）
//   --------------------------------------------------------------------
//       每一行有实际功能的代码，行尾都跟一条中文注释。
//       本文件以 **UTF-8（无 BOM）** 编码保存。
//////////////////////////////////////////////////////////////////////////////

`timescale 1ns / 1ps

module tb_dd_win3x3;

    //=====================================================================
    // 参数
    //=====================================================================
    localparam integer ROWS = 8;        // 每帧行数（≥3 才可能产生窗口；用 8 让 mod-4 轮转走两圈）
    localparam integer COLS = 972;      // 每行像素数（与真实图像一致）
    localparam integer GAPB = 2;        // 行间插入的空拍数（模拟行消隐）

    //=====================================================================
    // 时钟与复位
    //=====================================================================
    reg clk   = 1'b0;                   // 时钟初值 0
    reg rst_n = 1'b0;                   // 低有效复位，初值复位态

    always #5 clk = ~clk;               // 10ns 周期 = 100MHz

    //=====================================================================
    // DUT 端口
    //=====================================================================
    reg         in_valid = 1'b0;        // 输入 valid
    reg  [7:0]  in_pix   = 8'd0;        // 输入像素
    reg         in_sof   = 1'b0;        // 输入帧首
    reg         in_eol   = 1'b0;        // 输入行尾
    reg         in_eof   = 1'b0;        // 输入帧尾

    wire        out_valid;              // 输出 valid
    wire        out_sof, out_eol, out_eof;  // 输出 sideband
    wire [7:0]  w00, w01, w02;          // 上上行
    wire [7:0]  w10, w11, w12;          // 上一行（w11 = 中心）
    wire [7:0]  w20, w21, w22;          // 当前行

    dd_win3x3 dut (
        .clk       (clk),               // 100MHz
        .rst_n     (rst_n),             // 低有效复位
        .in_valid  (in_valid),          // …
        .in_pix    (in_pix),            // …
        .in_sof    (in_sof),            // …
        .in_eol    (in_eol),            // …
        .in_eof    (in_eof),            // …
        .out_valid (out_valid),         // …
        .out_sof   (out_sof),           // …
        .out_eol   (out_eol),           // …
        .out_eof   (out_eof),           // …
        .w00 (w00), .w01 (w01), .w02 (w02),     // 窗口第 0 行
        .w10 (w10), .w11 (w11), .w12 (w12),     // 窗口第 1 行
        .w20 (w20), .w21 (w21), .w22 (w22)      // 窗口第 2 行
    );

    //=====================================================================
    // 激励用的状态
    //=====================================================================
    integer cur_frame = 0;              // 当前发的是第几帧（决定用哪套图案）
    integer checks    = 0;              // 比对次数
    integer errors    = 0;              // 错误次数

    reg        pv_v = 1'b0;             // 1 拍前输入：是否有效
    integer    pv_r = 0;                // 1 拍前输入：行号
    integer    pv_c = 0;                // 1 拍前输入：列号
    integer    pv_f = 0;                // 1 拍前输入：属于第几帧
    reg        p2_v = 1'b0;             // ★ 2 拍前输入：是否有效（本模块延迟 2 拍，比对要用这一组）
    integer    p2_r = 0;                // ★ 2 拍前输入：行号
    integer    p2_c = 0;                // ★ 2 拍前输入：列号
    integer    p2_f = 0;                // ★ 2 拍前输入：属于第几帧

    //=====================================================================
    // 图案函数：像素值只跟 (帧号, 行号, 列号) 有关，闭式可算
    //
    //   ★ 帧号必须当参数传进来，不能读全局 cur_frame：
    //     第 0 帧**最后一个像素**的期望输出，是在"第 1 帧循环"的第一拍才比对的，
    //     那时全局 cur_frame 早已被切成 1 ⇒ 期望值会用错图案。
    //     （这个坑就是本 testbench 自己踩出来的：RTL 是对的，tb 报了一个假错。）
    //=====================================================================
    function [7:0] pat (input integer ff, input integer rr, input integer cc);
        begin
            if (ff == 0)                                    // 第 0 帧
                pat = (rr * 32 + (cc & 3)) & 8'hFF;         // 行号 ×32 做粗区分，列号低 2 位做细区分
            else                                            // 第 1 帧
                pat = ((7 - rr) * 32 + (cc & 3)) & 8'hFF;   // 故意换成 (7-r)，与第 0 帧同一行的值必然不同
        end
    endfunction

    //=====================================================================
    // 期望窗口函数：给定窗口中心的坐标，算出 9 个期望值
    //   用的是"闭式图案"，不是在 tb 里重建行缓冲 —— 参考模型和 RTL 无共同代码
    //=====================================================================
    task exp_win (input integer ff, input integer rr, input integer cc,
                  output [7:0] e00, output [7:0] e01, output [7:0] e02,
                  output [7:0] e10, output [7:0] e11, output [7:0] e12,
                  output [7:0] e20, output [7:0] e21, output [7:0] e22);
        begin
            // 窗口中心是 (rr, cc)：行从 rr-1 到 rr+1，列从 cc-1 到 cc+1
            e00 = pat(ff, rr-1, cc-1);  e01 = pat(ff, rr-1, cc);  e02 = pat(ff, rr-1, cc+1);   // 上上行
            e10 = pat(ff, rr  , cc-1);  e11 = pat(ff, rr  , cc);  e12 = pat(ff, rr  , cc+1);   // 上一行（中间那行）
            e20 = pat(ff, rr+1, cc-1);  e21 = pat(ff, rr+1, cc);  e22 = pat(ff, rr+1, cc+1);   // 当前行
        end
    endtask

    //=====================================================================
    // 检查：本拍输出应当等于"**2 拍前**输入像素对应的窗口"
    //
    //   ★ 本模块延迟 2 拍（第 1 级窗口寄存器 + 第 2 级输出寄存器）
    //   DUT 输出的窗口中心 = (2 拍前的行号 - 1, 2 拍前的列号 - 1)
    //   即：2 拍前输入是 (r, c) 时，本拍输出的窗口中心是 (r-1, c-1)。
    //=====================================================================
    task check_prev;
        reg        e_ok, e_sof, e_eol, e_eof;       // 期望的四根 sideband
        reg [7:0]  e00,e01,e02,e10,e11,e12,e20,e21,e22; // 期望的 9 个窗口值
        reg        bad;                             // 本拍是否出错
        begin
            checks = checks + 1;                    // 累计比对次数

            // 有完整 3×3 邻域的条件：2 拍前有效，且行号 ≥2、列号 ≥2
            e_ok  = p2_v && (p2_r >= 2) && (p2_c >= 2);
            e_sof = p2_v && (p2_r == 2) && (p2_c == 2);                 // 本帧第一个窗口
            e_eol = e_ok && (p2_c == COLS-1);                           // 本行最后一个窗口
            e_eof = e_ok && (p2_r == ROWS-1) && (p2_c == COLS-1);       // 本帧最后一个窗口

            // 先把期望窗口算出来（中心 = 2 拍前输入的左上角）
            exp_win(p2_f, p2_r-1, p2_c-1, e00,e01,e02, e10,e11,e12, e20,e21,e22);

            bad = 1'b0;                             // 先假设没错

            if (out_valid !== e_ok) begin           // ① 查 valid
                bad = 1'b1;
                $display("[ERR] t=%0t out_valid=%b 期望=%b  (2拍前 r=%0d c=%0d v=%b)",
                         $time, out_valid, e_ok, p2_r, p2_c, p2_v);
            end
            if (out_sof !== e_sof) begin            // ② 查帧首
                bad = 1'b1;
                $display("[ERR] t=%0t out_sof=%b 期望=%b  (2拍前 r=%0d c=%0d)",
                         $time, out_sof, e_sof, p2_r, p2_c);
            end
            if (out_eol !== e_eol) begin            // ③ 查行尾
                bad = 1'b1;
                $display("[ERR] t=%0t out_eol=%b 期望=%b  (2拍前 r=%0d c=%0d)",
                         $time, out_eol, e_eol, p2_r, p2_c);
            end
            if (out_eof !== e_eof) begin            // ④ 查帧尾
                bad = 1'b1;
                $display("[ERR] t=%0t out_eof=%b 期望=%b  (2拍前 r=%0d c=%0d)",
                         $time, out_eof, e_eof, p2_r, p2_c);
            end

            if (e_ok) begin                         // ⑤ 只有窗口有效时才查 9 个数值
                if (w00 !== e00 || w01 !== e01 || w02 !== e02 ||
                    w10 !== e10 || w11 !== e11 || w12 !== e12 ||
                    w20 !== e20 || w21 !== e21 || w22 !== e22) begin
                    bad = 1'b1;
                    $display("[ERR] t=%0t 窗口不符 (中心 r=%0d c=%0d)", $time, p2_r-1, p2_c-1);
                    $display("      实际 w00..w22 = %0d %0d %0d / %0d %0d %0d / %0d %0d %0d",
                             w00,w01,w02,w10,w11,w12,w20,w21,w22);
                    $display("      期望 w00..w22 = %0d %0d %0d / %0d %0d %0d / %0d %0d %0d",
                             e00,e01,e02,e10,e11,e12,e20,e21,e22);
                end
            end

            if (bad) errors = errors + 1;           // 记一次错（每拍最多记一次）
        end
    endtask

    //=====================================================================
    // 驱动：发一个有效像素
    //   在 posedge 之后 1ns 驱动；驱动前先查"2 拍前"的期望
    //=====================================================================
    task send_pix (input integer rr, input integer cc);
        begin
            @(posedge clk); #1;                                 // 对齐到本拍起点
            check_prev();                                       // 先查 2 拍前的期望输出
            in_valid = 1'b1;                                    // 本拍有像素
            in_pix   = pat(cur_frame, rr, cc);                  // 按图案给值（帧号显式传进去）
            in_sof   = (rr == 0) && (cc == 0);                  // 只在整帧第一个像素上拉高
            in_eol   = (cc == COLS-1);                          // 每行最后一个像素
            in_eof   = (rr == ROWS-1) && (cc == COLS-1);        // 整帧最后一个像素
            p2_v = pv_v; p2_r = pv_r; p2_c = pv_c; p2_f = pv_f;  // ★ 1 拍前顺移成 2 拍前
            pv_v = 1'b1; pv_r = rr; pv_c = cc; pv_f = cur_frame;// 记住本拍（含帧号），供下一拍顺移
        end
    endtask

    //=====================================================================
    // 驱动：发一个空拍（valid=0，模拟反压/消隐）
    //=====================================================================
    task send_gap;
        begin
            @(posedge clk); #1;                                 // 对齐到本拍起点
            check_prev();                                       // 先查 2 拍前的期望输出
            in_valid = 1'b0;                                    // 本拍没有像素
            in_pix   = 8'd0;                                    // 数据线给 0（无所谓）
            in_sof   = 1'b0; in_eol = 1'b0; in_eof = 1'b0;      // sideband 全部拉低（真实流就是这样限定的）
            p2_v = pv_v; p2_r = pv_r; p2_c = pv_c; p2_f = pv_f;  // ★ 1 拍前顺移成 2 拍前
            pv_v = 1'b0;                                        // 本拍无效 ⇒ 2 拍后期望 out_valid = 0
        end
    endtask

    //=====================================================================
    // 主激励
    //=====================================================================
    integer fr, r, c, k;                // 循环变量

    initial begin
        $display("==== tb_dd_win3x3 开始 ====");

        // ---- 复位 ----
        rst_n = 1'b0;                                       // 拉低复位
        repeat (5) @(negedge clk);                          // 保持 5 拍
        rst_n = 1'b1;                                       // 释放复位

        // ---- 发两帧 ----
        for (fr = 0; fr < 2; fr = fr + 1) begin             // 第 0 帧、第 1 帧
            cur_frame = fr;                                 // 切换图案
            for (r = 0; r < ROWS; r = r + 1) begin          // 逐行
                if (r != 0) begin                           // 非首行前面插行间空拍
                    for (k = 0; k < GAPB; k = k + 1) send_gap();   // 模拟消隐
                end
                for (c = 0; c < COLS; c = c + 1) begin      // 逐列
                    if (fr == 0 && r == 3 && (c == 100 || c == 500)) begin
                        send_gap();                         // ★ 行内空拍用例：第 0 帧第 3 行
                        send_gap();                         //    在 100 列 / 500 列前各插 2 拍
                    end
                    send_pix(r, c);                         // 发一个像素
                end
            end
        end

        // ---- 收尾：再走 4 拍空拍，把流水线冲干净 ----
        for (k = 0; k < 4; k = k + 1) send_gap();           // 让最后几拍的结果也走完并被查过

        // ---- 汇总 ----
        $display("==== 比对 %0d 拍，错误 %0d 处 ====", checks, errors);
        if (errors == 0) $display("==== PASS：3x3 窗口全部正确 ====");
        else             $display("==== FAIL：见上面的 [ERR] ====");
        $finish;                                            // 结束仿真
    end

    //=====================================================================
    // 超时保护：万一程序卡死，也能退出，不会把 xsim 挂住
    //=====================================================================
    initial begin
        #5000000;                                           // 5ms 仿真时间上限（足够跑完）
        $display("[ERR] 仿真超时，强制结束");
        $finish;
    end

endmodule
