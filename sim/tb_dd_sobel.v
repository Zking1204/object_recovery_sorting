//////////////////////////////////////////////////////////////////////////////
// tb_dd_sobel.v
//
//   dd_sobel（Sobel 边缘检测，第③级支路 B）的 testbench。
//   **故意不放进 Vivado 工程**，放在 PROJECT\tb\ 下单独跑。
//
//   --------------------------------------------------------------------
//   怎么验 —— 黄金参考"按数学定义直接算"，和 RTL 的加法器树没有共同结构
//   --------------------------------------------------------------------
//   RTL 走的是"4 个加权和 → 差分 → 条件取负 → 相加 → 比较"这个**硬件结构**；
//   tb 的参考模型直接用 **32 位整数**按定义算：
//       Gx = (右列和) − (左列和)；Gy = (下行和) − (上行和)
//       mag = |Gx| + |Gy|；hit = mag > th
//   两者结构不同 ⇒ RTL 里任何一个**位宽溢出**、**取负写错**、**加错项**
//   都会立刻对不上。这正是本模块最值得守的两个点。
//
//   --------------------------------------------------------------------
//   ★ tb 故意用满 0..255（而实际灰度上限只有 246）
//   --------------------------------------------------------------------
//   实际 2:4:1 灰度的上限是 246。tb 故意喂到 255，是为了证明
//   **即使上游给了满量程，10/11 位的中间量仍然不溢出**：
//       加权和最大 = 255×4 = 1020 < 1024  ✓ 10 位够
//       Gx/Gy   最大 = ±1020             ✓ 11 位补码够
//       幅值    最大 = 1530 < 2048       ✓ 11 位够
//   ★ 幅值上限是 6V=1530 而**不是** 8V=2040：Gx 与 Gy 共用四角且符号相反，
//     互相抵消，拉不满。本 tb 曾把这个数写成 2040，是错在注释上的。
//   这是"位宽留了余量"的直接证据。
//
//   --------------------------------------------------------------------
//   覆盖的用例
//   --------------------------------------------------------------------
//       1) 均匀区域（梯度恒 0 ⇒ 不该命中）
//       2) ★ **1 像素宽的亮竖线**：窗口中心落在线上 ⇒ **不命中**；
//          中心落在线的左/右一侧 ⇒ **命中**（Sobel 报的是"边"，不是"线"）
//       3) ★ 同理的 1 像素宽亮横线（走 Gy）
//       4) 正反两个方向的梯度（专测"条件取负"那一段）
//       5) ★ 满量程极值（0 与 255 混排）⇒ 幅值打到 2040，测位宽上限
//       6) 阈值边界：mag == th ⇒ 不命中；mag == th+1 ⇒ 命中（判据是 `>` 不是 `>=`）
//       7) 3000 个伪随机窗口（0..255 全量程）
//       8) 随机插空拍（valid 断开）
//       9) ★ **帧中改阈值**：前一帧最后一个像素必须用**旧**值、帧首用**新**值
//      10) 支路使能关掉 ⇒ 恒不命中
//      11) 延迟必须**正好 3 拍**（与支路 A 逐拍对齐的前提）
//
//   --------------------------------------------------------------------
//   注释规范（项目要求，2026-09-24）
//   --------------------------------------------------------------------
//       每一行有实际功能的代码，行尾都跟一条中文注释。
//       本文件以 **UTF-8（无 BOM）** 编码保存。
//////////////////////////////////////////////////////////////////////////////

`timescale 1ns / 1ps

module tb_dd_sobel;

    //=====================================================================
    // 时钟与复位
    //=====================================================================
    reg clk   = 1'b0;                   // 时钟初值 0
    reg rst_n = 1'b0;                   // 低有效复位

    always #5 clk = ~clk;               // 10ns = 100MHz

    //=====================================================================
    // DUT 端口
    //=====================================================================
    reg  [7:0] x0,x1,x2,x3,x4,x5,x6,x7,x8;  // 本拍窗口的 9 个值（x4 = 中心 w11）
    reg        in_valid = 1'b0;             // 本拍窗口有效
    reg        in_sof = 1'b0;               // 帧首
    reg        in_eol = 1'b0;               // 行尾
    reg        in_eof = 1'b0;               // 帧尾
    reg        cfg_en = 1'b0;               // 支路使能（SOB_TH[0]）
    reg  [7:0] cfg_th = 8'd0;               // 梯度阈值（SOB_TH[15:8]）

    wire       out_valid;                   // 输出 valid
    wire       out_hit;                     // 输出命中（本像素判为边）
    wire       out_sof, out_eol, out_eof;   // 输出 sideband

    dd_sobel dut (
        .clk        (clk),                  // 100MHz
        .rst_n      (rst_n),                // 低有效复位
        .w00(x0), .w01(x1), .w02(x2),       // 窗口第 0 行
        .w10(x3), .w11(x4), .w12(x5),       // 窗口第 1 行（x4 = 中心，Sobel 不用它）
        .w20(x6), .w21(x7), .w22(x8),       // 窗口第 2 行
        .in_valid   (in_valid),             // …
        .in_sof     (in_sof),               // …
        .in_eol     (in_eol),               // …
        .in_eof     (in_eof),               // …
        .cfg_en     (cfg_en),               // 支路使能
        .cfg_th     (cfg_th),               // 梯度阈值
        .out_valid  (out_valid),            // …
        .out_hit    (out_hit),              // …
        .out_sof    (out_sof),              // …
        .out_eol    (out_eol),              // …
        .out_eof    (out_eof)               // …
    );

    //=====================================================================
    // 历史环形缓冲（4 深）：记下每一拍"期望的输出"，3 拍后拿来比对
    //   本模块延迟 3 拍 ⇒ 第 k 拍查的是第 k-3 拍记下的槽位，
    //   即槽位 (k-3) mod 4 = (k+1) mod 4。
    //=====================================================================
    reg       h_val [0:3];              // 该拍是否应当有有效输出
    reg       h_hit [0:3];              // 该拍期望的 hit
    reg       h_sof [0:3];              // 该拍期望的 sof
    reg       h_eol [0:3];              // 该拍期望的 eol
    reg       h_eof [0:3];              // 该拍期望的 eof

    integer   cyc    = 0;               // 已发出的输入拍数
    integer   checks = 0;               // 比对次数
    integer   errors = 0;               // 错误次数

    reg       en_eff = 1'b0;            // tb 侧模拟"帧首锁存"后本帧实际生效的使能
    reg [7:0] th_eff = 8'd0;            // tb 侧模拟"帧首锁存"后本帧实际生效的阈值

    //=====================================================================
    // LFSR 伪随机数（16 位最大长度，抽头 16/14/13/11）
    //   ★ Verilog 要求函数至少有一个入参，所以留一个不用的占位参数。
    //=====================================================================
    reg [15:0] lfsr = 16'hACE1;         // 非零种子

    function [7:0] rnd (input integer dummy);
        begin
            lfsr = {lfsr[14:0], lfsr[15] ^ lfsr[13] ^ lfsr[12] ^ lfsr[10]};  // 推进一拍 LFSR
            rnd  = lfsr[7:0];                                                   // 取低 8 位
        end
    endfunction

    //=====================================================================
    // 黄金参考：**按数学定义**用 32 位整数直接算
    //   ★ 刻意不抄 RTL 的加法器树结构 —— 这样位宽/取负写错才会暴露
    // ====================================================================
    task golden (input [7:0] a0,a1,a2,a3,a4,a5,a6,a7,a8,
                 output integer gx_o, output integer gy_o,
                 output integer mag_o, output reg eh);
        integer gx, gy, ax, ay;
        begin
            gx  = (a2 + 2*a5 + a8) - (a0 + 2*a3 + a6);   // Gx = 右列加权和 − 左列加权和
            gy  = (a6 + 2*a7 + a8) - (a0 + 2*a1 + a2);   // Gy = 下行加权和 − 上行加权和
            ax  = (gx < 0) ? -gx : gx;                    // |Gx|（直接在整数域取绝对值）
            ay  = (gy < 0) ? -gy : gy;                    // |Gy|
            mag_o = ax + ay;                              // L1 范数幅值
            gx_o  = gx;                                   // 回传原始 Gx（供打印）
            gy_o  = gy;                                   // 回传原始 Gy
            eh    = en_eff & (mag_o > th_eff);            // 与"本帧生效"的阈值比较（判据是 >）
        end
    endtask

    //=====================================================================
    // 发一拍 + 比对 3 拍前的期望
    //=====================================================================
    task beat (input v, input [7:0] a0,a1,a2,a3,a4,a5,a6,a7,a8,
               input s, input e, input f);
        integer   sc, sn;               // 比对槽位 / 记录槽位
        integer   gx, gy, mag;          // 黄金参考算出的中间量
        reg       eh;                   // 黄金参考算出的期望命中
        begin
            @(posedge clk); #1;                             // 对齐到本拍起点

            // ---------- 1) 先比对"3 拍前那一拍"的期望 ----------
            sc = (cyc + 1) % 4;                             // 3 拍前那一拍所在的环形槽位
            if (h_val[sc]) begin                            // 只在该拍应当有有效输出时才查
                checks = checks + 1;                        // 累计比对次数
                if (out_hit !== h_hit[sc]) begin            // 逐像素比对命中
                    errors = errors + 1;                    // 记错
                    $display("[ERR] t=%0t out_hit=%b 期望=%b", $time, out_hit, h_hit[sc]);
                end
            end
            // ★ valid 与三条 sideband 必须逐拍对齐（不能只对 hit）
            if (out_valid !== h_val[sc]) begin              // valid 错位 = 整条流水线错位
                errors = errors + 1;                        // 记错
                $display("[ERR] t=%0t out_valid=%b 期望=%b", $time, out_valid, h_val[sc]);
            end
            if (out_sof !== h_sof[sc]) begin                // sof 错位 = 下游控制全乱
                errors = errors + 1;                        // 记错
                $display("[ERR] t=%0t out_sof=%b 期望=%b", $time, out_sof, h_sof[sc]);
            end
            if (out_eol !== h_eol[sc]) begin                // eol 错位 = 行计数全乱
                errors = errors + 1;                        // 记错
                $display("[ERR] t=%0t out_eol=%b 期望=%b", $time, out_eol, h_eol[sc]);
            end
            if (out_eof !== h_eof[sc]) begin                // eof 错位 = 帧计数全乱
                errors = errors + 1;                        // 记错
                $display("[ERR] t=%0t out_eof=%b 期望=%b", $time, out_eof, h_eof[sc]);
            end

            // ---------- 2) 驱动本拍 ----------
            x0=a0; x1=a1; x2=a2; x3=a3; x4=a4;              // 窗口第 0、1 行的 5 个值
            x5=a5; x6=a6; x7=a7; x8=a8;                     // 窗口剩下的 4 个值
            in_valid = v;                                   // 本拍 valid
            in_sof   = s;                                   // 本拍帧首
            in_eol   = e;                                   // 本拍行尾
            in_eof   = f;                                   // 本拍帧尾

            // ---------- 3) 算本拍的期望，记进环形缓冲 ----------
            if (v && s) begin                               // 帧首锁存：本帧用新参数
                en_eff = cfg_en;                            // ★ 使能
                th_eff = cfg_th;                            // ★ 阈值
            end
            golden(a0,a1,a2,a3,a4,a5,a6,a7,a8, gx,gy,mag,eh);   // 按定义算期望

            sn = cyc % 4;                                   // 本拍写进的环形槽位
            h_val[sn] = v;                                  // 记下本拍是否应有有效输出
            h_hit[sn] = eh;                                 // 记下本拍期望的命中
            h_sof[sn] = s;                                  // 记下本拍期望的 sof
            h_eol[sn] = e;                                  // 记下本拍期望的 eol
            h_eof[sn] = f;                                  // 记下本拍期望的 eof
            cyc = cyc + 1;                                  // 拍数 +1
        end
    endtask

    //=====================================================================
    // 发一个空拍（valid=0，9 个值随便给 0）
    //=====================================================================
    task gap;
        begin
            beat(1'b0, 8'd0,8'd0,8'd0,8'd0,8'd0,8'd0,8'd0,8'd0,8'd0, 1'b0, 1'b0, 1'b0);
        end
    endtask

    //=====================================================================
    // 定向用例：发一个窗口并把"期望的 Gx/Gy/幅值"打印出来（人眼可核对）
    //   ★ s = 1 表示这一拍同时是**帧首** —— 参数只在帧首锁存，
    //     所以每一帧的**第一个**用例必须带 s=1，否则整帧用的还是复位值。
    //   ★ 这里**不收中文标签**：中文一律由调用点的 $display 字面量打印。
    //     原因是把中文塞进宽 reg 再走 %0s 打印会被工具串成乱码（已实测），
    //     而字面量打印是干净的。
    // ====================================================================
    task case1 (input [7:0] a0,a1,a2,a3,a4,a5,a6,a7,a8, input s);
        integer gx, gy, mag;            // 黄金参考中间量
        reg     eh;                     // 期望命中
        begin
            if (s) begin                                    // 若是帧首，先把 tb 侧参数同步好
                en_eff = cfg_en;                            // ★ 使能随帧首锁存
                th_eff = cfg_th;                            // ★ 阈值随帧首锁存
            end
            golden(a0,a1,a2,a3,a4,a5,a6,a7,a8, gx,gy,mag,eh);   // 按定义算期望
            $display("       Gx=%6d Gy=%6d mag=%6d  期望命中=%b", gx, gy, mag, eh);
            beat(1'b1, a0,a1,a2,a3,a4,a5,a6,a7,a8, s, 1'b0, 1'b0);   // 发出去
        end
    endtask

    //=====================================================================
    // 主激励
    //=====================================================================
    integer i, n;                       // 循环变量

    initial begin
        $display("==== tb_dd_sobel 开始 ====");

        for (i = 0; i < 4; i = i + 1) begin                 // 初始化环形缓冲
            h_val[i] = 1'b0; h_hit[i] = 1'b0;               // 期望全 0（复位后正好对上）
            h_sof[i] = 1'b0; h_eol[i] = 1'b0; h_eof[i] = 1'b0;   // sideband 也全 0
        end

        rst_n = 1'b0;                                       // 拉低复位
        repeat (5) @(negedge clk);                          // 保持 5 拍
        rst_n = 1'b1;                                       // 释放复位

        //=================================================================
        // 第 0 帧：定向用例
        //=================================================================
        cfg_en = 1'b1;                                      // 支路使能打开
        cfg_th = 8'd100;                                    // 阈值 100
        en_eff = 1'b1; th_eff = 8'd100;                     // tb 侧同步（帧首那一拍还没发，先手动置上）

        $display("-- 定向用例（阈值=%0d）--", cfg_th);
        // ① 均匀区域：所有值相同 ⇒ Gx=Gy=0 ⇒ 不命中
        //    ★ 这一拍同时是**帧首** ⇒ 参数（使能/阈值）在这里才被锁存
        $display("  ① 均匀区域（9 个值都是 100）⇒ 梯度恒 0 ⇒ 不命中");
        case1(100,100,100,100,100,100,100,100,100, 1'b1);
        // ② 1像素宽亮竖线 · 窗口中心**落在线上**（中间列亮 200，左右列暗 30）
        //    Gx 的核里中间列权重是 0 ⇒ 梯度为 0 ⇒ **不该命中**
        $display("  ② 1px 亮竖线 · 中心落在线上 ⇒ Sobel 核中间列权重为 0 ⇒ 不命中");
        case1(30,200,30, 30,200,30, 30,200,30, 1'b0);
        // ③ 同一条竖线 · 窗口中心落在**线的左侧**（右列才是亮线）
        //    Gx = (200+400+200) - (30+60+30) = 680 ⇒ 命中
        $display("  ③ 同一条竖线 · 中心落在线的左侧 ⇒ Gx=+680 ⇒ 命中");
        case1(30,30,200, 30,30,200, 30,30,200, 1'b0);
        // ④ 同一条竖线 · 窗口中心落在**线的右侧**（左列是亮线）⇒ Gx = -680 ⇒ 靠取负命中
        $display("  ④ 同一条竖线 · 中心落在线的右侧 ⇒ Gx=-680 ⇒ 靠条件取负命中");
        case1(200,30,30, 200,30,30, 200,30,30, 1'b0);
        // ⑤ 1像素宽亮横线 · 中心落在线上（中间行亮）⇒ Gy 的核里中间行权重 0 ⇒ 不命中
        $display("  ⑤ 1px 亮横线 · 中心落在线上 ⇒ Sobel 核中间行权重为 0 ⇒ 不命中");
        case1(30,30,30, 200,200,200, 30,30,30, 1'b0);
        // ⑥ 同一条横线 · 中心落在线的上方（下行是亮线）⇒ Gy = 680 ⇒ 命中
        $display("  ⑥ 同一条横线 · 中心落在线的上方 ⇒ Gy=+680 ⇒ 命中");
        case1(30,30,30, 30,30,30, 200,200,200, 1'b0);
        // ⑦ 满量程 · **单轴拉满**：左列全 0、右列全 255 ⇒ Gx = 1020 = 4V
        //    （这是 |Gx| 的上限，验证 11 位补码够用且符号处理正确）
        $display("  ⑦ 满量程 · 单轴拉满 |Gx|=1020=4V（列上限，验证 11 位补码）");
        case1(0,0,255, 0,0,255, 0,0,255, 1'b0);
        // ⑧ 满量程 · **幅值拉满**：a0=a1=a3=255，其余 0 ⇒ Gx = Gy = -765 ⇒ mag = 1530
        //    （这是 |Gx|+|Gy| 的上限 6V，位宽上限的唯一真值，见文件头推导）
        $display("  ⑧ 满量程 · 幅值拉满 mag=1530=6V（L1 上限，验证 11 位不溢出）");
        case1(255,255,0, 255,0,0, 0,0,0, 1'b0);
        // ⑨ 阈值边界：mag 恰好等于 100 ⇒ 判据是 `>` 而不是 `>=` ⇒ **不命中**
        $display("  ⑨ 阈值边界：mag 恰好等于阈值 100 ⇒ 判据是 > 不是 >= ⇒ 不命中");
        case1(30,30,55, 30,30,55, 30,30,55, 1'b0);
        // ⑩ 刚过阈值：mag = 102（幅值恒为偶数，101 取不到）⇒ 命中
        $display("  ⑩ 刚过阈值：mag=102（幅值恒为偶数，取不到 101）⇒ 命中");
        case1(30,30,111, 30,30,0, 30,30,111, 1'b0);

        //=================================================================
        // 空拍用例：空拍必须原样流过去、不错位
        //=================================================================
        $display("  ⑪ 空拍用例");
        gap();                                              // 单个空拍
        gap(); gap();                                       // 连续两个空拍
        $display("  ⑫ 空拍之后仍正确（连着 3 个空拍再发一个应有的命中）");
        case1(30,30,200, 30,30,200, 30,30,200, 1'b0);

        //=================================================================
        // 第 1 帧：3000 个伪随机窗口（0..255 全量程），随机插空拍
        //=================================================================
        for (n = 0; n < 3000; n = n + 1) begin              // 逐个随机窗口
            beat(1'b1,                                      // 有效
                 rnd(0),rnd(0),rnd(0),rnd(0),rnd(0),        // 9 个随机灰度（0..255）
                 rnd(0),rnd(0),rnd(0),rnd(0),               // …
                 (n == 0),                                  // 第一个是帧首
                 (n % 20 == 19),                            // 每 20 个一个行尾
                 (n == 2999));                              // 最后一个是帧尾
            if (rnd(0) < 8'd40) gap();                          // 约 15% 概率插一个空拍
        end

        //=================================================================
        // ★ 帧中改阈值：只到下一帧才生效
        //   这一段专门守"参数对齐"那条 —— 直接拿 th_cur 去比的话，
        //   前一帧最后一个像素会用上新阈值，这里立刻报错。
        //=================================================================
        $display("-- 帧中改阈值（前 50 个用 100，后 50 个仍应用 100，换帧后才用 30）--");
        cfg_th = 8'd100;                                    // 帧首先用 100
        for (n = 0; n < 50; n = n + 1) begin                // 前 50 个
            beat(1'b1, rnd(0),rnd(0),rnd(0),rnd(0),rnd(0),  // 随机窗口
                 rnd(0),rnd(0),rnd(0),rnd(0),               // …
                 (n == 0), 1'b0, 1'b0);                     // 第 0 个带帧首
        end
        cfg_th = 8'd30;                                     // ★ 帧中改成 30
        for (n = 50; n < 100; n = n + 1) begin              // 这 50 个**仍应走旧阈值 100**
            beat(1'b1, rnd(0),rnd(0),rnd(0),rnd(0),rnd(0),  // 随机窗口
                 rnd(0),rnd(0),rnd(0),rnd(0),               // …
                 1'b0, 1'b0, 1'b0);                         // 注意：没有帧首
        end
        for (n = 0; n < 50; n = n + 1) begin                // 新的一帧 ⇒ 这才切到 30
            beat(1'b1, rnd(0),rnd(0),rnd(0),rnd(0),rnd(0),  // 随机窗口
                 rnd(0),rnd(0),rnd(0),rnd(0),               // …
                 (n == 0), 1'b0, (n == 49));                // 第 0 个带帧首 ⇒ 阈值在这里才更新
        end

        //=================================================================
        // 支路使能关掉 ⇒ 恒不命中
        //=================================================================
        $display("-- 支路使能关掉 --");
        cfg_en = 1'b0;                                      // ★ 关掉整条支路
        for (n = 0; n < 30; n = n + 1) begin                // 继续发随机窗口
            beat(1'b1, rnd(0),rnd(0),rnd(0),rnd(0),rnd(0),  // 随机窗口
                 rnd(0),rnd(0),rnd(0),rnd(0),               // …
                 (n == 0), 1'b0, (n == 29));                // 第 0 个带帧首 ⇒ 使能在帧首锁存为 0
        end

        //=================================================================
        // 收尾：多走几拍空拍，把流水线里最后 3 拍冲出来
        //=================================================================
        for (i = 0; i < 6; i = i + 1) gap();                // 冲干净流水线

        $display("==== 比对 %0d 拍，错误 %0d 处 ====", checks, errors);
        if (errors == 0) $display("==== PASS：Sobel 梯度与阈值判定全部正确 ====");
        else             $display("==== FAIL：见上面的 [ERR] ====");
        $finish;                                            // 结束仿真
    end

    //=====================================================================
    // 超时保护
    //=====================================================================
    initial begin
        #5000000;                                           // 5ms 上限
        $display("[ERR] 仿真超时，强制结束");
        $finish;
    end

