//////////////////////////////////////////////////////////////////////////////
// tb_dd_shadow.v  ——  dd_shadow 的自检 testbench（严格逐项比对）
//
//   【这个 TB 要证明什么】
//     ① 色度不变 + 变暗 + 暗度有上限，三条同时成立 ⇒ 判为阴影、亮度项被抹平
//     ② 三条里任意一条不成立 ⇒ 不判阴影，照旧按 |ΔY| 报（功能不退化）
//     ③ 等亮度但异色的物体（灰度差分永远抓不到的那一类）也能被色度项抓到
//     ④ cfg_sh_en = 0 时逐像素退回旧的 |ΔY| 行为（安全阀有效）
//     ⑤ cfg_en = 0 时输出恒 0
//
//   【判据（每个用例）】
//     A) dbg_shadow 必须**严格等于**期望值
//     B) score 必须落在期望区间内
//     C) 用例 1 精确断言 score == 0；用例 9（旁路）精确断言 score == 16
//
//   【时序】1 级喂数据 → 4 拍流水 → 第 4 个 posedge 后输出更新 → negedge 采样
//
//   本文件以 UTF-8（无 BOM）保存；自研代码逐行中文注释。
//////////////////////////////////////////////////////////////////////////////
`timescale 1ns / 1ps

module tb_dd_shadow;

    //=====================================================================
    // 时钟：100MHz（10ns）
    //=====================================================================
    reg clk = 1'b0;                                 // 初始 0
    always #5 clk = ~clk;                           // 每 5ns 翻转 ⇒ 周期 10ns

    //=====================================================================
    // DUT 接口信号
    //=====================================================================
    reg         rst_n    = 1'b0;                    // 复位（低有效）

    reg         a_valid  = 1'b0;                    // A 路有效
    reg  [23:0] a_pix    = 24'd0;                   // A 路彩色像素
    reg         a_sof    = 1'b0;                    // A 路帧首
    reg         a_eol    = 1'b0;                    // A 路行尾
    reg         a_eof    = 1'b0;                    // A 路帧尾

    reg         b_valid  = 1'b0;                    // B 路有效
    reg  [23:0] b_pix    = 24'd0;                   // B 路彩色像素

    reg         cfg_en     = 1'b0;                  // 检测总使能
    reg         cfg_sh_en  = 1'b0;                  // 阴影判据使能
    reg  [3:0]  cfg_wy     = 4'd1;                  // 亮度权重 wY
    reg  [3:0]  cfg_wc     = 4'd2;                  // 色度权重 wC
    reg  [7:0]  cfg_alpha  = 8'd128;                // αmin = 0.5
    reg  [7:0]  cfg_tau    = 8'd10;                 // 色度阈值 τc

    wire        out_valid, out_sof, out_eol, out_eof;   // 主输出 sideband
    wire [7:0]  out_pix;                                // score
    wire [7:0]  dbg_ya, dbg_dy, dbg_dc;                 // 调试量
    wire        dbg_shadow;                             // 阴影标记
    wire [23:0] dbg_bgc;                                // 背景彩色

    dd_shadow u_dut (
        .clk        (clk),                          // 100MHz
        .rst_n      (rst_n),                        // 低有效复位
        .a_valid    (a_valid),                      // A 路有效
        .a_pix      (a_pix),                        // A 路 24 位彩色
        .a_sof      (a_sof),                        // A 路帧首
        .a_eol      (a_eol),                        // A 路行尾
        .a_eof      (a_eof),                        // A 路帧尾
        .b_valid    (b_valid),                      // B 路有效
        .b_pix      (b_pix),                        // B 路 24 位彩色
        .cfg_en     (cfg_en),                       // 检测总使能
        .cfg_sh_en  (cfg_sh_en),                    // 阴影判据使能
        .cfg_wy     (cfg_wy),                       // 亮度权重
        .cfg_wc     (cfg_wc),                       // 色度权重
        .cfg_alpha  (cfg_alpha),                    // αmin
        .cfg_tau    (cfg_tau),                      // 色度阈值
        .out_valid  (out_valid),                    // 输出有效
        .out_pix    (out_pix),                      // score
        .out_sof    (out_sof),                      // 帧首
        .out_eol    (out_eol),                      // 行尾
        .out_eof    (out_eof),                      // 帧尾
        .dbg_ya     (dbg_ya),                       // Y_A
        .dbg_dy     (dbg_dy),                       // |ΔY|
        .dbg_dc     (dbg_dc),                       // 色度差
        .dbg_shadow (dbg_shadow),                   // 阴影标记
        .dbg_bgc    (dbg_bgc)                       // 背景彩色
    );

    //=====================================================================
    // 检查计数器
    //=====================================================================
    integer n_chk  = 0;                             // 总检查条数
    integer n_fail = 0;                             // 失败条数

    //---------------------------------------------------------------------
    // chk_shadow：阴影标志严格比对
    //---------------------------------------------------------------------
    task chk_shadow;
        input              exp;                     // 期望的阴影标志
        input [255:0]      name;                    // 用例名
        begin
            n_chk = n_chk + 1;                      // 计数
            if (dbg_shadow !== exp) begin           // 严格比较（含 x/z）
                n_fail = n_fail + 1;                // 记一次失败
                $display("  FAIL [%0s] shadow: got=%b want=%b | ya=%0d dy=%0d dc=%0d score=%0d",
                         name, dbg_shadow, exp, dbg_ya, dbg_dy, dbg_dc, out_pix);
            end
        end
    endtask

    //---------------------------------------------------------------------
    // chk_range：score 区间比对
    //---------------------------------------------------------------------
    task chk_range;
        input [7:0]        lo, hi;                  // 期望区间 [lo, hi]
        input [255:0]      name;                    // 用例名
        begin
            n_chk = n_chk + 1;                      // 计数
            if (out_pix < lo || out_pix > hi) begin // 越界即失败
                n_fail = n_fail + 1;                // 记一次失败
                $display("  FAIL [%0s] score: got=%0d want [%0d..%0d] | ya=%0d dy=%0d dc=%0d sh=%b",
                         name, out_pix, lo, hi, dbg_ya, dbg_dy, dbg_dc, dbg_shadow);
            end
        end
    endtask

    //---------------------------------------------------------------------
    // chk_eq：score 精确比对
    //---------------------------------------------------------------------
    task chk_eq;
        input [7:0]        exp;                     // 期望的 score
        input [255:0]      name;                    // 用例名
        begin
            n_chk = n_chk + 1;                      // 计数
            if (out_pix !== exp) begin              // 严格比较
                n_fail = n_fail + 1;                // 记一次失败
                $display("  FAIL [%0s] score: got=%0d want=%0d | ya=%0d dy=%0d dc=%0d sh=%b",
                         name, out_pix, exp, dbg_ya, dbg_dy, dbg_dc, dbg_shadow);
            end
        end
    endtask

    //---------------------------------------------------------------------
    // run：喂 1 拍 A/B 数据，等 4 拍流水出结果
    //---------------------------------------------------------------------
    task run;
        input [23:0]       av;                      // A 像素
        input [23:0]       bv;                      // B 像素
        begin
            @(negedge clk);                         // 在负沿驱动，避开正沿竞争
            a_valid <= 1'b1;                        // A 有效
            a_pix   <= av;                          // A 数据
            b_valid <= 1'b1;                        // B 有效
            b_pix   <= bv;                          // B 数据
            @(negedge clk);                         // 下一拍
            a_valid <= 1'b0;                        // 只喂一帧一拍
            b_valid <= 1'b0;                        // …
            a_pix   <= 24'd0;                       // ★ 数据也要清零：否则"输入一直保持"
            b_pix   <= 24'd0;                       //   会掩盖 sideband 错位，让错误的实现看起来是对的
            repeat (4) @(posedge clk);              // ★ 5 级流水：第 1 拍进级1，第 5 拍出级5
                                                    //   ⇒ 有效那拍在"第 4 个 posedge 之后"才在输出级站住，
                                                    //     再等一拍就被 valid 门控清零了（TB 晚一拍采样会看到 0）
            @(negedge clk);                         // 负沿采样（稳定）
        end
    endtask

    //=====================================================================
    // 测试主流程
    //=====================================================================
    initial begin
        $display("==================== tb_dd_shadow 开始 ====================");

        // ---- 复位 ----
        rst_n = 1'b0;                               // 复位有效
        repeat (3) @(posedge clk);                  // 保持 3 拍
        @(negedge clk);
        rst_n = 1'b1;                               // 释放复位

        // ---- 公共配置：wY=1, wC=2, τc=10, αmin=128(=0.5) ----
        cfg_wy    = 4'd1;                           // 亮度权重 1
        cfg_wc    = 4'd2;                           // 色度权重 2
        cfg_tau   = 8'd10;                          // 色度阈值 10（量化下限 8）
        cfg_alpha = 8'd128;                         // αmin = 0.5
        cfg_sh_en = 1'b1;                           // 阴影判据开
        cfg_en    = 1'b1;                           // 检测总使能开

        // ---- 背景统一用 24'hB0B0B0（R=G=B=176 ⇒ R5=22, G6=44, B5=22, Y=173）----
        //      这是"白桌面"的典型值

        //=================================================================
        // 用例 1：轻度阴影 α≈0.9（R=G=B=160）
        //   三通道同降 16 级 ⇒ ΔCb=ΔCr=0（数学严格为 0）⇒ 判为阴影，score=0
        //=================================================================
        $display("--- U1 轻度阴影 a=0.9（期望：阴影=1，score=0）---");
        run(24'hA0A0A0, 24'hB0B0B0);                // 喂 1 拍
        $display("    ya=%0d dy=%0d dc=%0d sh=%b score=%0d", dbg_ya, dbg_dy, dbg_dc, dbg_shadow, out_pix);
        chk_shadow(1'b1, "U1");                     // 必须是阴影
        chk_eq(8'd0, "U1");                         // ★ score 精确 0

        //=================================================================
        // 用例 2：中度阴影 α≈0.7（R5=15,G6=31,B5=15 ⇒ 实际 R=120,G=124,B=120）
        //   比例略有量化误差 ⇒ ΔCb≈-2、ΔCr≈-2 ⇒ dC≈4
        //   仍判为阴影，score = wC·dC = 2×4 = 8（这就是量化底噪，T 必须大于它）
        //=================================================================
        $display("--- U2 中度阴影 a=0.7（期望：阴影=1，score<=20）---");
        run(24'h787C78, 24'hB0B0B0);                // 喂 1 拍
        $display("    ya=%0d dy=%0d dc=%0d sh=%b score=%0d", dbg_ya, dbg_dy, dbg_dc, dbg_shadow, out_pix);
        chk_shadow(1'b1, "U2");                     // 必须是阴影
        chk_range(8'd0, 8'd20, "U2");               // 量化底噪 ≤ wC×τc = 20

        //=================================================================
        // 用例 3：深阴影 α≈0.4（R=G=B=72）
        //   色度仍然不变，但暗度超过 αmin=0.5 ⇒ **不判阴影**（用户接受深阴影漏检）
        //   score = wY·|ΔY| = 1×103 ≈ 103
        //=================================================================
        $display("--- U3 深阴影 a=0.4（期望：阴影=0，score>=80）---");
        run(24'h484848, 24'hB0B0B0);                // 喂 1 拍
        $display("    ya=%0d dy=%0d dc=%0d sh=%b score=%0d", dbg_ya, dbg_dy, dbg_dc, dbg_shadow, out_pix);
        chk_shadow(1'b0, "U3");                     // 暗度超限 ⇒ 不判阴影
        chk_range(8'd80, 8'd120, "U3");             // 按 |ΔY| 报

        //=================================================================
        // 用例 4：彩色物体 —— 橙色（R5=29,G6=35,B5=5 ⇒ R=232,G=140,B=40）
        //   色度大幅改变 ⇒ 不判阴影；score 饱和到 255
        //=================================================================
        $display("--- U4 橙色物体（期望：阴影=0，score=255）---");
        run(24'hE88C28, 24'hB0B0B0);                // (29<<19)|(35<<10)|(5<<3)
        $display("    ya=%0d dy=%0d dc=%0d sh=%b score=%0d", dbg_ya, dbg_dy, dbg_dc, dbg_shadow, out_pix);
        chk_shadow(1'b0, "U4");                     // 色度变了 ⇒ 不是阴影
        chk_range(8'd200, 8'd255, "U4");            // 强烈命中

        //=================================================================
        // 用例 5：黑色物体（R=G=B=40）
        //   三通道同降、色度严格不变，但暗到 0.23 ⇒ 暗度超限 ⇒ **不判阴影**
        //   ★ 这一条证明"功能没退化"：旧版能检出的黑色物体，现在仍然检出
        //=================================================================
        $display("--- U5 黑色物体（期望：阴影=0，score>=120）---");
        run(24'h282828, 24'hB0B0B0);                // 喂 1 拍
        $display("    ya=%0d dy=%0d dc=%0d sh=%b score=%0d", dbg_ya, dbg_dy, dbg_dc, dbg_shadow, out_pix);
        chk_shadow(1'b0, "U5");                     // 深色物体不能当成阴影
        chk_range(8'd120, 8'd160, "U5");            // 按 |ΔY| 报，确实检出

        //=================================================================
        // 用例 6：白色物体（比背景亮，R=G=B=224）
        //   变亮 ⇒ dark=0 ⇒ 不可能判阴影；score = wY·ΔY = 47
        //=================================================================
        $display("--- U6 白色物体（期望：阴影=0，score≈47）---");
        run(24'hE0E0E0, 24'hB0B0B0);                // (28<<19)|(56<<10)|(28<<3)
        $display("    ya=%0d dy=%0d dc=%0d sh=%b score=%0d", dbg_ya, dbg_dy, dbg_dc, dbg_shadow, out_pix);
        chk_shadow(1'b0, "U6");                     // 变亮不可能是阴影
        chk_range(8'd40, 8'd60, "U6");

        //=================================================================
        // 用例 7：完全没变化（A == B）
        //   score 必须严格 0
        //=================================================================
        $display("--- U7 无变化（期望：阴影=0，score=0）---");
        run(24'hB0B0B0, 24'hB0B0B0);                // 喂同一张
        $display("    ya=%0d dy=%0d dc=%0d sh=%b score=%0d", dbg_ya, dbg_dy, dbg_dc, dbg_shadow, out_pix);
        chk_shadow(1'b0, "U7");
        chk_eq(8'd0, "U7");                         // 精确 0

        //=================================================================
        // 用例 8：★ 等亮度但异色的物体（R5=31,G6=45,B5=0 ⇒ R=248,G=180,B=0，Y=171）
        //   |ΔY| 只有 2，**灰度差分永远抓不到**；但色度差很大 ⇒ 被检出
        //   这是加色度判据带来的"净收益"，不是抗阴影的副产品
        //=================================================================
        $display("--- U8 等亮度异色物体（期望：阴影=0，score 很大）---");
        run(24'hF8B400, 24'hB0B0B0);                // (31<<19)|(45<<10)|(0<<3)
        $display("    ya=%0d dy=%0d dc=%0d sh=%b score=%0d", dbg_ya, dbg_dy, dbg_dc, dbg_shadow, out_pix);
        chk_shadow(1'b0, "U8");                     // 色度变了
        chk_range(8'd200, 8'd255, "U8");            // ★ 靠色度项命中

        //=================================================================
        // 用例 9：★ 安全阀 —— cfg_sh_en = 0
        //   同一个"轻度阴影"输入，此时必须退回旧行为：score = wY·|ΔY| = 16
        //   证明关掉开关后与改造前**逐像素一致**
        //=================================================================
        $display("--- U9 安全阀 sh_en=0（期望：阴影=0，score=16）---");
        cfg_sh_en = 1'b0;                           // 关掉阴影判据
        run(24'hA0A0A0, 24'hB0B0B0);                // 与 U1 同一组数据
        $display("    ya=%0d dy=%0d dc=%0d sh=%b score=%0d", dbg_ya, dbg_dy, dbg_dc, dbg_shadow, out_pix);
        chk_shadow(1'b0, "U9");                     // 关掉就不可能有阴影标记
        chk_eq(8'd16, "U9");                        // ★ 精确 = |ΔY| = 16
        cfg_sh_en = 1'b1;                           // 恢复

        //=================================================================
        // 用例 10：cfg_en = 0（总使能关）⇒ 输出恒 0
        //   上电后背景还没采好时就是这个状态，绝不能误报
        //=================================================================
        $display("--- U10 总使能关（期望：score=0）---");
        cfg_en = 1'b0;                              // 关总使能
        run(24'hE88C28, 24'hB0B0B0);                // 喂一个很强的物体
        $display("    ya=%0d dy=%0d dc=%0d sh=%b score=%0d", dbg_ya, dbg_dy, dbg_dc, dbg_shadow, out_pix);
        chk_eq(8'd0, "U10");                        // 严格 0
        cfg_en = 1'b1;                              // 恢复

        //=================================================================
        // 用例 11：αmin 可调验证 —— 把 αmin 提到 0.75（192）
        //   用例 2 的中度阴影（Y_A=120，Y_B=173 ⇒ 比值 0.69）此时应当**不再判阴影**
        //   证明 αmin 这个旋钮真的在 PS 侧起作用（不用重编）
        //=================================================================
        $display("--- U11 a_min=0.75 后同一中度阴影（期望：阴影=0）---");
        cfg_alpha = 8'd192;                         // αmin = 0.75
        run(24'h787C78, 24'hB0B0B0);                // 与 U2 同一组数据
        $display("    ya=%0d dy=%0d dc=%0d sh=%b score=%0d", dbg_ya, dbg_dy, dbg_dc, dbg_shadow, out_pix);
        chk_shadow(1'b0, "U11");                    // 0.69 < 0.75 ⇒ 不判阴影
        cfg_alpha = 8'd128;                         // 恢复

        //=================================================================
        // 汇总
        //=================================================================
        $display("");
        $display("=== 共 %0d 条检查，失败 %0d 条 ===", n_chk, n_fail);
        if (n_fail == 0) $display("*** 全部通过 ***");
        else             $display("*** 有失败 ***");
        $display("==================== tb_dd_shadow 结束 ====================");
        $finish;                                    // 结束仿真
    end

endmodule
