//////////////////////////////////////////////////////////////////////////////
// defect_detect.v
//
//   **目标**检测 —— 顶层。
//
//   *** 负责人：用户 ***
//
//   --------------------------------------------------------------------
//   本文件只做三件事，**不写任何算法**
//   --------------------------------------------------------------------
//       1) 把 dd_* 子模块串成流水线（例化）
//       2) 帧内统计（命中像素计数 + 目标标志）
//       3) 帧末把结果锁存进影子寄存器，并发出 done
//
//   每一级算法都在**独立的文件**里，好处：
//       · 每一级可以单独写 testbench 仿真验证
//       · 综合后能单独看每个模块占多少 LUT / BRAM / DSP
//       · 出问题时能一级一级切出来看
//       · 几十行的文件才可能逐行注释得清楚
//
//   --------------------------------------------------------------------
//   当前实现进度：里程碑 4 = 在里程碑 3 的取或之后再加 **第⑥级 形态学（闭运算）**
//   --------------------------------------------------------------------
//                              ┌── 支路 A：dd_median3 ──► dd_thresh ──┐
//   px_data ─► dd_gray ─► dd_win3x3 ──┤       3 拍            0 拍    ├─► OR ─► dd_morph ─► 最终掩膜
//               第①级       第②级     └── 支路 B：dd_sobel ────────────┘        第⑥级
//                                              3 拍                              2 拍
//
//   ★★ 两条支路都是"窗口输出后 **3 拍**"，所以 sideband 逐拍对齐，
//     取或的时候**不需要任何延迟补偿**。这是本模块最要紧的接口约定，
//     改任何一条支路的流水级数都必须同时改另一条（或在这里补延迟）。
//
//   ★ 为什么必须两条支路并联、而不是串联：
//     · 串联（中值 → Sobel）会让中值先吃掉细目标，Sobel 就再也看不见它了；
//     · 并联**共用同一个 3×3 窗口**（dd_win3x3 的行缓冲有 4 个读口），
//       所以第二条支路**不需要第二套行缓冲**，只多约 210 个 LUT、0 个 BRAM。
//
//   ★ 为什么取或之后还必须有形态学（第⑥级）：
//     Sobel 报的是"**边**"不是"目标"。淡细线（灰度阈值报不出）经支路 B 之后
//     是**两条断开的平行线**；淡斑块是一个**空心环**。这种图 PS 拿去
//     会被连通域数成两个物体、面积只算成"周长" ⇒ **支路 B 等于白加**。
//     闭运算（先膨胀后腐蚀）把两条线连成一条、把空心环填实 ⇒ 才真的能用。
//     详见 dd_morph.v 的文件头。
//
//   后面每加一级，就是这里多一行例化，**老代码一行不用动**：
//       第④级  局部自适应阈值 需要"附近亮度"，也是并联吃同一个窗口
//
//   ★ 流水线延迟：**8 拍** = dd_gray(1) + dd_win3x3(2) + dd_median3(3) + dd_thresh(0) + dd_morph(2)。
//     ★ 统计（帧内计数 / 目标标志 / done）现在盯的是**形态学之后**的那条流
//       （sideband 全部改用 m_*），因为它才是算法的最终输出。
//     ★ 支路 B（dd_sobel 3 拍）与 dd_median3+dd_thresh 的 3 拍**完全等长**，
//       所以加它**没有改变**当时那条链的延迟。
//     ★★ 注意：dd_win3x3 / dd_morph 里的"1 行 / 2 行"是**空间**延迟（行缓冲造成的），
//        不落在拍数上。所以 DISP 各档的二值图相对原图会**整体下移几行、右移几列**
//        （外加上面那几拍）。这是行缓冲固有的，用户已拍板"对不齐就对不齐"，
//        只影响调试观察，不影响检测结果。
//     于是本模块里"帧尾 + 影子寄存器"的所有配对信号也必须跟着换：
//
//         错的写法（延迟 0 拍时才是对的）      对的写法（延迟 8 拍）
//         ---------------------------------   --------------------------------
//         hit_now = px_valid & mor_hit        hit_now = mor_valid & mor_hit
//         帧首清零用 px_sof                    帧首清零用 mor_sof
//         eof_d1 <= px_eof                     eof_d1 <= mor_eof
//
//     一句话规则：**下游永远拿"自己这一级的 sideband"跟"自己这一级的像素"
//     配对，绝不能混用上游的**。混用的后果不是报错，而是每帧悄悄少算/多算
//     一个像素 —— 屏幕上完全看不出来，只能靠仿真查。
//     （这一条已经被 tb_defect_detect.v 的"空拍"用例盯住了。）
//
//   ★ dd_win3x3 会**屏蔽**帧首 2 行、行首 2 列（那里凑不出完整 3×3 邻域），
//     dd_morph 再屏蔽 1 行 1 列 ⇒ 合计 3 行 3 列（占比 ≈0.6%，可忽略）。
//
//   --------------------------------------------------------------------
//   ★★★ 支路 B 的效果边界（必须知道，否则会误判 Sobel 没用）★★★
//   --------------------------------------------------------------------
//     Sobel 报的是"**边**"，不是"目标"，两者不等价：
//       · 一条 1 像素宽的细线 ⇒ Sobel 得到**两条**轮廓（细线两侧各一条），
//         而细线**正中间反而报不出来**（Sobel 核中间行/列的权重是 0）。
//         所以支路 A（灰度阈值）报中心、支路 B 报两侧，**两条支路是互补的**。
//       · 一块 3×3 的斑块 ⇒ Sobel 只给出它的一圈**轮廓**，中间是空的。
//     ⇒ 支路 B **不能单独使用**；取或之后细目标会被加宽 1 像素左右
//       （两侧各 1 像素），PS 侧做尺寸测量时要记住这一点。
//     ⇒ 要得到"实心"的目标区域，必须再加 **第⑥级形态学**（闭运算）：
//       它既能把细线的两条轮廓接成一条，又能填掉斑块轮廓里的空洞。
//       **形态学必须接在 OR 之后**，接在单条支路上都是错的。
//
//   --------------------------------------------------------------------
//   接口约定（改动前必须先告知另一位负责人）
//   --------------------------------------------------------------------
//     * 本模块是**纯旁听者**，没有 tready，所以永远不可能卡住视频流。
//       不要在这里加任何握手信号。
//     * rst_n 是**低有效**复位。
//     * px_sof / px_eol / px_eof 在顶层已经带 px_valid 限定，
//       所以直接写 "if (px_sof)" 就够了。
//
//   注意：与顶层 glass_defect_core 不同，本文件**不被 BD 引用**，
//   所以端口是可以改的；只有 glass_defect_core.v 的端口表是冻结的。
//
//   --------------------------------------------------------------------
//   px_data 数据格式 —— 重要
//   --------------------------------------------------------------------
//     采集 IP 输出的是 RGB565 **左对齐补 0** 塞进 24 位：
//         px_data[23:16] = {R5, 3'b000}     低位 3 位恒为 0
//         px_data[15: 8] = {G6, 2'b00}      低位 2 位恒为 0
//         px_data[ 7: 0] = {B5, 3'b000}     低位 3 位恒为 0
//     所以它**不是**真 RGB888，直接取高位就是 R5 / G6 / B5。
//
//   ★ 灰度公式（2:4:1）必须与 size_detect.v 完全一致 —— 这是合体交叉
//     验证点：两边同阈值同极性时，DISP=1 与 DISP=2 的二值图必须一模一样。
//
//   --------------------------------------------------------------------
//   注释规范（项目要求，2026-09-24）
//   --------------------------------------------------------------------
//       每一行有实际功能的代码，行尾都跟一条中文注释，说明"这行在做什么 / 为什么"。
//       本文件以 **UTF-8（无 BOM）** 编码保存。
//////////////////////////////////////////////////////////////////////////////

module defect_detect #(
    parameter integer H_ACTIVE = 972,   // 每行有效像素数（本里程碑未用，留给后面的坐标计数）
    parameter integer V_ACTIVE = 720    // 每帧有效行数（同上）
)(
    // ------------------------------------------------------------------
    // 时钟与复位
    // ------------------------------------------------------------------
    input  wire        clk,        // aclk，100MHz
    input  wire        rst_n,      // 低有效复位

    // ------------------------------------------------------------------
    // 视频观测口（两个检测模块完全一致）
    // ------------------------------------------------------------------
    input  wire [23:0] px_data,    // RGB565 左对齐补 0 的 24 位像素
    input  wire        px_valid,   // = s_axis_tvalid & s_axis_tready
    input  wire        px_sof,     // 帧首（已带 px_valid 限定）
    input  wire        px_eol,     // 行尾（已带 px_valid 限定；本里程碑未用）
    input  wire        px_eof,     // 帧尾（已带 px_valid 限定）

    // ------------------------------------------------------------------
    // 控制口 A（由 DEF_TH 寄存器 0x20 驱动）
    // ------------------------------------------------------------------
    input  wire        en,         // DEF_TH[0]，使能
    input  wire        polarity,   // DEF_TH[1]：0 = 目标比放置物亮
    input  wire        med_en,     // DEF_TH[2]：1 = 启用 3×3 中值，0 = 旁路（保小目标）
    input  wire        morph_en,   // DEF_TH[3]：1 = 启用闭运算，0 = 旁路（输出=取或的原始掩膜）
    input  wire [7:0]  th,         // DEF_TH[15:8]，灰度阈值

    // ------------------------------------------------------------------
    // 控制口 B（由 SOB_TH 寄存器 0x30 驱动）—— 支路 B（Sobel）
    // ------------------------------------------------------------------
    input  wire        sob_en,     // SOB_TH[0]：支路 B 使能。默认 0 ⇒ 本模块行为与里程碑 2 完全一致
    input  wire [7:0]  sob_th,     // SOB_TH[15:8]：Sobel 梯度阈值（幅值 0..1476，阈值 0..255 够用）

    // ------------------------------------------------------------------
    // 背景口 + 差分控制（"放置物识别与计数"新增：背景差分法）
    //   背景来自 DDR：PS 采好空场景背景后写进 bg_buf，由 axi_vdma_0/MM2S 循环读出，
    //   经顶层 s_axis_bg 送进来。**背景只取 8 位**（PS 写进去的就是灰度本身）。
    // ------------------------------------------------------------------
    input  wire        bg_valid,   // 背景流像素有效
    input  wire [23:0] bg_pix,     // ★ 背景彩色原图（顶层直通 s_axis_bg_tdata，24 位）
    input  wire        bg_sof,     // 背景帧首（顶层已带 valid 限定）
    input  wire        diff_en,    // BG_CTL[0]：差分+配对使能（背景没采好时必须为 0）

    // ------------------------------------------------------------------
    // ★ 阴影抑制配置（全部来自 PS 的 AXI-Lite 寄存器 0x28 SHADOW_CFG）
    //   做成寄存器是为了**在板上实时调，不用重编位流**
    // ------------------------------------------------------------------
    input  wire        sh_en,      // SHADOW_CFG[0]：阴影判据使能（0 ⇒ 退回纯 |ΔY| 的旧行为）
    input  wire [3:0]  sh_wy,      // SHADOW_CFG[7:4]  ：亮度项权重 wY
    input  wire [3:0]  sh_wc,      // SHADOW_CFG[11:8] ：色度项权重 wC
    input  wire [7:0]  sh_tau,     // SHADOW_CFG[23:16]：色度阈值 τc（建议 10~12，下限 8）
    input  wire [7:0]  sh_alpha,   // SHADOW_CFG[31:24]：αmin 定点码（128 = 0.5）

    output wire        bg_ready,   // 回给 s_axis_bg_tready —— 配对器要求 B 稍等时的反压

    // ------------------------------------------------------------------
    // 结果口
    // ------------------------------------------------------------------
    output wire [15:0] crack_cnt,  // 【里程碑1 临时语义】本帧目标像素总数，见文件末尾说明
    output wire [15:0] stain_cnt,  // 本里程碑固定输出 0
    output wire [15:0] bubble_cnt, // 本里程碑固定输出 0
    output wire        defect_flag,// 1 = 本帧至少存在一个目标像素
    output wire        done,       // 帧末单拍脉冲（此时影子寄存器已更新完毕）
    output wire [15:0] sob_cnt,    // 【新】本帧**支路 B 单独**的命中像素数（上板扫阈值用）
    output wire        px_hit,     // 【支路 A】灰度阈值命中 —— 供 DISP=2 显示二值图
                                   //   ★ 语义与里程碑 2 **完全一致**，没有被 OR 污染
    output wire        px_hit_b,   // 【支路 B】Sobel 边缘命中 —— 供 DISP=3 显示二值图
    output wire        px_hit_or,  // 【A|B】取或之后的掩膜 —— 供 DISP=4 显示
    output wire        px_hit_fin, // 【最终】形态学之后的掩膜 —— 供 DISP=5 显示，
                                   //   也是**帧内统计（计数/目标标志）实际计入的那一路**
    output wire [7:0]  px_gray,    // 【DISP=6】当前帧灰度 Y_A（由 dd_shadow 现算，8 位）
    output wire [7:0]  px_diff,    // 【DISP=8】|ΔY| 亮度差（dd_shadow 输出，8 位）
    output wire [23:0] px_bg,      // 【DISP=7】**配对之后**的背景彩色（配对器输出，和屏的时序同源）
    output wire [7:0]  px_cdiff,   // 【DISP=9】色度差 |ΔCb|+|ΔCr|（阴影区应接近 0，调 τc 就看这一档）
    output wire [7:0]  px_shadow,  // 【DISP=10】阴影标记：255 = 本拍被判为阴影，0 = 不是

    // ------------------------------------------------------------------
    // 对齐诊断口（供 PS 读寄存器判断两路有没有对上，上板调试用）
    // ------------------------------------------------------------------
    output wire [15:0] align_lead,    // 最近一次 B 帧首量到的 L：A 领先 B 多少像素（应是小常数）
    output wire [15:0] align_leadmax, // 峰值领先量（像素）
    output wire [15:0] align_stall,   // 因 A 未就绪而停顿的拍数（A 落后于 B）
    output wire [15:0] align_lap      // 超前超过缓冲深度的拍数（数据已被覆盖 ⇒ 不给坏数据）
);

    //=====================================================================
    // 算法流水线：由 dd_* 子模块串联而成
    //
    //   px_data ─► dd_gray ─► dd_pair ─► dd_diff ─► dd_win3x3 ─► dd_median3 ─► dd_thresh ─► px_hit
    //               第①级     ①·五级     ①·六级       第②级          第③级          第⑤级
    //                            ▲
    //   s_axis_bg ───────────────┘（背景，来自 DDR）
    //
    //   ★ 顺序说明：先差分、再 3×3 中值滤波。
    //     中值放在差分之后 = "给差分图去孤立噪点"，能直接压掉误报；
    //     而且两边输入都是同一条链出来的**原始灰度**，是同一把尺子量出来的，公平。
    //
    //   整条链共 10 拍延迟（8 拍 + 配对 1 拍 + 差分 1 拍），px_hit 比 px_data 晚 10 拍；
    //   下游统计必须用 t_* 这一组 sideband（流水线最末端的）。
    //=====================================================================

    // ---- 第①级：灰度化 ----
    wire        g_valid;                            // 传输级的 valid
    wire [23:0] g_pix;                              // ★ 24 位彩色原图（透传，不再灰度化）
    wire        g_sof, g_eol, g_eof;                // 灰度级的帧首/行尾/帧尾

    dd_gray u_gray (
        .clk       (clk),                           // 本模块当前是纯组合，clk/rst_n 暂时用不到
        .rst_n     (rst_n),                         // …
        .in_valid  (px_valid),                      // 从顶层的观测信号接进来
        .in_pix    (px_data),                       // 原始像素
        .in_sof    (px_sof),                        // …
        .in_eol    (px_eol),                        // …
        .in_eof    (px_eof),                        // …
        .out_valid (g_valid),                       // 与 in_valid 同拍（0 拍延迟）
        .out_pix   (g_pix),                         // ★ 24 位彩色原图（透传）
        .out_sof   (g_sof),                         // …
        .out_eol   (g_eol),                         // …
        .out_eof   (g_eof)                          // …
    );

    // ---- 第①·五级：A/B 配对（弹性对齐缓冲）----
    //   为什么需要这一级：A 路（当前帧灰度）是 PL 现场产生的，B 路（背景）要绕一趟
    //   DDR 才回来，两路在同一帧内差了几百到几千个像素。直接相减 = 拿第 n 个像素
    //   去减第 n±k 个像素 ⇒ 背景静止区也会大面积误报。本模块按"帧内位置"把两路配对。
    wire        p_valid;                            // 配对后的成对有效
    wire [23:0] p_pix;                              // 配对后的 A 路彩色
    wire        p_sof, p_eol, p_eof;                // 配对后的 A 路 sideband
    wire [23:0] p_b_pix;                            // 配对后的 B 路彩色（同拍）

    dd_pair #(.DW(24)) u_pair (                      // ★ DW=24：按彩色原图配对（对齐逻辑本身未改）
        .clk        (clk),                          // 100MHz
        .rst_n      (rst_n),                        // 低有效复位
        .cfg_en     (diff_en),                      // 差分没使能 ⇒ 不配对（下游输出无效拍 ⇒ 掩膜全黑）
        .a_valid    (g_valid),                      // A 路 = 上一级（透传）的输出
        .a_pix      (g_pix),                        // …
        .a_sof      (g_sof),                        // …
        .a_eol      (g_eol),                        // …
        .a_eof      (g_eof),                        // …
        .b_valid    (bg_valid),                     // B 路 = 背景（来自 DDR）
        .b_pix      (bg_pix),                       // …
        .b_sof      (bg_sof),                       // …
        .b_ready    (bg_ready),                     // ← 回顶层，接 s_axis_bg_tready
        .out_valid  (p_valid),                      // 成对有效
        .out_pix    (p_pix),                        // A 像素（空间位置与 B 相同）
        .out_sof    (p_sof),                        // …
        .out_eol    (p_eol),                        // …
        .out_eof    (p_eof),                        // …
        .out_b_pix  (p_b_pix),                      // B 像素（同拍）
        .lead_max   (align_leadmax),                // 诊断直通顶层
        .stall_cnt  (align_stall),                  // …
        .lap_cnt    (align_lap),                    // …
        .lead_last  (align_lead)                    // …
    );

    // ---- 第①·六级：彩色差分 + 阴影抑制评分（dd_shadow）----
    //   旧版这里是 dd_diff：D = |当前帧灰度 − 背景灰度|。
    //   现在改成吃**彩色** A/B 两路，同时算亮度差和色度差：
    //       阴影 = 色度不变 + 变暗 + 暗得没超过 αmin（三条同时成立）
    //       score = wY·(阴影 ? 0 : |ΔY|) + wC·(|ΔCb| + |ΔCr|)
    //   ★ 下游 dd_win3x3 起的五个模块仍然只吃 8 位单通道，**一个字都不用改**。
    wire        d_valid;                            // 评分级的 valid
    wire [7:0]  d_pix;                              // score（送进 dd_win3x3）
    wire        d_sof, d_eol, d_eof;                // 评分级的帧首/行尾/帧尾
    wire [7:0]  sh_ya, sh_dy, sh_dc;                // 调试量：Y_A / |ΔY| / 色度差
    wire        sh_flag;                            // 阴影标记
    wire [23:0] sh_bgc;                             // 配对后的背景彩色（供 DISP=7）

    dd_shadow u_shadow (
        .clk        (clk),                          // 100MHz
        .rst_n      (rst_n),                        // 低有效复位
        .a_valid    (p_valid),                      // A 路 = 配对后的当前帧彩色
        .a_pix      (p_pix),                        // 24 位彩色原图
        .a_sof      (p_sof),                        // …
        .a_eol      (p_eol),                        // …
        .a_eof      (p_eof),                        // …
        .b_valid    (p_valid),                      // B 路与 A 同拍（配对器已经配好）
        .b_pix      (p_b_pix),                      // 24 位背景彩色
        .cfg_en     (diff_en),                      // 关掉时输出恒 0
        .cfg_sh_en  (sh_en),                        // SHADOW_CFG[0]
        .cfg_wy     (sh_wy),                        // 亮度项权重
        .cfg_wc     (sh_wc),                        // 色度项权重
        .cfg_alpha  (sh_alpha),                     // αmin 定点码
        .cfg_tau    (sh_tau),                       // 色度阈值 τc
        .out_valid  (d_valid),                      // 评分级有效（晚 4 拍）
        .out_pix    (d_pix),                        // score
        .out_sof    (d_sof),                        // …
        .out_eol    (d_eol),                        // …
        .out_eof    (d_eof),                        // …
        .dbg_ya     (sh_ya),                        // DISP=6
        .dbg_dy     (sh_dy),                        // DISP=8
        .dbg_dc     (sh_dc),                        // DISP=9
        .dbg_shadow (sh_flag),                      // DISP=10
        .dbg_bgc    (sh_bgc)                        // DISP=7
    );

    // ---- 第②级：3×3 窗口（行缓冲 + 邻域展开）----
    //   只把 9 个邻居凑齐，不做任何运算；后面的 Sobel / 形态学都并联吃这个窗口。
    wire        w_valid;                            // 窗口级的 valid
    wire        w_sof, w_eol, w_eof;                // 窗口级的帧首/行尾/帧尾
    wire [7:0]  win00, win01, win02;                // 上上行
    wire [7:0]  win10, win11, win12;                // 上一行（win11 = 窗口中心）
    wire [7:0]  win20, win21, win22;                // 当前行

    dd_win3x3 u_win (
        .clk       (clk),                           // 100MHz
        .rst_n     (rst_n),                         // 低有效复位
        .in_valid  (d_valid),                       // ★ 接差分级的输出（不是灰度级：先差分再滤波）
        .in_pix    (d_pix),                         // ★ 差分绝对值图
        .in_sof    (d_sof),                         // …
        .in_eol    (d_eol),                         // …
        .in_eof    (d_eof),                         // …
        .out_valid (w_valid),                       // 窗口有效（比输入晚 2 拍）
        .out_sof   (w_sof),                         // …
        .out_eol   (w_eol),                         // …
        .out_eof   (w_eof),                         // …
        .w00(win00), .w01(win01), .w02(win02),      // 窗口第 0 行
        .w10(win10), .w11(win11), .w12(win12),      // 窗口第 1 行
        .w20(win20), .w21(win21), .w22(win22)       // 窗口第 2 行
    );

    // ---- 第③级：3×3 中值（19 比较器，3 级流水）----
    //   med_en = 1 时输出中值（去孤立噪点），= 0 时旁路输出窗口中心（保小目标）。
    wire        m_valid;                            // 中值级的 valid
    wire [7:0]  m_pix;                              // 中值级的像素
    wire        m_sof, m_eol, m_eof;                // 中值级的帧首/行尾/帧尾

    dd_median3 u_med (
        .clk        (clk),                          // 100MHz
        .rst_n      (rst_n),                        // 低有效复位
        .w00(win00), .w01(win01), .w02(win02),      // 接窗口第 0 行
        .w10(win10), .w11(win11), .w12(win12),      // 接窗口第 1 行
        .w20(win20), .w21(win21), .w22(win22),      // 接窗口第 2 行
        .in_valid   (w_valid),                      // 接窗口级的 valid
        .in_sof     (w_sof),                        // …
        .in_eol     (w_eol),                        // …
        .in_eof     (w_eof),                        // …
        .cfg_med_en (med_en),                       // 中值使能（顶层 DEF_TH[2]）
        .out_valid  (m_valid),                      // 比输入晚 3 拍
        .out_pix    (m_pix),                        // …
        .out_sof    (m_sof),                        // …
        .out_eol    (m_eol),                        // …
        .out_eof    (m_eof)                         // …
    );

    // ---- 第⑤级：二值化 ----
    wire        t_valid;                            // 二值化级的 valid
    wire        t_hit;                              // 二值化级的命中标志
    wire        t_sof, t_eol, t_eof;                // 二值化级的帧首/行尾/帧尾

    dd_thresh u_thresh (
        .clk       (clk),                           // 参数锁存器用的时钟
        .rst_n     (rst_n),                         // 低有效复位
        .in_valid  (m_valid),                       // 接上一级（中值）的输出
        .in_pix    (m_pix),                         // 接上一级的像素
        .in_sof    (m_sof),                         // …
        .in_eol    (m_eol),                         // …
        .in_eof    (m_eof),                         // …
        .cfg_en    (en),                            // 使能来自顶层寄存器
        .cfg_pol   (polarity),                      // 极性来自顶层寄存器
        .cfg_th    (th),                            // 阈值来自顶层寄存器
        .out_valid (t_valid),                       // 与 in_valid 同拍（本模块 0 拍，但 in_* 已是 1 拍）
        .out_hit   (t_hit),                         // 二值化结果
        .out_sof   (t_sof),                         // …
        .out_eol   (t_eol),                         // …
        .out_eof   (t_eof)                          // …
    );

    // ---- 第③级（支路 B）：Sobel 边缘检测 ----
    //   ★ **并联**吃 dd_win3x3 的同一个窗口，不额外占行缓冲。
    //   ★ 延迟 3 拍，与「dd_median3(3) + dd_thresh(0)」**完全等长**
    //     ⇒ s_* 与 t_* 逐拍对齐，下面直接取或即可，不需要延迟补偿。
    wire        s_valid;                            // 支路 B 的 valid
    wire        s_hit;                              // 支路 B 的命中（梯度超阈值）
    wire        s_sof, s_eol, s_eof;                // 支路 B 的帧首/行尾/帧尾

    dd_sobel u_sobel (
        .clk        (clk),                          // 100MHz
        .rst_n      (rst_n),                        // 低有效复位
        .w00(win00), .w01(win01), .w02(win02),      // 与支路 A **同一个**窗口第 0 行
        .w10(win10), .w11(win11), .w12(win12),      // 同一个窗口第 1 行（中心 w11 不用）
        .w20(win20), .w21(win21), .w22(win22),      // 同一个窗口第 2 行
        .in_valid   (w_valid),                      // 与支路 A 同源的窗口 valid
        .in_sof     (w_sof),                        // 同一组 sideband ⇒ 天然对齐
        .in_eol     (w_eol),                        // …
        .in_eof     (w_eof),                        // …
        .cfg_en     (sob_en),                       // 支路 B 使能（SOB_TH[0]）
        .cfg_th     (sob_th),                       // 梯度阈值（SOB_TH[15:8]）
        .out_valid  (s_valid),                      // 比窗口晚 3 拍
        .out_hit    (s_hit),                        // …
        .out_sof    (s_sof),                        // …
        .out_eol    (s_eol),                        // …
        .out_eof    (s_eof)                         // …
    );

    // 流水线末端就是送给顶层的二值图。整条链共 6 拍延迟
    // ⇒ px_hit 比 px_data 晚 6 拍；再加上 dd_win3x3 空间上的"晚一行一列"，
    //   顶层 DISP=2 的二值图会比原图**下移一行、右移一列**（只影响调试观察）。
    //
    //   ★ 三个输出各司其职，**不要把 px_hit 改成取或的结果**：
    //     px_hit   = 支路 A，DISP=2 的语义必须与里程碑 2 一模一样（用户已上板验证过）
    //     px_hit_b = 支路 B，DISP=3
    //     px_hit_or= A|B，才是"最终目标掩膜"，也是统计计入的东西
    //   ★ 支路 B 关掉（sob_en=0）时，px_hit_or 恒等于 px_hit ⇒
    //     上板默认配置下，本模块的行为与里程碑 2 **逐像素完全一致**。
    assign px_hit    = t_hit;                       // 支路 A：灰度阈值命中（DISP=2，语义冻结）
    assign px_hit_b  = s_hit;                       // 支路 B：Sobel 边缘命中（DISP=3）
    assign px_hit_or = t_hit | s_hit;               // 两条支路取或（DISP=4）

    // ---- 第⑥级：二值形态学（闭运算）----
    //   ★ 吃的是**取或之后**的掩膜，必须接在这里 —— 接在单条支路上都是错的。
    //   ★ 它的输入 sideband 用 t_*（或 s_*，两者事实等值），因为两条支路已经对齐。
    //   ★ 输出 sideband 是 mor_*，**下游统计全部改用 mor_***（见下面的说明）。
    //     （★ 名字不能叫 m_* —— 那是中值级已经占用的，重名会直接编译不过。）
    wire        mor_valid;                          // 形态学级的 valid
    wire        mor_hit;                            // 形态学级的命中（闭运算结果）
    wire        mor_sof, mor_eol, mor_eof;          // 形态学级的帧首/行尾/帧尾

    dd_morph #(
        .H_ACTIVE (H_ACTIVE - 2)                    // ★★ 必须减 2 ★★
        //   形态学的输入是**取或掩膜**，而掩膜的每一行只有 H_ACTIVE-2 个有效像素
        //   （dd_win3x3 把每行最前面 2 列屏蔽掉了）。
        //   传原图行宽进去 ⇒ 行缓冲深度多 2 ⇒ "上一行"的抽头会**横向偏 2 列**，
        //   窗口变成一个歪的邻域 —— 屏幕上完全看不出来，只能靠仿真抓。
    ) u_morph (
        .clk       (clk),                           // 100MHz
        .rst_n     (rst_n),                         // 低有效复位
        .in_hit    (t_hit | s_hit),                 // ★ 取或之后的掩膜
        .in_valid  (t_valid),                       // 与取或结果同拍
        .in_sof    (t_sof),                         // …
        .in_eol    (t_eol),                         // …
        .in_eof    (t_eof),                         // …
        .cfg_en    (morph_en),                      // 闭运算使能（DEF_TH[3]）
        .out_hit   (mor_hit),                       // 比输入晚 2 拍
        .out_valid (mor_valid),                     // …
        .out_sof   (mor_sof),                       // …
        .out_eol   (mor_eol),                       // …
        .out_eof   (mor_eof)                        // …
    );

    assign px_hit_fin = mor_hit;                    // 最终掩膜（DISP=5，也是统计判据）
    assign px_gray    = sh_ya;                      // 【DISP=6】当前帧灰度 Y_A（dd_shadow 现算）
    assign px_diff    = sh_dy;                      // 【DISP=8】|ΔY| 亮度差
    assign px_bg      = sh_bgc;                     // 【DISP=7】配对后的背景彩色（★ 与屏时序同源，不会被切）
    assign px_cdiff   = sh_dc;                      // 【DISP=9】色度差 |ΔCb|+|ΔCr|
    assign px_shadow  = sh_flag ? 8'hFF : 8'h00;    // 【DISP=10】阴影标记（255 = 判为阴影）

    //=====================================================================
    // 帧内统计：命中像素计数 + 目标标志
    //   ★ 全部用 t_* 这一组（流水线末端的 sideband），不用 px_*。
    //     整条链现在是 6 拍（灰度1 + 窗口2 + 中值3 + 二值化0），
    //     t_hit 对应的是 t_valid 那一拍的像素；
    //     拿 px_valid 去与 t_hit，会在"空拍之后第一个像素"上多算一个命中，
    //     同时把"空拍之前最后一个像素"的命中漏掉。
    //
    //   ★★ 为什么用 16 位饱和计数、而且影子寄存器要"晚一拍"锁存 ★★
    //
    //   最早的写法是：计数器 32 位，帧末再组合地算一个
    //       hit_final = hit_cnt + hit_now;              // 补上最后一个像素
    //       hit_sat   = (hit_final > 65535) ? FFFF : …; // 饱和判断
    //   这**两个组合运算直接串在灰度链后面**：
    //       输入寄存器 → 3 个加法器 → 比较器 → hit_now → 32位加法 → 32位比较 → 影子寄存器
    //   实测数据路径 **11.42ns**（要求 10ns），Slack **-1.677ns**，
    //   **17 条时序违反全部出自这一条路径**（2026-09-24 综合结果）。
    //
    //   改法：
    //     ① 计数器改成 **16 位饱和**（真实目标像素远小于 65535），
    //        32 位加法和 32 位比较一起消失；
    //     ② 影子寄存器改为**比流水线帧尾晚一拍**锁存 —— 那一拍 hit_cnt 里
    //        自然已经包含最后一个像素，**根本不需要那个组合的 hit_final**。
    //   结果：灰度链的终点只是一个寄存器的 CE，和计数器彻底分开。
    //
    //   饱和（而不是回绕）的理由：回绕会给出一个看起来"很正常"的小数字，
    //   反而让人以为检测正常；饱和成 0xFFFF 一眼就能看出"阈值设错了"。
    //=====================================================================
    //   ★ 里程碑 4：计入统计的是**形态学之后的最终掩膜**（mor_valid & mor_hit），
    //     因为它才是算法的输出。形态学被旁路（DEF_TH[3]=0）时，
    //     dd_morph 的输出逐像素等于取或的原始掩膜 ⇒ 计数与里程碑 3 一致。
    //   ★ 两个"本拍是否有一个命中像素"的信号各自用**自己那一条流的 sideband**，
    //     虽然几组 sideband 事实上等值，但这样写才能保证"改一条流的延迟时，
    //     另一条不会被偷偷带错"，也把"必须对齐"这件事写在了代码里。
    wire hit_fin_now = mor_valid & mor_hit;         // ★ 最终判据（形态学之后）—— 计入统计
    wire hit_b_now   = s_valid & s_hit;             // 支路 B 本拍送出一个命中像素（单独计数用）

    reg [15:0] hit_cnt;                             // 本帧累计的命中像素数（16 位，饱和）
    // ★ 声明顺序要紧：cnt_full 用到 hit_cnt，必须写在 hit_cnt **之后**，
    //   否则 Verilog 会把 hit_cnt 当成隐式线网，报 "used before its declaration"。
    wire cnt_full = (hit_cnt == 16'hFFFF);          // 计数器已满（饱和用）

    always @(posedge clk) begin
        if (!rst_n)
            hit_cnt <= 16'd0;                       // 复位清零
        else if (mor_sof)
            hit_cnt <= hit_fin_now ? 16'd1 : 16'd0; // ★ 帧首清零（用 mor_sof）；这一拍本身命中就记 1
        else if (hit_fin_now && !cnt_full)
            hit_cnt <= hit_cnt + 16'd1;             // 命中一个加一；满了就保持不再加
    end

    // ---- 支路 B 单独计数（上板扫 Sobel 阈值时的唯一量化依据）----
    //   为什么必须单独统计：取或之后的计数把两条支路混在一起，
    //   调 Sobel 阈值时看到的数字同时被灰度阈值影响，**根本分不清是谁在动**。
    //   有了这个数，就能固定 DEF_TH、只扫 SOB_TH[15:8]，看 B 的命中数怎么变。
    //   它和 hit_cnt 共用同一个 eof_d1 做影子锁存（两条支路的帧尾等值且同拍）✓
    reg [15:0] sob_cnt_r;                           // 支路 B 本帧累计命中数（16 位，饱和）
    wire sob_full = (sob_cnt_r == 16'hFFFF);        // 支路 B 计数器已满（饱和用）

    always @(posedge clk) begin
        if (!rst_n)
            sob_cnt_r <= 16'd0;                     // 复位清零
        else if (s_sof)
            sob_cnt_r <= hit_b_now ? 16'd1 : 16'd0; // ★ 用**支路 B 自己的**帧首清零
        else if (hit_b_now && !sob_full)
            sob_cnt_r <= sob_cnt_r + 16'd1;         // 命中一个加一；满了就保持不再加
    end

    reg eof_d1;                                     // 流水线帧尾延后一拍（done 和影子锁存都用它）

    always @(posedge clk) begin
        if (!rst_n)
            eof_d1 <= 1'b0;                         // 复位清零
        else
            eof_d1 <= mor_eof;                        // ★ 用 m_eof（形态学之后的，不是 px_eof！）
    end
    // ★ 为什么必须用 m_eof：m_eof 那一拍正是"最后一个像素"被计数的同一拍，
    //   而计数器要等到**下一个时钟沿**才把它加进去。所以帧尾信号必须再晚
    //   一拍（eof_d1），影子寄存器才能在计数完成后搬运，否则永远少算最后一个像素。

    reg [15:0] hit_cnt_sh;                          // 影子寄存器：供 PS 随时读
    reg [15:0] sob_cnt_sh;                          // 影子寄存器：支路 B 的计数
    reg        dflag_sh;                            // 影子寄存器：本帧是否存在目标

    always @(posedge clk) begin
        if (!rst_n) begin
            hit_cnt_sh <= 16'd0;                    // 复位清零
            sob_cnt_sh <= 16'd0;                    // 复位清零
            dflag_sh   <= 1'b0;                     // 复位后无目标
        end else if (eof_d1) begin
            hit_cnt_sh <= hit_cnt;                  // ★ 此刻 hit_cnt 已含最后一像素，直接搬
            sob_cnt_sh <= sob_cnt_r;                // 支路 B 的计数同理
            dflag_sh   <= (hit_cnt != 16'd0);       // 帧末判定：这一帧到底有没有目标
        end
    end

    //=====================================================================
    // 结果输出
    //
    //   ★★ 关于 crack_cnt 的临时语义 ★★
    //
    //   真正的分类（类别判定）按当前方案是在 **PS 侧**用
    //   连通域 + 形状特征做，PL 这边只负责给出"本帧有多少目标像素"，
    //   用来实时判"合格 / 不合格"。
    //
    //   但寄存器表里这三个 16 位结果口的**最终归属还没定**
    //   （候选：0x24 改成"目标像素总数"由 PL 写，0x28/0x2C 退回给 PS），
    //   所以本里程碑暂时把计数放在 crack_cnt 上，另两个固定输出 0。
    //   等寄存器表定下来再调整 —— 目前不影响任何功能。
    //=====================================================================
    assign crack_cnt   = hit_cnt_sh;                // 【临时】本帧目标像素总数（**A|B**）
    assign stain_cnt   = 16'd0;                     // 未使用
    assign bubble_cnt  = 16'd0;                     // 未使用
    assign defect_flag = dflag_sh;                  // 本帧是否有目标（按 A|B 判定）
    assign done        = eof_d1;                    // 帧末单拍脉冲（此时影子寄存器刚锁存完）
    assign sob_cnt     = sob_cnt_sh;                // 【新】支路 B 单独的命中像素数

endmodule
