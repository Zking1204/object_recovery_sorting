//////////////////////////////////////////////////////////////////////////////
// dd_gray.v  ——  第①级：**24 位彩色透传 + 1 拍流水寄存器**（灰度化已停用）
//
//   【2026-10-21 变更：从"灰度化"改成"透传"】
//
//     原设计在这里就把彩色压成 8 位灰度（权重 2:4:1）：
//         S = 2(R5+G6) + B5 ； Y = S + (S>>3)
//     问题在于：**灰度化发生在 A/B 配对之前** ⇒ 色度信息在对齐之前就被销毁了。
//     而抗阴影恰恰要靠色度（阴影是"同一材质照度乘 α"，色度不变；换材质才会变色度）。
//     ⇒ 现在把彩色原样传下去，灰度化/色度化统一挪到 **配对之后** 做（见 dd_shadow.v）。
//
//   --------------------------------------------------------------------
//   ★★ 本模块延迟 **1 拍**（寄存器保留，用来维持原有的组合链切分点）★★
//   --------------------------------------------------------------------
//       原设计插这一级的目的：把"输入寄存器 → 3 个加法器 → 阈值比较 → 显示 MUX → VDMA"
//       那条过长的组合链切成两半。现在内部虽然只剩连线，但**仍保留这一级寄存器**，
//       原因是：① 时序结构不变，回归风险最小；② 层级划分与旧版一致，便于对照。
//
//   --------------------------------------------------------------------
//   流水级怎么写才是对的（反复确认过，记下来免得再错）
//   --------------------------------------------------------------------
//       五根信号（像素 + valid/sof/eol/eof）**无条件一起打拍**：
//           r_pix <= in_pix;  r_valid <= in_valid;
//           r_sof <= in_sof;  r_eol <= in_eol;  r_eof <= in_eof;
//       不要写 "if (in_valid)" 之类的门控 —— 不需要，而且是错的写法。
//       理由：下游反压时上游会把同一个像素重复送好几拍，但那几拍
//       px_valid = tvalid & tready 是 0，最后一拍才变 1；
//       五根一起打拍，下游看到的仍然"只有一拍 valid"，既不会漏像素也不会数重。
//
//   --------------------------------------------------------------------
//   像素流接口约定（本工程所有 dd_* 子模块统一使用）
//   --------------------------------------------------------------------
//       in_valid  本拍有有效像素
//       in_pix    像素数据
//       in_sof    帧首（本拍是一帧的第一个像素）
//       in_eol    行尾（本拍是一行的最后一个像素）
//       in_eof    帧尾
//     出口同名加 out_ 前缀。五个信号必须始终同拍。
//
//   --------------------------------------------------------------------
//   注释规范（项目要求，2026-09-24）
//   --------------------------------------------------------------------
//       每一行有实际功能的代码，行尾都跟一条中文注释，说明"这行在做什么 / 为什么"。
//       本文件以 **UTF-8（无 BOM）** 编码保存。
//////////////////////////////////////////////////////////////////////////////

module dd_gray (
    // ------------------------------------------------------------------
    // 时钟与复位
    // ------------------------------------------------------------------
    input  wire        clk,        // aclk，100MHz
    input  wire        rst_n,      // 低有效复位（同步复位，来自 peripheral_aresetn）

    // ------------------------------------------------------------------
    // 像素输入
    // ------------------------------------------------------------------
    input  wire        in_valid,   // 本拍有有效像素
    input  wire [23:0] in_pix,     // ★ 24 位彩色像素（RGB565 左对齐补 0）
    input  wire        in_sof,     // 帧首
    input  wire        in_eol,     // 行尾
    input  wire        in_eof,     // 帧尾

    // ------------------------------------------------------------------
    // 像素输出（比输入晚 1 拍）
    // ------------------------------------------------------------------
    output wire        out_valid,  // = in_valid 打 1 拍
    output wire [23:0] out_pix,    // ★ 24 位彩色像素（透传，晚 1 拍）
    output wire        out_sof,    // = in_sof 打 1 拍
    output wire        out_eol,    // = in_eol 打 1 拍
    output wire        out_eof     // = in_eof 打 1 拍
);

    //=====================================================================
    // 流水寄存器：像素 + 四根 sideband，无条件一起打 1 拍
    //
    //   ★ 这里**不做任何运算** —— 只把彩色原图原样往后传一拍。
    //     真正的灰度化现在发生在 dd_shadow.v 里（配对之后，A/B 各算一次）。
    //
    //   复位值全给 0：这样仿真一上电输出就是确定的 0，不会出现 x/z
    //   （testbench 要拿复位后的输出当基准比对）。
    //=====================================================================
    reg        r_valid;                                 // 延迟 1 拍的 valid
    reg [23:0] r_pix;                                   // 延迟 1 拍的彩色像素
    reg        r_sof;                                   // 延迟 1 拍的帧首
    reg        r_eol;                                   // 延迟 1 拍的行尾
    reg        r_eof;                                   // 延迟 1 拍的帧尾

    always @(posedge clk) begin
        if (!rst_n) begin
            r_valid <= 1'b0;                            // 复位：无有效像素
            r_pix   <= 24'd0;                           // 复位：像素 0
            r_sof   <= 1'b0;                            // 复位：非帧首
            r_eol   <= 1'b0;                            // 复位：非行尾
            r_eof   <= 1'b0;                            // 复位：非帧尾
        end else begin
            r_valid <= in_valid;                        // ★ 与像素同拍进寄存器
            r_pix   <= in_pix;                          // ★ 彩色原图原样进寄存器（本模块不再运算）
            r_sof   <= in_sof;                          // ★ 帧首跟着一起走，绝不落下
            r_eol   <= in_eol;                          // ★ 行尾跟着一起走
            r_eof   <= in_eof;                          // ★ 帧尾跟着一起走
        end
    end

    //=====================================================================
    // 输出：全部取自寄存器，所以整体比输入晚 1 拍
    //=====================================================================
    assign out_pix   = r_pix;                           // 彩色像素（晚 1 拍）
    assign out_valid = r_valid;                         // valid（晚 1 拍，与像素同拍）
    assign out_sof   = r_sof;                           // 帧首（晚 1 拍，与像素同拍）
    assign out_eol   = r_eol;                           // 行尾（晚 1 拍，与像素同拍）
    assign out_eof   = r_eof;                           // 帧尾（晚 1 拍，与像素同拍）

endmodule
