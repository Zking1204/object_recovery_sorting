// dd_win3x3.v
//
//   第②级（底座）：3×3 窗口生成器 —— 行缓冲 + 邻域展开。
//
//   在定位流水线里的位置（由 defect_detect.v 例化）：
//       dd_gray ──► [dd_win3x3] ──► dd_median3 ──► dd_thresh ──► px_hit
//                      第②级           第③级          第⑤级
//
//   --------------------------------------------------------------------
//   本模块只干一件事：把"当前像素 + 周围 8 个邻居"在同一拍上凑齐
//   --------------------------------------------------------------------
//   它**不做任何运算** —— 不做中值、不做 Sobel、不做形态学。
//   运算交给后面的模块，本模块只负责"把 9 个数摆到桌面上"。
//   好处：中值、Sobel、形态学可以**并联吃同一个窗口**，共用这一套行缓冲，
//   后面每加一个邻域算法只需要多一个运算模块，不用再建第二套行缓冲。
//
//   --------------------------------------------------------------------
//   空间对齐：输出的是"上一行、左一列"为中心的那个窗口
//   --------------------------------------------------------------------
//            w00 w01 w02                        w00 = (r-2, c-2)
//            w10 w11 w12    ⇒                   w11 = (r-1, c-1) ← 窗口中心
//            w20 w21 w22                        w22 = (r  , c  )
//
//   （r, c）= **上一个被消费掉的输入像素**的坐标 ⇒ 窗口中心比输入像素
//   晚 "1 行 + 1 列"。这个"晚一行一列"是行缓冲天然带来的，不用另外对齐。
//
//   --------------------------------------------------------------------
//   ★★ 本模块延迟 **2 拍**（不是 1 行！）★★
//   --------------------------------------------------------------------
//   行缓冲只负责把**数据**延迟一行；valid/sof/eol/eof 这四根 sideband
//   **在输出侧就地生成**，所以只要跟流水打 2 拍（窗口级 1 拍 + 输出级 1 拍），
//   ★ 不需要 972 拍（一行）的延迟线，更不需要 1944 拍。
//   这是本模块最容易搞错的地方：一旦按"延迟一行"去凑 sideband，
//   空拍（反压）一出现就整幅错位，而且屏幕上完全看不出来，只能靠仿真抓。
//
//   --------------------------------------------------------------------
//   行缓冲怎么搭：4 个独立数组 + 行号低 2 位轮转
//   --------------------------------------------------------------------
//   3×3 窗口要同时拿到第 r、r-1、r-2 三行。
//   把行缓冲做成 **4 个独立的 1024×8 数组**：第 r 行写进 lb[r[1:0]]，
//   同时从 lb[(r-1)[1:0]] 和 lb[(r-2)[1:0]] 读出另外两行。
//       · 不用 3 个数组：是为了躲开"模 3 计数器"（3 不是 2 的幂，写起来别扭）
//       · 用 4 个而不是 2 个：让"正在写的数组"和"正在读的两个数组"
//         **永远不是同一个** ⇒ 天然没有读写冲突，不需要 READ_FIRST 之类的技巧
//   代价：4 个 1024×8 = 4 个 RAMB18 = 2 个 BRAM36，占全片 140 个的 1.4%。
//
//   --------------------------------------------------------------------
//   ★ 空拍（下游反压）怎么处理 —— 只冻结，不推进
//   --------------------------------------------------------------------
//   上游在反压时会把同一个像素重复送好几拍，那几拍 in_valid = 0，
//   最后一拍才 in_valid = 1。所以规则很简单：
//       **所有数据寄存器（含行缓冲的写地址）只在 in_valid 那一拍推进**，
//       空拍时全部冻结，行缓冲里的内容一个字节都不动。
//   而 sideband 走的是**无门控的 1 拍延迟**：
//       空拍期间冻结出来的那个"重复窗口"被 out_valid = 0 掩掉，
//       不会多算一个像素。两条规则配合，任何空拍图案都不会错位。
//
//   --------------------------------------------------------------------
//   边界怎么处理：**屏蔽**（out_valid = 0），不做边界复制
//   --------------------------------------------------------------------
//   帧首 2 行、行首 2 列拿不到完整的 3×3 邻域。本模块选择**直接不输出**，
//   而不是 BORDER_REPLICATE 复制边缘像素：
//       · 复制边缘会在图像四边造出"人造纹理"，正是假目标的温床
//       · 代价只有 (2 行 × 972 + 2 列 × 718) 个像素 ≈ 0.4%，可以忽略
//       · 屏幕上表现为二值图顶部 2 行、左侧 2 列是黑，看不出来
//
//   --------------------------------------------------------------------
//   注释规范（项目要求，2026-09-24）
//   --------------------------------------------------------------------
//       每一行有实际功能的代码，行尾都跟一条中文注释，说明"这行在做什么 / 为什么"。
//       本文件以 **UTF-8（无 BOM）** 编码保存。
//////////////////////////////////////////////////////////////////////////////

module dd_win3x3 (
    // ------------------------------------------------------------------
    // 时钟与复位
    // ------------------------------------------------------------------
    input  wire        clk,        // aclk，100MHz
    input  wire        rst_n,      // 低有效复位；只清控制寄存器，行缓冲数据不清

    // ------------------------------------------------------------------
    // 像素输入（来自 dd_gray，8 位灰度）
    // ------------------------------------------------------------------
    input  wire        in_valid,   // 本拍有有效像素
    input  wire [7:0]  in_pix,     // 本拍灰度值
    input  wire        in_sof,     // 帧首（顶层已带 valid 限定）
    input  wire        in_eol,     // 行尾（顶层已带 valid 限定）
    input  wire        in_eof,     // 帧尾（顶层已带 valid 限定）

    // ------------------------------------------------------------------
    // 3×3 窗口输出（比输入晚 2 拍）
    //   w00 w01 w02   第 r-2 行（上上行）
    //   w10 w11 w12   第 r-1 行（上一行），w11 是窗口中心
    //   w20 w21 w22   第 r   行（当前行）
    // ------------------------------------------------------------------
    output wire        out_valid,  // 本拍 9 个窗口值全部有效
    output wire        out_sof,    // 帧首：本拍是本帧第一个有效窗口
    output wire        out_eol,    // 行尾：本拍是本行最后一个有效窗口
    output wire        out_eof,    // 帧尾：本拍是本帧最后一个有效窗口
    output wire [7:0]  w00, w01, w02,   // 上上行的左二列 / 左一列 / 当前列
    output wire [7:0]  w10, w11, w12,   // 上一行的左二列 / 左一列 / 当前列
    output wire [7:0]  w20, w21, w22    // 当前行的左二列 / 左一列 / 当前列
);

    //=====================================================================
    // 一、行缓冲：4 个独立数组（1024 深 × 8 位，放得下 972 个有效像素）
    //
    //   (* ram_style = "block" *) 强制综合成 BRAM。
    //   不加这条，综合器可能推成分布式 RAM（吃 LUT）：一行 972×8 = 7776 个
    //   存储位，4 个数组下来会白吃掉几百个 LUT，而 BRAM 只用掉 4 个。
    //
    //   ★ 数据数组**不加复位**（下面 always 里也不复位它们）：
    //     BRAM 没有复位端，硬写复位会让综合器放弃 BRAM、退化成几万个 FF。
    //     数组内容帧间也不需要清 —— 帧首 2 行是靠 out_valid 屏蔽掉的，
    //     上一帧的残留值根本用不到。
    //   ★ 深度 1024 ≥ 972（一行有效像素数）。若将来行宽超过 1024，
    //     地址会回绕并静默出错，加宽数组前必须先改这里。
    //=====================================================================
    (* ram_style = "block" *) reg [7:0] lb0 [0:1023];   // 存行号 r ≡ 0 (mod 4) 的行
    (* ram_style = "block" *) reg [7:0] lb1 [0:1023];   // 存行号 r ≡ 1 (mod 4) 的行
    (* ram_style = "block" *) reg [7:0] lb2 [0:1023];   // 存行号 r ≡ 2 (mod 4) 的行
    (* ram_style = "block" *) reg [7:0] lb3 [0:1023];   // 存行号 r ≡ 3 (mod 4) 的行

    //=====================================================================
    // 二、行/列计数器 + 两个"边界标志"小计数器
    //
    //   row_cnt / col_cnt    ：真实坐标，col_cnt 同时兼作行缓冲的**写/读地址**
    //   rows_seen/cols_seen  ：2 位饱和计数器，专门判边界，**省比较器**
    //
    //   ★ 为什么用 2 位饱和计数器，而不是直接比较 row_cnt >= 2：
    //     比较 10 位数要 10 个 LUT；而"本行已经走过几个像素"饱和在 3 只要 2 位，
    //     "≥ 2" 就是取最高位 cols_seen[1] —— **0 个 LUT**。
    //     这是本模块唯一能省下来的比较器，别改回去。
    //=====================================================================
    reg [9:0] row_cnt;         // 帧内行号 0..719
    reg [9:0] col_cnt;         // 行内列号 0..971，同时是行缓冲地址
    reg [1:0] rows_seen;       // 本帧**已经走完**的行数，饱和在 3
    reg [1:0] cols_seen;       // 本行**已经走过**的像素数，饱和在 3

    always @(posedge clk) begin
        if (!rst_n) begin                               // 复位
            row_cnt   <= 10'd0;                         // 行号归零
            col_cnt   <= 10'd0;                         // 列号归零
            rows_seen <= 2'd0;                          // 一行都还没走完
            cols_seen <= 2'd0;                          // 一个像素都还没走
        end else if (in_valid) begin                    // ★ 只在有效像素拍推进，空拍全部冻结
            // ★★ 坐标系在**帧尾**清零，不在帧首清零 ★★（2026-10-04 被仿真抓出来的）
            //   计数器是在**时钟沿**更新的，更新出来的是"下一拍"要用的值。
            //   如果写在 in_sof 里，那么 sof 那一拍用的还是上一帧留下的列号，
            //   于是**含 sof 的那一整行**（每帧第 0 行）写入地址整体左移一列，
            //   ⇒ 只有"以第 0 行为上上行"的那一条输出行（中心行 1）整行错位，
            //   其余行全对 —— 屏幕上完全看不出来，只有仿真能抓。
            //   写在 in_eof 里就没这个问题：下一帧第一个像素天然拿到 (0,0)。
            if (in_eof) begin                           // 帧尾：整帧坐标系归零
                row_cnt   <= 10'd0;                     // 下一帧从第 0 行开始
                col_cnt   <= 10'd0;                     // 下一帧从第 0 列开始
                rows_seen <= 2'd0;                      // 边界计数器清零
                cols_seen <= 2'd0;                      // 边界计数器清零
            end else if (in_eol) begin                  // 行尾：本行结束
                row_cnt   <= row_cnt + 1'b1;            // 行号 +1（Verilog 自动补零扩展）
                col_cnt   <= 10'd0;                     // 下一拍从新行的第 0 列开始
                cols_seen <= 2'd0;                      // 新行重新数像素
                if (rows_seen != 2'd3) rows_seen <= rows_seen + 2'd1;   // 已走完行数 +1，饱和在 3
            end else begin                              // 行内普通像素
                col_cnt <= col_cnt + 1'b1;              // 列号 +1
                if (cols_seen != 2'd3) cols_seen <= cols_seen + 2'd1;   // 已走像素数 +1，饱和在 3
            end
        end
    end

    //=====================================================================
    // 三、行缓冲的写 / 读
    //
    //   写：本行像素写进 lb[row_cnt[1:0]]，地址就是当前列号。
    //   读：同时从 lb[(row_cnt-1) 的低 2 位] 读**上一行**同列，
    //           从 lb[(row_cnt-2) 的低 2 位] 读**上上行**同列。
    //   两个减法都写成 2 位宽，借位自然丢弃 ⇒ 等于取模回绕，正是轮转需要的。
    //
    //   BRAM 的读数据带一级输出寄存器 ⇒ 读到的值在**下一拍**才有效。
    //   所以这一级的寄存器都用 in_valid 门控，空拍时一起冻结。
    //
    //   ------------------------------------------------------------------
    //   ★★ 为什么四个数组要"各读各的"，而不是用一个 case 去选 ★★
    //      （2026-10-04 综合报告抓出来的，第一版就栽在这里）
    //
    //   第一版写成了"用 ra_sel / rb_sel 两个 case 去挑数组"：
    //       case (ra_sel) 2'd0: row_a_d <= lb0[col_cnt]; ...
    //       case (rb_sel) 2'd0: row_b_d <= lb0[col_cnt]; ...
    //   综合直接报：
    //       WARNING: [Synth 8-6849] Infeasible attribute ram_style = "block"
    //                ... trying to implement using LUTRAM
    //   原因不在时序、在**端口数**：这么写之后，每个数组都有可能被
    //   "读口 1" 或 "读口 2" 中的任意一个选中 ⇒ 综合器认为每个数组需要
    //   **2 个读口 + 1 个写口 = 3 端口**，而一块 BRAM 最多 2 个端口
    //   ⇒ 推不出 BRAM，只能退化成分布式 RAM。
    //   实测代价：4 个数组一共吃掉 **512 个 LUT**（报告里 LUT as Memory = 512）。
    //
    //   修法：**每个数组只接一个属于自己的读口** —— 四个数组同时读同一列，
    //   读完再拿寄存器里的数据做 4 选 1。这样每个数组就是标准的
    //   "1 写口 + 1 读口" ⇒ BRAM 推得出来 ⇒ 4 个 RAMB18、LUT 花 0 个。
    //   代价：多 4 个 8 位读数据寄存器（32 个 FF）换掉 512 个 LUT，非常划算。
    //
    //   ★ 选择信号必须**跟着数据一起打一拍**：
    //     rdN 是第 E 拍读出来的，选它的 ra_sel/rb_sel 也必须用第 E 拍的值。
    //     行尾那一拍 row_cnt 会 +1（ra_sel 跟着变），若直接拿"当前"的 ra_sel
    //     去选，每行最后一个像素就会选错数组。所以 ra_sel_d / rb_sel_d 要打一拍。
    //=====================================================================
    wire [1:0] wr_sel = row_cnt[1:0];                   // 本行写哪个数组
    wire [1:0] ra_sel = row_cnt[1:0] - 2'd1;            // 上一行在哪个数组（2 位减法自然回绕）
    wire [1:0] rb_sel = row_cnt[1:0] - 2'd2;            // 上上行在哪个数组

    reg [7:0] rd0, rd1, rd2, rd3;                       // 四个数组各自的读数据寄存器（每数组 1 个读口）
    reg [1:0] ra_sel_d, rb_sel_d;                       // 读数据对应的数组选择，跟数据一起打一拍
    reg [7:0] row_c_d;                                  // 本行、第 c 列的像素（打 1 拍与两路读对齐）

    // 上一行、第 c 列的像素：纯组合的 4 选 1，取的是**上一拍读出来**的数据
    wire [7:0] row_a_d = (ra_sel_d == 2'd0) ? rd0 :     // 上一行存在 lb0
                         (ra_sel_d == 2'd1) ? rd1 :     // 上一行存在 lb1
                         (ra_sel_d == 2'd2) ? rd2 : rd3;// 上一行存在 lb2 / lb3

    // 上上行、第 c 列的像素：同样纯组合 4 选 1
    wire [7:0] row_b_d = (rb_sel_d == 2'd0) ? rd0 :     // 上上行存在 lb0
                         (rb_sel_d == 2'd1) ? rd1 :     // 上上行存在 lb1
                         (rb_sel_d == 2'd2) ? rd2 : rd3;// 上上行存在 lb2 / lb3

    always @(posedge clk) begin
        if (in_valid) begin                             // ★ 只在有效像素拍推进
            case (wr_sel)                               // 写：按行号低 2 位选数组
                2'd0:    lb0[col_cnt] <= in_pix;        // 行号 ≡ 0 写 lb0
                2'd1:    lb1[col_cnt] <= in_pix;        // 行号 ≡ 1 写 lb1
                2'd2:    lb2[col_cnt] <= in_pix;        // 行号 ≡ 2 写 lb2
                2'd3:    lb3[col_cnt] <= in_pix;        // 行号 ≡ 3 写 lb3
                default: lb0[col_cnt] <= in_pix;        // 兜底（2 位不会走到这里）
            endcase
            rd0 <= lb0[col_cnt];                        // 四个数组同时读同一列（各用各的读口）
            rd1 <= lb1[col_cnt];                        // —— 读口固定，BRAM 才推得出来
            rd2 <= lb2[col_cnt];                        // …
            rd3 <= lb3[col_cnt];                        // …
            ra_sel_d <= ra_sel;                         // 选择信号跟数据一起打一拍（行尾会变，必须延迟）
            rb_sel_d <= rb_sel;                         // …
            row_c_d  <= in_pix;                         // 本行像素打 1 拍，与两路读同拍
        end
    end

    //=====================================================================
    // 四、列方向延迟链：每行再取出"左一列""左二列"
    //
    //   上面三路给出的都是**第 c 列**（c = 上一个被消费像素的列号），
    //   再各接一条 2 级移位链，就同时拿到第 c 列、c-1 列、c-2 列。
    //
    //   ★ 这里每行只花 2 个寄存器，不能多打：
    //     上面三路本身已经是寄存器输出（BRAM 输出寄存器 / row_c_d），
    //     它们**就是**第 c 列；再串 1 拍 = 左一列，串 2 拍 = 左二列。
    //     多打一拍窗口中心会整体偏一列，而且全部对齐关系要重新推。
    //=====================================================================
    reg [7:0] a1, a2;       // 上一行：左一列、左二列
    reg [7:0] b1, b2;       // 上上行：左一列、左二列
    reg [7:0] c1, c2;       // 本行  ：左一列、左二列

    always @(posedge clk) begin
        if (in_valid) begin                             // ★ 同样只在有效像素拍推进
            a1 <= row_a_d;   a2 <= a1;                  // 上一行的列延迟链（2 级）
            b1 <= row_b_d;   b2 <= b1;                  // 上上行的列延迟链（2 级）
            c1 <= row_c_d;   c2 <= c1;                  // 本行的列延迟链（2 级）
        end
    end

    //=====================================================================
    // 五、窗口输出（第 1 级）：9 个值都取自寄存器
    //     w11 是窗口中心 = (r-1, c-1)
    //=====================================================================
    wire [7:0] p_w00 = b2;        // (r-2, c-2) 上上行 · 左二列
    wire [7:0] p_w01 = b1;        // (r-2, c-1) 上上行 · 左一列
    wire [7:0] p_w02 = row_b_d;   // (r-2, c  ) 上上行 · 当前列
    wire [7:0] p_w10 = a2;        // (r-1, c-2) 上一行 · 左二列
    wire [7:0] p_w11 = a1;        // (r-1, c-1) 上一行 · 左一列  ← 窗口中心
    wire [7:0] p_w12 = row_a_d;   // (r-1, c  ) 上一行 · 当前列
    wire [7:0] p_w20 = c2;        // (r  , c-2) 当前行 · 左二列
    wire [7:0] p_w21 = c1;        // (r  , c-1) 当前行 · 左一列
    wire [7:0] p_w22 = row_c_d;   // (r  , c  ) 当前行 · 当前列

    //=====================================================================
    // 六、输出 sideband（第 1 级）+ ★ 输出寄存器（第 2 级）★
    //
    //   ★ 为什么窗口在"吃下像素的下一拍"就齐了：
    //     BRAM 读数据那 1 拍延迟 + 列延迟链都在同一个时钟沿完成。
    //     行缓冲那 972 拍的**行**延迟不落在 sideband 上 ——
    //     它是靠"窗口中心比输入晚一行一列"这个空间关系隐含掉的。
    //
    //   ★★ 边界标志必须在**输入侧**算好再打拍 ★★
    //     窗口是在"吃下像素的下一拍"才出现的，那时候 row_cnt/col_cnt
    //     已经往前走了，直接用当前计数器判会**错一拍**。
    //     所以：在输入那一拍用当时的行列号判边界，再跟 valid 一起打 1 拍。
    //
    //   ------------------------------------------------------------------
    //   ★★ 为什么还要再加一级输出寄存器 ★★
    //      （2026-10-04，被布线后的时序报告逼出来的，改完 Slack 从 0.103 回到 1+）
    //
    //   第一版把 9 根窗口线**直接**接到 dd_median3 的比较器上，于是
    //   clk_fpga_0 域的最差路径变成：
    //       RAMB18 的 CLK→DOADO 2.454ns
    //         → 4 选 1 多路选择 + 长走线 1.203ns
    //         → 三数排序 比较器① → ② → ③（进位链）约 5.0ns
    //         → 寄存器
    //     合计 **9.712ns**（要求 10ns），Slack 只剩 **0.103ns**；
    //     整条路径 **57.9% 是走线** —— 因为行缓冲的慢输出直接串进一整串
    //     比较器，综合器只好把它们摆得七零八落。
    //
    //   根子就是**这一级之间没有寄存器边界**。加一级输出寄存器后，路径被切成：
    //       RAMB18 → 4 选 1 → 【寄存器】      ≈ 3.8ns
    //       【寄存器】→ 三数排序 3 个比较器    ≈ 4~5ns
    //   两段都宽裕，而且综合器可以把中值那一堆比较器自由地摆到一起。
    //   代价：9×8 + 4 = 76 个 FF，总延迟 +1 拍（本模块由 1 拍变 **2 拍**）。
    //
    //   ★ 通用规律（写下一级时照做）：**让存储器/长走线的输出先过一级寄存器，
    //     再进组合算法**。存储器件的 CLK→Q 本身就要 2ns 上下，等于白送掉
    //     1/5 个周期，后面不能再接长组合链。
    //=====================================================================
    wire in_ok    = in_valid & cols_seen[1] & rows_seen[1];                 // 本拍像素有完整的 3×3 邻域
    wire in_first = in_valid & (cols_seen == 2'd2) & (rows_seen == 2'd2);  // 本帧第一个有效窗口（第 2 行第 2 列）

    reg v1, ok1, first1;                                // 第 1 级 sideband：1 拍延迟
    reg eol1, eof1;                                     // 第 1 级 sideband：行尾 / 帧尾

    always @(posedge clk) begin
        if (!rst_n) begin                               // 复位
            v1     <= 1'b0;                             // 无有效输出
            ok1    <= 1'b0;                             // 边界不满足
            first1 <= 1'b0;                             // 非帧首
            eol1   <= 1'b0;                             // 非行尾
            eof1   <= 1'b0;                             // 非帧尾
        end else begin                                  // ★ 不门控：空拍也要照常往前走一拍
            v1     <= in_valid;                         // valid 打 1 拍
            ok1    <= in_ok;                            // 边界标志打 1 拍，与窗口对齐
            first1 <= in_first;                         // 帧首标志打 1 拍
            eol1   <= in_eol;                           // 行尾打 1 拍（本行最后一个窗口和本行同时在下一拍结束）
            eof1   <= in_eof;                           // 帧尾打 1 拍（本帧最后一个窗口和本帧同时在下一拍结束）
        end
    end

    // ---- 第 2 级：输出寄存器（★ 与后面的组合算法之间必须有这一级）----
    reg [7:0] o_w00, o_w01, o_w02;                      // 输出窗口 · 上上行
    reg [7:0] o_w10, o_w11, o_w12;                      // 输出窗口 · 上一行（o_w11 = 中心）
    reg [7:0] o_w20, o_w21, o_w22;                      // 输出窗口 · 当前行
    reg       o_v, o_sof, o_eol, o_eof;                 // 输出的四根 sideband

    always @(posedge clk) begin
        if (!rst_n) begin                               // 复位：全部清零，仿真一上电就是确定值
            o_w00 <= 8'd0; o_w01 <= 8'd0; o_w02 <= 8'd0;    // 上上行清零
            o_w10 <= 8'd0; o_w11 <= 8'd0; o_w12 <= 8'd0;    // 上一行清零
            o_w20 <= 8'd0; o_w21 <= 8'd0; o_w22 <= 8'd0;    // 当前行清零
            o_v   <= 1'b0; o_sof <= 1'b0; o_eol <= 1'b0; o_eof <= 1'b0;  // sideband 清零
        end else if (v1 & ok1) begin                    // ★ 只在第 1 级真有窗口时推进（空拍冻结）
            o_w00 <= p_w00; o_w01 <= p_w01; o_w02 <= p_w02;     // 窗口 9 个值一起进寄存器
            o_w10 <= p_w10; o_w11 <= p_w11; o_w12 <= p_w12;     // …
            o_w20 <= p_w20; o_w21 <= p_w21; o_w22 <= p_w22;     // …
            o_v    <= 1'b1;                             // 有窗口 ⇒ 输出 valid
            o_sof  <= first1;                           // 帧首：只在本帧第一个有效窗口上拉高
            o_eol  <= eol1;                             // 行尾
            o_eof  <= eof1;                             // 帧尾
        end else begin                                  // 本拍没有有效窗口
            o_v    <= 1'b0;                             // valid 拉低（其余寄存器保持，反正被掩掉了）
            o_sof  <= 1'b0;                             // 非帧首
            o_eol  <= 1'b0;                             // 非行尾
            o_eof  <= 1'b0;                             // 非帧尾
        end
    end

    //=====================================================================
    // 七、输出：全部取自第 2 级寄存器 ⇒ 整体比输入晚 **2 拍**
    //=====================================================================
    assign w00 = o_w00;     // (r-2, c-2) 上上行 · 左二列
    assign w01 = o_w01;     // (r-2, c-1) 上上行 · 左一列
    assign w02 = o_w02;     // (r-2, c  ) 上上行 · 当前列
    assign w10 = o_w10;     // (r-1, c-2) 上一行 · 左二列
    assign w11 = o_w11;     // (r-1, c-1) 上一行 · 左一列  ← 窗口中心
    assign w12 = o_w12;     // (r-1, c  ) 上一行 · 当前列
    assign w20 = o_w20;     // (r  , c-2) 当前行 · 左二列
    assign w21 = o_w21;     // (r  , c-1) 当前行 · 左一列
    assign w22 = o_w22;     // (r  , c  ) 当前行 · 当前列
    assign out_valid = o_v;                 // 本拍 9 个窗口值全部有效
    assign out_sof   = o_sof;               // 帧首（本帧第一个有效窗口）
    assign out_eol   = o_eol;               // 行尾（本行最后一个有效窗口）
    assign out_eof   = o_eof;               // 帧尾（本帧最后一个有效窗口）

endmodule
