// dd_median3.v
//
//   第③级：3×3 中值滤波（19 比较器排序网络，3 级流水）。
//
//   在定位流水线里的位置（由 defect_detect.v 例化）：
//       dd_gray ──► dd_win3x3 ──► [dd_median3] ──► dd_thresh ──► px_hit
//                      第②级          第③级           第⑤级
//
//   --------------------------------------------------------------------
//   这一级是干嘛的 / 它的作用 / 它的重要性
//   --------------------------------------------------------------------
//   【干嘛的】把 3×3 窗口里 9 个灰度值排序，输出**中间那个**（第 5 大）。
//   【作用】① 消掉孤立噪点：一个比周围亮/暗的点，在 9 个数里排不进中间，
//             会被直接扔掉 ⇒ 椒盐噪声、单像素坏点、sensor 热噪声全没了；
//           ② 它是一个"局部背景亮度估计器"——中值是抗噪的邻域亮度，
//             第④级局部自适应阈值要拿它当"附近本该有多亮"的基准。
//   【重要性】**不是可有可无的装饰**，原因有三：
//       1) 全局单阈值最怕的就是孤立噪点 —— 一个噪点就是一个假目标，
//          屏幕上就是一粒白点。中值是 PL 侧最便宜的去假目标手段
//          （形态学更贵，而且要二值化之后才能做）。
//       2) 它是第④级（局部自适应阈值）的**前置条件**：没有它，
//          "附近亮度"就只能拿原始窗口的均值算，而均值会被目标本身污染
//          （目标正好在窗口里 ⇒ 均值被拉偏 ⇒ 阈值跟着跑 ⇒ 检不出来）。
//          中值不怕污染：9 个数里坏掉 4 个，中值仍然是背景。
//       3) 它**不能替代其他级**：中值只处理"孤立"的异常，对成片的目标
//          （大面积区域）完全无效，因为它不会改变连成一片的区域。
//
//   --------------------------------------------------------------------
//   ★ 中值的副作用：3.6 像素以下的小目标会被抹掉 ★
//   --------------------------------------------------------------------
//   0.3 mm 的目标在 83 µm/px 下只占 3.6 像素。9 个数的窗口里，
//   目标像素如果只有 4 个、背景 5 个 ⇒ 中值取到背景 ⇒ **目标中心被抹平**。
//   所以本模块带一个**旁路开关** cfg_med_en（顶层 DEF_TH[2]）：
//       关掉 = 直接吐窗口中心像素 w11（保细节，但噪点全在）
//       打开 = 吐中值        （干净，但小目标可能丢）
//   目的：一次上板就能 A/B 对比，用实测数据决定留哪个，不用重编位流。
//
//   --------------------------------------------------------------------
//   ★★ 为什么是 19 个比较器，而不是"把 9 个数全排序" ★★
//   --------------------------------------------------------------------
//   全排序（插入排序）要 25~30 个比较器。3×3 中值有公认的更省结构：
//       ① 每行 3 个数各自排序 ⇒ 得到 (min, med, max)，每行 3 个比较器，共 9 个
//       ② 取  A = 三个 min 的**最大**者
//              B = 三个 med 的**中位**者
//              C = 三个 max 的**最小**者          —— 共 7 个比较器
//       ③ 中值 = median(A, B, C)                 —— 3 个比较器（三数排序取中间）
//   合计 **19 个比较器**，而且结果是精确的（不是近似）。
//   这个结构在文献里叫"中值滤波网络"（Smith 网络 / Paar 网络），
//   是 3×3 中值公认的最省实现之一。
//
//   --------------------------------------------------------------------
//   ★ 省逻辑单元的三个做法（本文件都用了）★
//   --------------------------------------------------------------------
//   ① **比较结果只算一次**：每个比较交换写成
//          wire lt = (a < b);  lo = lt ? a : b;  hi = lt ? b : a;
//      而不是写两个独立的 min/max 表达式 —— 后者要靠综合器自己去识别
//      公共子表达式，不保证。显式写 lt 最保险，一个比较交换只需 1 个比较器。
//   ② **位宽永远是 8 位**：中值不改变数值范围，任何中间量都不许扩位。
//      扩到 9 位会让后面每个比较器、每个多路选择器都白涨 12%。
//   ③ **0 个 DSP**：全是比较器 + 多路选择器，没有乘法、没有加法。
//      实测整套中值 ≈ 400~500 个 LUT、约 130 个 FF。
//
//   --------------------------------------------------------------------
//   ★ 为什么切成 3 级流水（用户要求：模块之间必须有寄存器隔断）★
//   --------------------------------------------------------------------
//   如果不打拍，最长组合路径 = 3 个比较交换串联（约 9 层 LUT + 进位链），
//   在 100MHz（10ns）下非常危险。切成 3 级之后：
//       第 1 级：3 个三数排序，深度 3 个比较交换   → 打拍
//       第 2 级：max3 / median3 / min3，深度 3     → 打拍
//       第 3 级：三数排序取中间，深度 3            → 打拍
//   每级都是"寄存器进、寄存器出"，单级深度 ≤3，对 1.479ns 的域余量很安全。
//
//   --------------------------------------------------------------------
//   延迟与 sideband
//   --------------------------------------------------------------------
//   本模块延迟 **3 拍**。五根 sideband（valid/sof/eol/eof）跟着一起打 3 拍，
//   所以下游永远能用"本级的 sideband"配"本级的像素"，不会错位。
//   和 dd_gray 一样，这里的寄存器**不做 in_valid 门控**：本模块没有存储器，
//   空拍（反压）让它自然流过去就行，输出那一拍 valid 自然是 0。
//
//   --------------------------------------------------------------------
//   注释规范（项目要求，2026-09-24）
//   --------------------------------------------------------------------
//       每一行有实际功能的代码，行尾都跟一条中文注释，说明"这行在做什么 / 为什么"。
//       本文件以 **UTF-8（无 BOM）** 编码保存。
//////////////////////////////////////////////////////////////////////////////

module dd_median3 (
    // ------------------------------------------------------------------
    // 时钟与复位
    // ------------------------------------------------------------------
    input  wire        clk,        // aclk，100MHz
    input  wire        rst_n,      // 低有效复位

    // ------------------------------------------------------------------
    // 窗口输入（来自 dd_win3x3，共 9 个 8 位灰度）
    //   w00 w01 w02   上上行
    //   w10 w11 w12   上一行（w11 = 窗口中心）
    //   w20 w21 w22   当前行
    // ------------------------------------------------------------------
    input  wire [7:0]  w00, w01, w02,   // 上上行的左二列 / 左一列 / 当前列
    input  wire [7:0]  w10, w11, w12,   // 上一行的左二列 / 左一列 / 当前列（w11 是中心）
    input  wire [7:0]  w20, w21, w22,   // 当前行的左二列 / 左一列 / 当前列
    input  wire        in_valid,   // 本拍窗口有效
    input  wire        in_sof,     // 帧首（已带 valid 限定）
    input  wire        in_eol,     // 行尾（已带 valid 限定）
    input  wire        in_eof,     // 帧尾（已带 valid 限定）

    // ------------------------------------------------------------------
    // 控制（来自顶层 AXI-Lite 寄存器 DEF_TH[2]）
    // ------------------------------------------------------------------
    input  wire        cfg_med_en, // 1 = 输出中值；0 = 旁路，输出窗口中心 w11

    // ------------------------------------------------------------------
    // 输出（比输入晚 3 拍）
    // ------------------------------------------------------------------
    output wire        out_valid,  // 与 out_pix 同拍
    output wire [7:0]  out_pix,    // 中值（或旁路时的窗口中心）
    output wire        out_sof,    // 帧首，晚 3 拍
    output wire        out_eol,    // 行尾，晚 3 拍
    output wire        out_eof     // 帧尾，晚 3 拍
);

    //=====================================================================
    // 参数锁存：中值使能只在**帧首**更新，**而且还要再延迟 1 拍**
    //
    //   和 dd_thresh 一个道理：PS 随时可能改这个位，如果直接用组合值，
    //   改的那一拍会落在画面中间 ⇒ 同一帧上半部分启用中值、下半部分旁路
    //   ⇒ 画面中间出现一条"突变线"。锁存到帧首就没有这个问题。
    //
    //   ★★ 但这里比 dd_thresh 多一条：**锁存值必须跟着数据往下走 1 拍** ★★
    //   （2026-10-04 被 tb_dd_median3.v 抓出来的，只错 3 个像素/3 次切换）
    //
    //     差别在于"用到这个控制信号的位置"离输入有多远：
    //       dd_thresh 的比较器就在**输入端**，帧首那一拍锁存、同一拍就用 ⇒ 对齐；
    //       本模块的旁路多路选择在**输出级**（第 3 级），比输入晚 2 拍。
    //     于是：帧首那一拍锁存的新值，会被"sof **前一个**像素"用上 ——
    //     那个像素其实还属于上一帧，本该用**旧**使能 ⇒ 每帧边界错 1 个像素。
    //     屏幕上完全看不出来，只有 tb 逐像素比对才抓得到。
    //
    //     修法：en_cur 再打 1 拍成 en_d1，多路选择器用 en_d1。
    //       窗口在第 E 拍被吃进 ⇒ 多路选择器在第 E+1 拍做选择 ⇒
    //       E+1 拍看到的 en_d1 正好是"第 E 拍锁存下来的那个值" ✓
    //
    //   ★ 通用规律：**控制信号要和它作用的**那一级数据**对齐**，
    //     不是和帧首对齐。控制信号在流水线里走到第几级，就延迟到第几级。
    //=====================================================================
    reg en_cur;                                         // 帧首锁存下来的中值使能
    reg en_d1;                                          // 再延迟 1 拍，与输出级的多路选择器对齐

    always @(posedge clk) begin
        if (!rst_n) begin
            en_cur <= 1'b0;                             // 复位后默认旁路（与旧行为一致，安全）
            en_d1  <= 1'b0;                             // 延迟副本也清零
        end else begin
            if (in_sof) en_cur <= cfg_med_en;           // 帧首更新，一帧内保持不变
            en_d1 <= en_cur;                            // ★ 跟着数据往下走一拍（不门控）
        end
    end

    //=====================================================================
    // ============ 第 1 级：三行各自排序（9 个比较器）============
    //
    //   每个"比较交换"（compare-exchange）= 1 个 8 位比较器 + 2 个 8 位 2:1 多路选择器。
    //   三数排序(x, y, z)的标准写法（排序网络）：
    //       cmp1: (x, y)  → lo1, hi1
    //       cmp2: (lo1, z) → lo2(=min), m
    //       cmp3: (hi1, m) → med, hi2(=max)
    //   输出 lo2 / med / hi2 就是 min / med / max，只用 3 个比较器。
    //=====================================================================

    // ---------- 第 0 行：w00 w01 w02 ----------
    wire       lt_0a = (w00 < w01);                     // 比较器①（结果给下面两个多路选择器共用）
    wire [7:0] e0a_lo = lt_0a ? w00 : w01;              // 较小者
    wire [7:0] e0a_hi = lt_0a ? w01 : w00;              // 较大者
    wire       lt_0b = (e0a_lo < w02);                  // 比较器②
    wire [7:0] r0_min = lt_0b ? e0a_lo : w02;           // 三个数的最小值
    wire [7:0] e0b_m  = lt_0b ? w02 : e0a_lo;           // 中间量（还没定序）
    wire       lt_0c = (e0a_hi < e0b_m);                // 比较器③
    wire [7:0] r0_med = lt_0c ? e0a_hi : e0b_m;         // 三个数的中位值
    wire [7:0] r0_max = lt_0c ? e0b_m : e0a_hi;         // 三个数的最大值

    // ---------- 第 1 行：w10 w11 w12 ----------
    wire       lt_1a = (w10 < w11);                     // 比较器④
    wire [7:0] e1a_lo = lt_1a ? w10 : w11;              // 较小者
    wire [7:0] e1a_hi = lt_1a ? w11 : w10;              // 较大者
    wire       lt_1b = (e1a_lo < w12);                  // 比较器⑤
    wire [7:0] r1_min = lt_1b ? e1a_lo : w12;           // 最小值
    wire [7:0] e1b_m  = lt_1b ? w12 : e1a_lo;           // 中间量
    wire       lt_1c = (e1a_hi < e1b_m);                // 比较器⑥
    wire [7:0] r1_med = lt_1c ? e1a_hi : e1b_m;         // 中位值
    wire [7:0] r1_max = lt_1c ? e1b_m : e1a_hi;         // 最大值

    // ---------- 第 2 行：w20 w21 w22 ----------
    wire       lt_2a = (w20 < w21);                     // 比较器⑦
    wire [7:0] e2a_lo = lt_2a ? w20 : w21;              // 较小者
    wire [7:0] e2a_hi = lt_2a ? w21 : w20;              // 较大者
    wire       lt_2b = (e2a_lo < w22);                  // 比较器⑧
    wire [7:0] r2_min = lt_2b ? e2a_lo : w22;           // 最小值
    wire [7:0] e2b_m  = lt_2b ? w22 : e2a_lo;           // 中间量
    wire       lt_2c = (e2a_hi < e2b_m);                // 比较器⑨
    wire [7:0] r2_med = lt_2c ? e2a_hi : e2b_m;         // 中位值
    wire [7:0] r2_max = lt_2c ? e2b_m : e2a_hi;         // 最大值

    //=====================================================================
    // ★ 流水寄存器第 1 级（用户要求：模块内也要有寄存器隔断）
    //   把第 1 级的 9 个结果 + 旁路要用的窗口中心 + 4 根 sideband 一起打拍。
    //   五根信号（像素类 + sideband）**无条件一起打拍**，绝不落下任何一根。
    //=====================================================================
    reg [7:0] s1_r0min, s1_r0med, s1_r0max;             // 第 0 行排序结果
    reg [7:0] s1_r1min, s1_r1med, s1_r1max;             // 第 1 行排序结果
    reg [7:0] s1_r2min, s1_r2med, s1_r2max;             // 第 2 行排序结果
    reg [7:0] s1_ctr;                                   // 窗口中心 w11（旁路用），跟着一起延迟
    reg       s1_v, s1_sof, s1_eol, s1_eof;             // 第 1 级的 sideband

    always @(posedge clk) begin
        if (!rst_n) begin                               // 复位：全部清零，仿真一上电就是确定值
            s1_r0min <= 8'd0; s1_r0med <= 8'd0; s1_r0max <= 8'd0;   // 第 0 行清零
            s1_r1min <= 8'd0; s1_r1med <= 8'd0; s1_r1max <= 8'd0;   // 第 1 行清零
            s1_r2min <= 8'd0; s1_r2med <= 8'd0; s1_r2max <= 8'd0;   // 第 2 行清零
            s1_ctr   <= 8'd0;                           // 中心像素清零
            s1_v <= 1'b0; s1_sof <= 1'b0; s1_eol <= 1'b0; s1_eof <= 1'b0;   // sideband 清零
        end else begin                                  // ★ 不门控：空拍自然流过去，靠 valid 标记
            s1_r0min <= r0_min; s1_r0med <= r0_med; s1_r0max <= r0_max;     // 第 0 行排序结果进寄存器
            s1_r1min <= r1_min; s1_r1med <= r1_med; s1_r1max <= r1_max;     // 第 1 行排序结果进寄存器
            s1_r2min <= r2_min; s1_r2med <= r2_med; s1_r2max <= r2_max;     // 第 2 行排序结果进寄存器
            s1_ctr   <= w11;                            // 窗口中心跟着走（旁路分支要用）
            s1_v   <= in_valid;                         // sideband 一起打拍
            s1_sof <= in_sof;                           // …
            s1_eol <= in_eol;                           // …
            s1_eof <= in_eof;                           // …
        end
    end

    //=====================================================================
    // ============ 第 2 级：跨行归并（7 个比较器）============
    //
    //   A = 三个 min 里的最大值    （比较器⑩⑪）
    //   C = 三个 max 里的最小值    （比较器⑫⑬）
    //   B = 三个 med 的中位值      （比较器⑭⑮⑯，三数排序取中间）
    //   这三个量把中值的候选范围一次缩到 3 个，第 3 级只要再比 3 次。
    //=====================================================================

    // ---------- A = max(r0_min, r1_min, r2_min) ----------
    wire       lt_A1 = (s1_r0min < s1_r1min);           // 比较器⑩
    wire [7:0] A_mx = lt_A1 ? s1_r1min : s1_r0min;      // 前两个里较大的
    wire       lt_A2 = (A_mx < s1_r2min);               // 比较器⑪
    wire [7:0] n_A  = lt_A2 ? s1_r2min : A_mx;          // 三个 min 的最大者

    // ---------- C = min(r0_max, r1_max, r2_max) ----------
    wire       lt_C1 = (s1_r0max < s1_r1max);           // 比较器⑫
    wire [7:0] C_mn = lt_C1 ? s1_r0max : s1_r1max;      // 前两个里较小的
    wire       lt_C2 = (C_mn < s1_r2max);               // 比较器⑬
    wire [7:0] n_C  = lt_C2 ? C_mn : s1_r2max;          // 三个 max 的最小者

    // ---------- B = median(r0_med, r1_med, r2_med) ----------
    wire       lt_B1 = (s1_r0med < s1_r1med);           // 比较器⑭
    wire [7:0] B_lo = lt_B1 ? s1_r0med : s1_r1med;      // 较小者
    wire [7:0] B_hi = lt_B1 ? s1_r1med : s1_r0med;      // 较大者
    wire       lt_B2 = (B_lo < s1_r2med);               // 比较器⑮
    wire [7:0] B_m  = lt_B2 ? s1_r2med : B_lo;          // 三数排序的中间量
    wire       lt_B3 = (B_hi < B_m);                    // 比较器⑯
    wire [7:0] n_B  = lt_B3 ? B_hi : B_m;               // 三个 med 的中位者

    //=====================================================================
    // ★ 流水寄存器第 2 级
    //   第 2 级只剩 3 个值 + 中心像素 + 4 根 sideband，寄存器数量骤降。
    //=====================================================================
    reg [7:0] s2_a, s2_b, s2_c;                         // A / B / C 三个候选
    reg [7:0] s2_ctr;                                   // 窗口中心 w11（第 2 次延迟）
    reg       s2_v, s2_sof, s2_eol, s2_eof;             // 第 2 级的 sideband

    always @(posedge clk) begin
        if (!rst_n) begin                               // 复位清零
            s2_a <= 8'd0; s2_b <= 8'd0; s2_c <= 8'd0;   // 三个候选清零
            s2_ctr <= 8'd0;                             // 中心像素清零
            s2_v <= 1'b0; s2_sof <= 1'b0; s2_eol <= 1'b0; s2_eof <= 1'b0;   // sideband 清零
        end else begin                                  // ★ 同样不门控
            s2_a <= n_A;                                // A 进寄存器
            s2_b <= n_B;                                // B 进寄存器
            s2_c <= n_C;                                // C 进寄存器
            s2_ctr <= s1_ctr;                           // 中心像素跟着延迟
            s2_v   <= s1_v;                             // sideband 一起打拍
            s2_sof <= s1_sof;                           // …
            s2_eol <= s1_eol;                           // …
            s2_eof <= s1_eof;                           // …
        end
    end

    //=====================================================================
    // ============ 第 3 级：三数排序取中间（3 个比较器）============
    //   中值 = median(A, B, C)，还是用"三数排序取中间"那套。
    //=====================================================================
    wire       lt_D1 = (s2_a < s2_b);                   // 比较器⑰
    wire [7:0] D_lo = lt_D1 ? s2_a : s2_b;              // 较小者
    wire [7:0] D_hi = lt_D1 ? s2_b : s2_a;              // 较大者
    wire       lt_D2 = (D_lo < s2_c);                   // 比较器⑱
    wire [7:0] D_m  = lt_D2 ? s2_c : D_lo;              // 三数排序的中间量
    wire       lt_D3 = (D_hi < D_m);                    // 比较器⑲
    wire [7:0] med_val = lt_D3 ? D_hi : D_m;            // ★ 3×3 中值（19 个比较器的结果）

    //=====================================================================
    // ★ 流水寄存器第 3 级（输出级）：旁路多路选择 + 打拍
    //
    //   旁路选择放在**寄存器之前**：多路选择器输出直接进寄存器，
    //   所以这一级只多 1 个 LUT 级，不会把中值的组合链拉长。
    //   s2_ctr 是窗口中心 w11 延迟 2 级的结果，和 med_val 同拍 ⇒ 可以直接选。
    //   ★ 选择信号用 en_d1（不是 en_cur）：见文件上面"参数锁存"那段的推导。
    //=====================================================================
    reg [7:0] o_pix;                                    // 输出像素
    reg       o_v, o_sof, o_eol, o_eof;                 // 输出的 sideband

    always @(posedge clk) begin
        if (!rst_n) begin                               // 复位清零
            o_pix <= 8'd0;                              // 输出像素清零
            o_v <= 1'b0; o_sof <= 1'b0; o_eol <= 1'b0; o_eof <= 1'b0;   // sideband 清零
        end else begin                                  // ★ 不门控
            o_pix <= en_d1 ? med_val : s2_ctr;          // 使能则输出中值，否则旁路输出窗口中心
            o_v   <= s2_v;                              // sideband 一起打第 3 拍
            o_sof <= s2_sof;                            // …
            o_eol <= s2_eol;                            // …
            o_eof <= s2_eof;                            // …
        end
    end

    //=====================================================================
    // 输出：全部取自寄存器 ⇒ 整体比输入晚 3 拍
    //=====================================================================
    assign out_pix   = o_pix;                           // 中值（或旁路时的窗口中心）
    assign out_valid = o_v;                             // 与 out_pix 同拍
    assign out_sof   = o_sof;                           // 帧首，晚 3 拍
    assign out_eol   = o_eol;                           // 行尾，晚 3 拍
    assign out_eof   = o_eof;                           // 帧尾，晚 3 拍

endmodule
