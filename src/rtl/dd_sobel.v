// dd_sobel.v
//
//   第③级（支路 B）：Sobel 边缘检测 + 梯度阈值二值化。
//
//   在定位流水线里的位置（由 defect_detect.v 例化）：
//                        ┌─ dd_median3 ─► dd_thresh ─┐
//       dd_win3x3 ───────┤   （支路 A：灰度/面）      ├─ OR ─► px_hit
//                        └─ [dd_sobel] ──────────────┘
//                            （支路 B：边缘/线）
//
//   --------------------------------------------------------------------
//   这一级是干嘛的 / 它的作用 / 它的重要性
//   --------------------------------------------------------------------
//   【干嘛的】算每个像素的"变化率"（梯度）：和左右邻居的差 = Gx，
//             和上下邻居的差 = Gy，两者一合成就是"这一点有多像一条边"。
//   【作用】把判定依据从"这一点有多亮"换成"这一点和旁边差多少"。
//           一整块均匀的放置物，不管整体亮暗，梯度都 ≈0 ⇒ 不报警；
//           一条细细线两侧的像素差很大 ⇒ 梯度很大 ⇒ 报警。
//   【重要性】★ 它是唯一能救回"细线"的一级：
//       · 灰度阈值：0.5 mm 块状斑块能检（36 px 够大），
//         但 1 像素宽的细细线要看它比背景暗多少，而且**中值会把它抹掉**
//         （上板实测："会吃掉小于 4 个像素点的白斑"）
//       · Sobel：细细线两侧**梯度极大**，而且**中值抹不掉梯度**
//     ⇒ 两条支路并联，正好把中值造成的那个取舍补回来。
//   【第二层重要性】它不依赖"光照绝对亮度" —— 梯度是差分，
//     光照整体变亮变暗不影响梯度 ⇒ 背光底座没到货也能先做、先验证。
//
//   --------------------------------------------------------------------
//   ★ 参考的成熟做法（先查一手资料再写）
//   --------------------------------------------------------------------
//   · 硬件 Sobel 通行的结构是 **3~4 级流水**：行缓冲 → 加权和 → 差分 → 幅值/比较。
//     官方 `hls-stencil-pattern` 技能只查 `#pragma HLS array_stencil`，**对写 RTL 不适用**。
//   · 幅值用 **|Gx| + |Gy|**（L1 范数）代替 √(Gx²+Gy²)：省掉 2 个乘法器和开方，
//     最大误差 ≤ √2 倍 —— 文献里最通行的做法。
//     ★ 它只改变"幅值的**标度**"，不改变"哪里是边" ⇒ **不影响检测效果**。
//   · 3×3 窗口（行缓冲）**不重复建**：直接并联吃 dd_win3x3 的输出（0 个 BRAM）。
//
//   --------------------------------------------------------------------
//   ★★ 明确"不采纳"的做法（查到了但不用，以及为什么）★★
//   --------------------------------------------------------------------
//   ① **近似加法器**（有论文用近似进位链换面积/功耗）：会在梯度上引入误差
//      ⇒ 可能漏检弱边 ⇒ 违反"一定不能影响检测效果" ✗ 不用。
//   ② **可分离实现**（Gx = "垂直平滑"再延迟两拍相减，省 2 个加法器 ≈20 LUT）：
//      收益太小，代价是"Gx 和 Gy 走不同结构"，验证负担大 ⇒ 不划算。
//      （而且 **Gy 根本不能这样省**：它平滑方向是水平的，平滑结果要跨行相减
//        ⇒ 又得加一套行缓冲，反而更贵。）
//   ③ **只算一个方向**（LUT 减半）：斜线/水平线会漏检 ✗ 不用。
//   ④ **梯度图上再做一次中值来压噪声**：中值挡在 Sobel **前面**会把细线抹平
//      （Sobel 就白做了）；挡在**后面**（梯度图上）要第二套 **11 位**行缓冲
//      （4 个 RAMB18 + 约 500 LUT）⇒ 太贵。
//      ⇒ 梯度图的去噪交给**第⑥级形态学**（它工作在**二值图**上，只有 1 位宽，
//        行缓冲极便宜），这才是性价比最高的做法。
//
//   --------------------------------------------------------------------
//   ★★ 位宽推导（本模块最容易错、也绝不能省的地方）★★
//   --------------------------------------------------------------------
//   输入 w00..w22 是 8 位灰度，**实际范围 0..246**（2:4:1 灰度的上限，不是 255）。
//   设灰度上限为 V，则（V=246、V=255 都列出，后者用于证明位宽对满量程也够）：
//       加权和 = V + 2V + V = 4V       ⇒ 984 / 1020 ⇒ 需要 **10 位**（上限 1023）✓
//       Gx/Gy  = 两个加权和之差 ⇒ ±4V  ⇒ ±984 / ±1020 ⇒ **11 位**（补码）✓
//       |Gx|   = 0 .. 4V               ⇒ 984 / 1020 ⇒ 10 位够（本模块统一留 11 位）
//       幅值   = |Gx|+|Gy| ≤ **6V**    ⇒ 1476 / 1530 ⇒ **11 位**（上限 2047）✓
//
//   ★★ 幅值上限是 6V，**不是 8V** —— 这里曾经写错过，是 testbench 顶出来的 ★★
//   想当然会算成 |Gx|+|Gy| ≤ 4V+4V = 8V，但**做不到**：Gx 和 Gy 共用四个角，
//   且符号相反。要让"右列高、左列低"把 Gx 拉满，右上角 a2 就得取高值；
//   可 a2 在 Gy 里是**减项**，一取高值就把 Gy 拉低了 ⇒ 两者互相抵消。
//   用 512 个顶点穷举验证过（|Gx|+|Gy| 是凸函数，最大值必在顶点）：
//       max |Gx| = 4V = 1020      （左列全 0、右列全 V）
//       max |Gx|+|Gy| = 6V = 1530 （例：a0=a1=a3=V、其余 0 ⇒ Gx=Gy=−765）
//   ⇒ 位宽结论**不变**，而且余量更大：11 位（2047）够，10 位（1023）**不够**
//     （1530 > 1023）⇒ 选 11 位是**必须的**，不是浪费。
//
//   ★ 如果偷懒把中间量留在 8 位，`2×w12` 立刻溢出 ⇒ Gx 完全错。
//     这是"偷工减料"的典型，不能省。
//
//   --------------------------------------------------------------------
//   ★ 为什么是 3 级流水
//   --------------------------------------------------------------------
//       第 1 级：4 个加权和（每个 2 个 10 位加法器，**并行**）        组合深度 2
//       第 2 级：Gx/Gy 差分 + 取绝对值（2 个减法 + 2 个条件取负）      组合深度 2
//       第 3 级：幅值相加 + 阈值比较（1 个加法 + 1 个比较）            组合深度 2
//   每级深度 ≤2（经验值 ≈1ns/级）⇒ 约 2ns，对 100MHz 极宽裕。
//   · 为什么不少打（2 拍）：那样最后一级要串"取负 → 加 → 比较"3 级；
//     省下的只有 26 个 FF（全片 106400 个的 0.02%）⇒ 不值当。
//   · 为什么不多打：每多一级 +26 个 FF，而当前域的瓶颈是**布线**
//     （实测最差路径走线占 66%）不是逻辑深度 ⇒ 再加拍收益很小。
//
//   --------------------------------------------------------------------
//   ★★ 参数对齐（上一级踩过这个坑，这次先把推导写下来）★★
//   --------------------------------------------------------------------
//   参数在 `in_sof` 那一拍**锁存**（设 in_sof 在拍 S ⇒ 沿 S+1 起 th_cur = 新值）。
//   窗口在**拍 S** 进入；比较器在**拍 S+2** 工作（第 3 级输出寄存器在沿 S+3 锁存）。
//   ⇒ 需要"拍 S 锁存的那份值"在拍 S+2 可用 ⇒ **参数再延迟 1 拍**（th_d1/en_d1）。
//   验算：
//     · 帧首窗口（拍 S 进入）  ⇒ 比较在拍 S+2 ⇒ th_d1 = th_cur(拍 S+1) = **新值** ✓
//     · 前一帧最后窗口（拍 S−1 进入）⇒ 比较在拍 S+1
//                                      ⇒ th_d1 = th_cur(拍 S) = **旧值** ✓
//   ★ 通用公式：**参数延迟链的拍数 =（窗口进入到参数被使用之间的拍数）− 1**。
//     如果直接拿 th_cur 去比，就会让"sof **前一个**像素"用上新参数
//     ⇒ 每次切换错 1 个像素，而屏幕上完全看不出来（dd_median3 就是这么错的）。
//
//   --------------------------------------------------------------------
//   ★ 延迟与"两条支路的对齐"（本模块最要紧的接口约定）
//   --------------------------------------------------------------------
//   本模块从窗口算延迟 **3 拍**；支路 A（dd_median3 3 拍 + dd_thresh 0 拍）也是 **3 拍**
//   ⇒ **两条支路的 sideband 逐拍对齐，OR 的时候不需要任何延迟补偿** ✓
//   （中值被旁路时延迟**不变**，仍然是 3 拍 —— 这一点是 dd_median3 特意保证的。）
//   ★ 改动本模块的流水级数，必须同时改 dd_median3 或在上层补延迟，否则两支路错位。
//
//   --------------------------------------------------------------------
//   注释规范（项目要求，2026-09-24）
//   --------------------------------------------------------------------
//       每一行有实际功能的代码，行尾都跟一条中文注释。
//       本文件以 **UTF-8（无 BOM）** 编码保存。
//////////////////////////////////////////////////////////////////////////////

module dd_sobel (
    // ------------------------------------------------------------------
    // 时钟与复位
    // ------------------------------------------------------------------
    input  wire        clk,        // aclk，100MHz
    input  wire        rst_n,      // 低有效复位

    // ------------------------------------------------------------------
    // 窗口输入（来自 dd_win3x3，与 dd_median3 吃的是**同一个**窗口）
    //   w00 w01 w02   上上行
    //   w10 w11 w12   上一行（w11 = 窗口中心）
    //   w20 w21 w22   当前行
    //   ★ 注意：Sobel **不用** w11（中心像素）—— 它算的是邻域差分。
    // ------------------------------------------------------------------
    input  wire [7:0]  w00, w01, w02,   // 上上行的左二列 / 左一列 / 当前列
    input  wire [7:0]  w10, w11, w12,   // 上一行的左二列 / 左一列 / 当前列
    input  wire [7:0]  w20, w21, w22,   // 当前行的左二列 / 左一列 / 当前列
    input  wire        in_valid,   // 本拍窗口有效
    input  wire        in_sof,     // 帧首（已带 valid 限定）
    input  wire        in_eol,     // 行尾（已带 valid 限定）
    input  wire        in_eof,     // 帧尾（已带 valid 限定）

    // ------------------------------------------------------------------
    // 控制（来自顶层 AXI-Lite 寄存器 SOB_TH 0x30）
    // ------------------------------------------------------------------
    input  wire        cfg_en,     // bit0：支路使能（0 = 这条支路整个关掉，命中恒 0）
    input  wire [7:0]  cfg_th,     // [15:8]：梯度阈值（幅值实际范围 0..1476，阈值 0..255 足够分开噪声边与真细线）

    // ------------------------------------------------------------------
    // 输出（比输入晚 3 拍）
    // ------------------------------------------------------------------
    output wire        out_valid,  // 与 out_hit 同拍
    output wire        out_hit,    // 1 = 本像素的梯度超过阈值（判为"边"）
    output wire        out_sof,    // 帧首，晚 3 拍
    output wire        out_eol,    // 行尾，晚 3 拍
    output wire        out_eof     // 帧尾，晚 3 拍
);

    //=====================================================================
    // 参数锁存 + 对齐延迟（推导见文件头"参数对齐"一节）
    //=====================================================================
    reg [7:0] th_cur;                                   // 帧首锁存的梯度阈值
    reg       en_cur;                                   // 帧首锁存的支路使能
    reg [7:0] th_d1;                                    // ★ 再延迟 1 拍（与第 3 级的比较器对齐）
    reg       en_d1;                                    // ★ 同上

    always @(posedge clk) begin
        if (!rst_n) begin                               // 复位
            th_cur <= 8'd0;                             // 阈值清零
            en_cur <= 1'b0;                             // 使能清零（默认关，安全）
            th_d1  <= 8'd0;                             // 延迟副本清零
            en_d1  <= 1'b0;                             // …
        end else begin
            if (in_sof) begin                           // 帧首更新，一帧内保持不变
                th_cur <= cfg_th;                       // 阈值
                en_cur <= cfg_en;                       // 使能
            end
            th_d1 <= th_cur;                            // ★ 跟着数据往下走一拍（不门控）
            en_d1 <= en_cur;                            // …
        end
    end

    //=====================================================================
    // ============ 第 1 级：四个加权和（8 个 10 位加法器）============
    //
    //   Sobel 的两个方向：
    //       Gx = (w02 + 2·w12 + w22) − (w00 + 2·w10 + w20)   右列和 − 左列和
    //       Gy = (w20 + 2·w21 + w22) − (w00 + 2·w01 + w02)   下行和 − 上行和
    //
    //   ★ 省资源的两招：
    //     ① "×2" 用**左移一位**实现 —— 常数移位只是连线，**不耗任何逻辑**；
    //     ② 每个加权和写成"先加两项、再加第三项"两个加法器（3 输入加法在
    //        7 系列里就是两个 2 输入加法器，写清楚反而让位宽一眼可见）。
    //
    //   位宽：每个加权和最大 246+492+246 = 984 ⇒ 10 位（0..1023）✓
    //=====================================================================
    wire [8:0] w12x2 = {w12, 1'b0};                     // 2×w12（左移，免费）
    wire [8:0] w10x2 = {w10, 1'b0};                     // 2×w10
    wire [8:0] w21x2 = {w21, 1'b0};                     // 2×w21
    wire [8:0] w01x2 = {w01, 1'b0};                     // 2×w01

    // ---- 右列加权和 = w02 + 2·w12 + w22（最大 984）----
    wire [9:0] r_p   = {1'b0, w02} + {1'b0, w12x2};     // 前两项，最大 738
    wire [9:0] sum_r = r_p + {1'b0, w22};               // 加第三项，最大 984 ⇒ 10 位够

    // ---- 左列加权和 = w00 + 2·w10 + w20 ----
    wire [9:0] l_p   = {1'b0, w00} + {1'b0, w10x2};     // 前两项
    wire [9:0] sum_l = l_p + {1'b0, w20};               // 加第三项

    // ---- 上行加权和 = w00 + 2·w01 + w02 ----
    wire [9:0] t_p   = {1'b0, w00} + {1'b0, w01x2};     // 前两项
    wire [9:0] sum_t = t_p + {1'b0, w02};               // 加第三项

    // ---- 下行加权和 = w20 + 2·w21 + w22 ----
    wire [9:0] b_p   = {1'b0, w20} + {1'b0, w21x2};     // 前两项
    wire [9:0] sum_b = b_p + {1'b0, w22};               // 加第三项

    //=====================================================================
    // ★ 流水寄存器第 1 级：4 个加权和 + 4 根 sideband，无条件一起打拍
    //=====================================================================
    reg [9:0] s1_sr, s1_sl, s1_st, s1_sb;               // 四个加权和
    reg       s1_v, s1_sof, s1_eol, s1_eof;             // 第 1 级的 sideband

    always @(posedge clk) begin
        if (!rst_n) begin                               // 复位：全部清零，仿真一上电就是确定值
            s1_sr <= 10'd0; s1_sl <= 10'd0;             // 行列和清零
            s1_st <= 10'd0; s1_sb <= 10'd0;             // 上下行和清零
            s1_v <= 1'b0; s1_sof <= 1'b0;               // sideband 清零
            s1_eol <= 1'b0; s1_eof <= 1'b0;             // …
        end else begin                                  // ★ 不门控：空拍自然流过去，靠 valid 标记
            s1_sr <= sum_r;                             // 右列和进寄存器
            s1_sl <= sum_l;                             // 左列和进寄存器
            s1_st <= sum_t;                             // 上行和进寄存器
            s1_sb <= sum_b;                             // 下行和进寄存器
            s1_v   <= in_valid;                         // sideband 一起打拍
            s1_sof <= in_sof;                           // …
            s1_eol <= in_eol;                           // …
            s1_eof <= in_eof;                           // …
        end
    end

    //=====================================================================
    // ============ 第 2 级：差分 + 取绝对值 ============
    //
    //   Gx = 右列和 − 左列和，Gy = 下行和 − 上行和
    //   两者都是**有符号**的（−984..+984）⇒ 用 11 位**补码**表示：
    //       最高位 bit[10] = 1 表示负数。
    //   ★ 这里**不写 signed 类型**，而是显式判 bit[10] 再取负 ——
    //     不依赖 Verilog 的 signed 语义（混用有/无符号是经典坑），一眼可查。
    //   取绝对值：负数就做 2 补码取负（`0 − x`，1 个 11 位减法器）。
    //=====================================================================
    wire [10:0] gx     = {1'b0, s1_sr} - {1'b0, s1_sl}; // Gx（11 位补码）
    wire [10:0] gy     = {1'b0, s1_sb} - {1'b0, s1_st}; // Gy（11 位补码）
    wire [10:0] gx_abs = gx[10] ? (11'd0 - gx) : gx;    // |Gx| = 0..984（bit[10] 恒 0）
    wire [10:0] gy_abs = gy[10] ? (11'd0 - gy) : gy;    // |Gy| = 0..984

    //=====================================================================
    // ★ 流水寄存器第 2 级：两个绝对值（已经是"梯度幅值的两个分量"）
    //=====================================================================
    reg [10:0] s2_gxa, s2_gya;                          // |Gx| / |Gy|
    reg        s2_v, s2_sof, s2_eol, s2_eof;            // 第 2 级的 sideband

    always @(posedge clk) begin
        if (!rst_n) begin                               // 复位
            s2_gxa <= 11'd0; s2_gya <= 11'd0;           // 两个分量清零
            s2_v <= 1'b0; s2_sof <= 1'b0;               // sideband 清零
            s2_eol <= 1'b0; s2_eof <= 1'b0;             // …
        end else begin                                  // ★ 同样不门控
            s2_gxa <= gx_abs;                           // |Gx| 进寄存器
            s2_gya <= gy_abs;                           // |Gy| 进寄存器
            s2_v   <= s1_v;                             // sideband 一起打拍
            s2_sof <= s1_sof;                           // …
            s2_eol <= s1_eol;                           // …
            s2_eof <= s1_eof;                           // …
        end
    end

    //=====================================================================
    // ============ 第 3 级：幅值 + 阈值比较 ============
    //
    //   幅值用 L1 范数：mag = |Gx| + |Gy|，上限是 **6V = 1476**（不是 8V！见文件头推导）
    //   ⇒ 11 位（< 2048）✓
    //   ★ 不用 √(Gx²+Gy²)：那要 2 个乘法器 + 开方（DSP + 长组合链）。
    //     L1 范数最大误差 ≤ √2 倍，**只改标度不改"哪里是边"** ⇒ 不影响检测效果。
    //
    //   比较用 **th_d1**（不是 th_cur）：本拍就是"窗口进入后第 2 拍"，
    //   需要的是"帧首那一拍锁存的值"，推导见文件头。
    // ====================================================================
    wire [10:0] mag   = s2_gxa + s2_gya;                // 梯度幅值（L1 范数），0..1968
    wire        hit_c = (mag > {3'b0, th_d1});          // 阈值零扩展到 11 位再比（阈值 0..255）
    wire        hit   = en_d1 & hit_c;                  // 支路关掉时强制不命中

    //=====================================================================
    // ★ 流水寄存器第 3 级（输出级）
    //=====================================================================
    reg o_hit;                                          // 输出：本像素是否判为边
    reg o_v, o_sof, o_eol, o_eof;                       // 输出的 sideband

    always @(posedge clk) begin
        if (!rst_n) begin                               // 复位
            o_hit <= 1'b0;                              // 不命中
            o_v <= 1'b0; o_sof <= 1'b0;                 // sideband 清零
            o_eol <= 1'b0; o_eof <= 1'b0;               // …
        end else begin                                  // ★ 不门控
            o_hit <= hit;                               // 比较结果进寄存器（组合链到此为止）
            o_v   <= s2_v;                              // sideband 一起打第 3 拍
            o_sof <= s2_sof;                            // …
            o_eol <= s2_eol;                            // …
            o_eof <= s2_eof;                            // …
        end
    end

    //=====================================================================
    // 输出：全部取自寄存器 ⇒ 整体比输入晚 3 拍（与支路 A 逐拍对齐）
    //=====================================================================
    assign out_hit   = o_hit;                           // 梯度命中
    assign out_valid = o_v;                             // 与 out_hit 同拍
    assign out_sof   = o_sof;                           // 帧首，晚 3 拍
    assign out_eol   = o_eol;                           // 行尾，晚 3 拍
    assign out_eof   = o_eof;                           // 帧尾，晚 3 拍

endmodule
