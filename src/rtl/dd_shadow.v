//////////////////////////////////////////////////////////////////////////////
// dd_shadow.v  ——  第①·六级：**彩色差分 + 阴影抑制评分**（取代旧的 dd_diff）
//
//   【这一级在干什么】
//     输入：A（当前帧彩色原图）、B（背景彩色原图），两路已由 dd_pair 逐拍对齐。
//     输出：8 位 score，送进 dd_win3x3 → dd_median3 → dd_thresh → dd_morph。
//     下游五个模块**一个字都不用改**（它们只吃 8 位单通道）。
//
//   --------------------------------------------------------------------
//   【为什么必须用彩色：阴影的物理本质】
//   --------------------------------------------------------------------
//     纯灰度差分 |ΔY| 分不开"阴影"和"暗物体" —— 两者在灰度里表现为同一件事：变暗。
//
//     但阴影的物理定义是"**同一材质，照度乘一个系数 α**"：
//         R_A = α·R_B,  G_A = α·G_B,  B_A = α·B_B
//     代入 BT.601 色度（Cb = 128 + 0.564(B−Y)，Cr = 128 + 0.713(R−Y)）：
//         Cb_A − 128 = α·(Cb_B − 128)
//         Cr_A − 128 = α·(Cr_B − 128)
//     ⇒ **阴影只让色度"量值缩小"，不改变色度方向**；而换了材质会改变色度。
//     ⇒ 判据：色度几乎不动 + 画面变暗 ⇒ 阴影。
//
//   --------------------------------------------------------------------
//   【判据三条（用户 2026-10-21 定案）】
//   --------------------------------------------------------------------
//     ① 色度不变  ：|ΔCb| + |ΔCr| < τc       （换了材质色度必然跳）
//     ② 变暗      ：Y_A < Y_B                 （阴影不可能让画面变亮）
//     ③ 暗度有上限：Y_A·256 > Y_B·αmin        （太暗就不是阴影，而是深色物体）
//     三条同时成立 ⇒ 判为阴影 ⇒ **把这一拍的亮度差抹成 0**
//
//     ②③ 合起来是"变暗、但不能太暗"，这一对是把**阴影**和**深色物体**分开的唯一依据：
//         · 轻度/中度阴影（α≈0.7~0.95）：过 ③ ⇒ 被抹掉 ✓
//         · 深色物体（黑键盘/黑袋，α<0.5）  ：不过 ③ ⇒ 照旧检出 ✓（功能不退化）
//         · 深阴影（α<αmin）               ：不过 ③ ⇒ 会漏，用户明确接受 ✓
//
//   --------------------------------------------------------------------
//   【score 的组成（权重全部来自 PS 寄存器，运行时可调）】
//   --------------------------------------------------------------------
//         score = wY · (阴影 ? 0 : |ΔY|)  +  wC · (|ΔCb| + |ΔCr|)
//
//     · 阴影   ：亮度项被 ① 抹成 0，色度项本身 ≈0 ⇒ score ≈ 0 ⇒ 不命中 ✓
//     · 物体   ：两项都在 ⇒ score 大 ⇒ 命中 ✓
//     · 等亮度异色物体（灰度差分永远抓不到的那一类）：|ΔY|≈0 但色度项大 ⇒ 仍命中 ✓
//
//   --------------------------------------------------------------------
//   【定点与量化须知】
//   --------------------------------------------------------------------
//     · 输入是 RGB565 左对齐补 0 ⇒ R/B 粒度 8、G 粒度 4
//       ⇒ |ΔCb| 的量化步长约 1.3、|ΔCb|+|ΔCr| 合计约 3~8（纯量化噪声）
//       ⇒ **τc 不能低于 8**，实用起点 10~12
//     · 色度系数之和恰好为 0（−43−85+128 = 0、128−107−21 = 0）
//       ⇒ 三通道同比例下降时 ΔCb=ΔCr=0，是**数学严格为 0**，不是"很小"
//     · 全局 **0 个除法**：所有常数乘 + 移位，综合器会映射成 LUT/移位加法
//
//   --------------------------------------------------------------------
//   ★★ 本模块延迟 **4 拍**。五根 sideband 无条件跟着每一级一起打拍。★★
//   本文件以 UTF-8（无 BOM）保存；自研代码逐行中文注释。
//////////////////////////////////////////////////////////////////////////////

module dd_shadow (
    // ------------------------------------------------------------------
    // 时钟与复位
    // ------------------------------------------------------------------
    input  wire        clk,          // aclk，100MHz
    input  wire        rst_n,        // 低有效复位（同步复位）

    // ------------------------------------------------------------------
    // A 路：当前帧彩色原图（已由 dd_pair 与 B 逐拍对齐）
    // ------------------------------------------------------------------
    input  wire        a_valid,      // 本拍有有效像素
    input  wire [23:0] a_pix,        // 24 位彩色（RGB565 左对齐补 0）
    input  wire        a_sof,        // 帧首
    input  wire        a_eol,        // 行尾
    input  wire        a_eof,        // 帧尾

    // ------------------------------------------------------------------
    // B 路：背景彩色原图（同拍配对好的）
    // ------------------------------------------------------------------
    input  wire        b_valid,      // 本拍背景数据可用（配对器没配上时为 0）
    input  wire [23:0] b_pix,        // 24 位彩色背景

    // ------------------------------------------------------------------
    // 配置（全部来自 PS 的 AXI-Lite 寄存器，运行时可调，不用重编）
    // ------------------------------------------------------------------
    input  wire        cfg_en,       // 检测总使能（= BG_CTL[0]；背景没采好时必须 0）
    input  wire        cfg_sh_en,    // 阴影判据使能（=0 ⇒ 退回纯 |ΔY| 的旧行为）
    input  wire [3:0]  cfg_wy,       // 亮度项权重 wY
    input  wire [3:0]  cfg_wc,       // 色度项权重 wC
    input  wire [7:0]  cfg_alpha,    // αmin 定点码：128 = 0.5，192 = 0.75
    input  wire [7:0]  cfg_tau,      // 色度阈值 τc（建议 10~12，不能低于 8）

    // ------------------------------------------------------------------
    // 主输出（→ dd_win3x3），比输入晚 4 拍
    // ------------------------------------------------------------------
    output wire        out_valid,    // 本拍 score 有效
    output wire [7:0]  out_pix,      // score（0..255，饱和）
    output wire        out_sof,      // 帧首（跟随 A 路）
    output wire        out_eol,      // 行尾（跟随 A 路）
    output wire        out_eof,      // 帧尾（跟随 A 路）

    // ------------------------------------------------------------------
    // 调试输出（与 out_pix 同拍，给顶层 DISP 显示用）
    // ------------------------------------------------------------------
    output wire [7:0]  dbg_ya,       // 【DISP=6】当前帧灰度 Y_A
    output wire [7:0]  dbg_dy,       // 【DISP=8】|ΔY|（未抹平的亮度差）
    output wire [7:0]  dbg_dc,       // 【DISP=9】|ΔCb| + |ΔCr|（色度差，饱和到 255）
    output wire        dbg_shadow,   // 【DISP=10】阴影标记（1 = 本拍被判为阴影）
    output wire [23:0] dbg_bgc       // 【DISP=7】配对后的背景彩色（原样透出，供显示）
);

    //=====================================================================
    // 级 0：从 24 位像素里取分量（纯连线，0 逻辑）
    //   RGB565 左对齐补 0 ⇒ 取高位就是分量值，低位恒 0 不用管
    //=====================================================================
    wire [4:0] ar5 = a_pix[23:19];                  // A 的 R（5 位）
    wire [5:0] ag6 = a_pix[15:10];                  // A 的 G（6 位）
    wire [4:0] ab5 = a_pix[ 7: 3];                  // A 的 B（5 位）

    wire [4:0] br5 = b_pix[23:19];                  // B 的 R（5 位）
    wire [5:0] bg6 = b_pix[15:10];                  // B 的 G（6 位）
    wire [4:0] bb5 = b_pix[ 7: 3];                  // B 的 B（5 位）

    // ---- 灰度（2:4:1，与旧 dd_gray 完全同一算式，保证与历史行为可比）----
    //      S = 2·(R5+G6) + B5 ； Y = S + S/8  ⇒ 0..246，220 个可区分档位
    wire [6:0] a_rg = ar5 + ag6;                    // A：R5+G6，0..94
    wire [7:0] a_s  = {a_rg, 1'b0} + {2'b0, ab5};   // A：2(R5+G6)+B5，0..219
    wire [7:0] a_y  = a_s + (a_s >> 3);             // A：≈S×9/8，0..246

    wire [6:0] b_rg = br5 + bg6;                    // B：R5+G6
    wire [7:0] b_s  = {b_rg, 1'b0} + {2'b0, bb5};   // B：2(R5+G6)+B5
    wire [7:0] b_y  = b_s + (b_s >> 3);             // B：0..246

    // ---- 分量差（补码；无符号相减后按补码解释，范围见注释）----
    wire [5:0] d_r5 = {1'b0, ar5} - {1'b0, br5};    // −31..+31
    wire [6:0] d_g6 = {1'b0, ag6} - {1'b0, bg6};    // −63..+63
    wire [5:0] d_b5 = {1'b0, ab5} - {1'b0, bb5};    // −31..+31

    // ---- 亮度差 ΔY（9 位补码，−246..+246；bit8=1 表示变暗）----
    wire [8:0] d_y_raw = {1'b0, a_y} - {1'b0, b_y};

    //=====================================================================
    // 级 1：打一拍，把"分量差 + 灰度 + ΔY"固定下来
    //=====================================================================
    reg         v1, s1, e1, f1;                     // sideband 级 1
    reg         b_v1;                               // ★ B 路 valid 也要跟着打拍（不能直接拿当前的，
                                                    //    否则 4 级流水之后 b_valid 早就回 0 了 ⇒ 输出恒 0 ✗）
    reg  [7:0]  ya1, yb1;                           // Y_A / Y_B
    reg  [5:0]  dr1;                                // dR（补码）
    reg  [6:0]  dg1;                                // dG（补码）
    reg  [5:0]  db1;                                // dB（补码）
    reg  [8:0]  dy1;                                // ΔY（补码）
    reg  [8:0]  dy2;                                // ★ ΔY 必须跟着流水往后走（级 3 要用）
    reg  [23:0] bc1;                                // 背景彩色（供 DISP=7）

    always @(posedge clk) begin
        if (!rst_n) begin
            v1 <= 1'b0; s1 <= 1'b0; e1 <= 1'b0; f1 <= 1'b0;
            b_v1 <= 1'b0;
            ya1 <= 8'd0; yb1 <= 8'd0;
            dr1 <= 6'd0; dg1 <= 7'd0; db1 <= 6'd0;
            dy1 <= 9'd0; bc1 <= 24'd0;
        end else begin
            v1 <= a_valid;                          // ★ 五根 sideband 无条件一起打拍
            b_v1 <= b_valid;                        // ★ B 路 valid 同步打拍（见上面的说明）
            s1 <= a_sof;
            e1 <= a_eol;
            f1 <= a_eof;
            ya1 <= a_y;                             // 当前帧灰度
            yb1 <= b_y;                             // 背景灰度
            dr1 <= d_r5;                            // 分量差（补码）
            dg1 <= d_g6;
            db1 <= d_b5;
            dy1 <= d_y_raw;                         // 亮度差（补码）
            bc1 <= b_pix;                           // 背景彩色透出（显示用）
        end
    end

    //=====================================================================
    // 级 1.5 → 级 2：算 ΔCb / ΔCr（×256 定点，避免除法）
    //
    //   因为分量已按 RGB565 补零展开（R = 8·R5、G = 4·G6、B = 8·B5）：
    //     ΔCb×256 = −43·(8·dR) − 85·(4·dG) + 128·(8·dB)
    //             = −344·dR − 340·dG + 1024·dB
    //     ΔCr×256 =  128·(8·dR) − 107·(4·dG) − 21·(8·dB)
    //             = 1024·dR − 428·dG − 168·dB
    //   ★ 1024 是 2^10 ⇒ 综合时自动变成移位，不占乘法器
    //   ★ 系数之和为 0 ⇒ dR=dG=dB（同比例下降）时结果**严格为 0**，这是判据成立的根本
    //=====================================================================
    // 有符号视图（位模式不变，只是告诉后续运算按补码解释）
    wire signed [5:0] sd_r = dr1;                   // dR
    wire signed [6:0] sd_g = dg1;                   // dG
    wire signed [5:0] sd_b = db1;                   // dB

    wire signed [15:0] cb_r  = -16'sd344 * sd_r;    // −344·dR，范围 ±10664
    wire signed [16:0] cb_g  = -17'sd340 * sd_g;    // −340·dG，范围 ±21420
    wire signed [16:0] cb_b  =  17'sd1024 * sd_b;   // +1024·dB（移位），范围 ±31744

    wire signed [17:0] cb_x256 = {{2{cb_r[15]}}, cb_r}      // 符号扩展到 18 位后相加
                               + {{1{cb_g[16]}}, cb_g}      //   结果范围 ±63828，18 位够
                               + {{1{cb_b[16]}}, cb_b};

    wire signed [16:0] cr_r  =  17'sd1024 * sd_r;   // +1024·dR（移位）
    wire signed [16:0] cr_g  = -17'sd428 * sd_g;    // −428·dG，范围 ±26964
    wire signed [15:0] cr_b  = -16'sd168 * sd_b;    // −168·dB，范围 ±5208

    wire signed [17:0] cr_x256 = {{1{cr_r[16]}}, cr_r}      // 符号扩展到 18 位
                               + {{1{cr_g[16]}}, cr_g}
                               + {{2{cr_b[15]}}, cr_b};

    reg         v2, s2, e2, f2;                     // sideband 级 2
    reg         b_v2;                               // B 路 valid 级 2
    reg  [17:0] cbx2, crx2;                         // ΔCb×256 / ΔCr×256
    reg  [7:0]  ya2, yb2;                           // 灰度跟着往后走（级 3 算暗度上限要用）
    reg  [23:0] bc2;

    always @(posedge clk) begin
        if (!rst_n) begin
            v2 <= 1'b0; s2 <= 1'b0; e2 <= 1'b0; f2 <= 1'b0;
            b_v2 <= 1'b0;
            cbx2 <= 18'd0; crx2 <= 18'd0;
            dy2  <= 9'd0;
            ya2 <= 8'd0; yb2 <= 8'd0; bc2 <= 24'd0;
        end else begin
            v2 <= v1; s2 <= s1; e2 <= e1; f2 <= f1; // ★ sideband 一起打拍
            b_v2 <= b_v1;                           // ★ B 路 valid 同步
            cbx2 <= cb_x256;                        // 色度差（×256）
            crx2 <= cr_x256;
            dy2  <= dy1;                            // ★ ΔY 跟着打拍（级 3 判"变暗/|ΔY|"用它）
            ya2 <= ya1;
            yb2 <= yb1;
            bc2 <= bc1;
        end
    end

    //=====================================================================
    // 级 2.5 → 级 3：右移 8 位取真实色度差 + 取绝对值 + 判暗度上限
    //   ★ 有符号数取 [16:8] 等价于算术右移 8 位（向负无穷取整），范围 ±249，9 位够
    //=====================================================================
    wire signed [8:0] d_cb = cbx2[16:8];            // ΔCb（−249..+249）
    wire signed [8:0] d_cr = crx2[16:8];            // ΔCr（−249..+249）

    wire [8:0] abs_cb = d_cb[8] ? (~d_cb + 9'd1) : d_cb;   // |ΔCb|
    wire [8:0] abs_cr = d_cr[8] ? (~d_cr + 9'd1) : d_cr;   // |ΔCr|
    wire [9:0] d_c    = abs_cb + abs_cr;                    // 色度差合计 0..510

    // ---- 暗度上限：Y_A·256 > Y_B·αmin ----
    wire [15:0] ya_x256  = {ya2, 8'd0};             // Y_A × 256（左移 8 位，免费）
    wire [15:0] yb_alpha = yb2 * cfg_alpha;         // Y_B × αmin（8×8 乘，αmin=128 即 ×0.5）
    wire        alpha_ok = (ya_x256 > yb_alpha);    // 1 = 暗得没超过 αmin ⇒ 可能是阴影

    reg         v3, s3, e3, f3;                     // sideband 级 3
    reg         b_v3;                               // B 路 valid 级 3（输出级判有效性就用它）
    reg  [9:0]  dc3;                                // 色度差合计
    reg         dark3;                              // 1 = 本拍比背景暗
    reg  [8:0]  ady3;                               // |ΔY|
    reg         aok3;                               // 暗度上限通过
    reg  [7:0]  ya3;                                // Y_A（调试显示用）
    reg  [23:0] bc3;

    always @(posedge clk) begin
        if (!rst_n) begin
            v3 <= 1'b0; s3 <= 1'b0; e3 <= 1'b0; f3 <= 1'b0;
            b_v3 <= 1'b0;
            dc3 <= 10'd0; dark3 <= 1'b0; ady3 <= 9'd0; aok3 <= 1'b0;
            ya3 <= 8'd0; bc3 <= 24'd0;
        end else begin
            v3 <= v2; s3 <= s2; e3 <= e2; f3 <= f2; // ★ sideband 一起打拍
            b_v3 <= b_v2;                           // ★ B 路 valid 同步
            dc3   <= d_c;                           // 色度差合计
            dark3 <= dy2[8];                        // ★ 用级 2 打拍后的 ΔY 符号（变暗=1），不能跨级取 dy1！
            ady3  <= dy2[8] ? (~dy2 + 9'd1) : dy2;  // ★ |ΔY|（同上，必须用本级对齐的 dy2）
            aok3  <= alpha_ok;                      // 暗度上限判据
            ya3   <= ya2;                           // Y_A
            bc3   <= bc2;
        end
    end

    //=====================================================================
    // 级 3.5 → 级 4：三条判据合流 + 色度项加权（**在这里切断长组合链**）
    //
    //   ★ 为什么拆成两级（2026-10-22 首轮综合实测逼出来的）：
    //     原来把"判据 → 抹平 → 两个乘法 → 相加 → 饱和 → 输出"写成一段组合，
    //     综合后这条路径 **9 级逻辑 / 11.5ns**（要求 10ns），
    //     clk_fpga_0 域 WNS = **−1.663ns、224 个违例端点**，时序直接不过 ✗
    //     违例路径的起点是配置寄存器 shadow_cfg_reg[18]（= cfg_tau），
    //     终点是 o_sc_reg —— 正是这一级。
    //     修法：在"乘法之前"插一级寄存器，把链切成两段各约 5 级 ✓
    //     ⇒ 本模块延迟从 4 拍变 **5 拍**（detect.py 的 SHIFT_X 相应 13 → 14）。
    //=====================================================================
    // ---- 阴影判据：色度不变 + 变暗 + 暗得没超过 αmin ----
    wire is_shadow_w = cfg_sh_en & cfg_en           // 开关（关掉就退回纯 |ΔY| 的老行为）
                     & dark3                        // ② 变暗
                     & aok3                         // ③ 暗度有上限
                     & (dc3 < {2'b0, cfg_tau});     // ① 色度几乎没动

    // ---- 阴影就把亮度项抹成 0，否则用 |ΔY| ----
    wire [7:0] dy_eff_w = is_shadow_w ? 8'd0 : ady3[7:0];

    // ---- 色度项加权（10×4 = 14 位）：在这一级先乘好并寄存 ----
    wire [13:0] pc_w = dc3 * cfg_wc;

    // ---- 调试量：色度差饱和到 8 位（超 255 就报 255）----
    wire [7:0] dc8_w = (dc3 > 10'd255) ? 8'd255 : dc3[7:0];

    reg         v4, s4, e4, f4;                     // sideband 级 4
    reg         b_v4;                               // B 路 valid 级 4
    reg         sh4;                                // 阴影标记
    reg  [7:0]  dye4;                               // 抹平后的 |ΔY|
    reg  [13:0] pc4;                                // 色度项（已乘权重）
    reg  [7:0]  ya4;                                // Y_A
    reg  [7:0]  ady4;                               // |ΔY|（未抹平，调试用）
    reg  [7:0]  dc4;                                // 色度差（饱和到 8 位）
    reg  [23:0] bc4;                                // 背景彩色

    always @(posedge clk) begin
        if (!rst_n) begin
            v4 <= 1'b0; s4 <= 1'b0; e4 <= 1'b0; f4 <= 1'b0; b_v4 <= 1'b0;
            sh4 <= 1'b0; dye4 <= 8'd0; pc4 <= 14'd0;
            ya4 <= 8'd0; ady4 <= 8'd0; dc4 <= 8'd0; bc4 <= 24'd0;
        end else begin
            v4 <= v3; s4 <= s3; e4 <= e3; f4 <= f3; // ★ sideband 一起打拍
            b_v4 <= b_v3;                           // ★ B 路 valid 同步
            sh4  <= is_shadow_w;                    // ★ 判据结果寄存（组合链到此为止）
            dye4 <= dy_eff_w;                       // 抹平后的亮度项
            pc4  <= pc_w;                           // 色度项（已乘权重）
            ya4  <= ya3;
            ady4 <= ady3[7:0];
            dc4  <= dc8_w;
            bc4  <= bc3;
        end
    end

    //=====================================================================
    // 级 4.5 → 级 5（输出）：亮度项加权 + 求和 + 饱和
    //   这一级只剩"1 个乘法 + 1 个加法 + 1 个饱和比较"，组合深度约 4~5 级
    //=====================================================================
    wire [11:0] py_w = dye4 * cfg_wy;               // 8×4 = 12 位
    wire [13:0] score_full = {2'b0, py_w} + pc4;    // 对齐到 14 位后相加
    wire [7:0]  score_w = (score_full > 14'd255) ? 8'd255 : score_full[7:0];  // 饱和到 8 位

    // ---- 本拍真正的输出值：只有"差分使能 + A 有效 + B 可用"这一拍才算数 ----
    //   ★ 必须用**打过拍的** v4/b_v4，不能用当前拍的 valid：
    //     这条流水有 5 级，等到算 score 那一拍，原始 b_valid 早就回 0 了。
    //     （这个 bug 是 tb_dd_shadow 第一轮抓出来的：所有 score 恒 0，而 dbg_* 全对。）
    wire [7:0] out_next = (cfg_en & v4 & b_v4) ? score_w : 8'd0;

    reg         v5, s5, e5, f5;                     // sideband 级 5（= 输出）
    reg  [7:0]  o_sc;                               // score
    reg  [7:0]  o_ya;                               // Y_A  → DISP=6
    reg  [7:0]  o_dy;                               // |ΔY| → DISP=8
    reg  [7:0]  o_dc;                               // ΔC    → DISP=9
    reg         o_sh;                               // 阴影   → DISP=10
    reg  [23:0] o_bc;                               // 背景彩色 → DISP=7

    always @(posedge clk) begin
        if (!rst_n) begin
            v5 <= 1'b0; s5 <= 1'b0; e5 <= 1'b0; f5 <= 1'b0;
            o_sc <= 8'd0; o_ya <= 8'd0; o_dy <= 8'd0; o_dc <= 8'd0; o_sh <= 1'b0; o_bc <= 24'd0;
        end else begin
            v5 <= v4; s5 <= s4; e5 <= e4; f5 <= f4; // ★ sideband 一起打拍
            o_sc <= out_next;                       // 主输出：score
            o_ya <= ya4;                            // Y_A
            o_dy <= ady4;                           // |ΔY|
            o_dc <= dc4;                            // 色度差
            o_sh <= sh4;                            // 阴影标记
            o_bc <= bc4;                            // 背景彩色
        end
    end

    //=====================================================================
    // 输出
    //=====================================================================
    assign out_valid = v5;                          // 本拍 score 有效
    assign out_pix   = o_sc;                        // score（0..255）
    assign out_sof   = s5;                          // 帧首（跟随 A 路）
    assign out_eol   = e5;                          // 行尾（跟随 A 路）
    assign out_eof   = f5;                          // 帧尾（跟随 A 路）

    assign dbg_ya    = o_ya;                        // DISP=6
    assign dbg_dy    = o_dy;                        // DISP=8
    assign dbg_dc    = o_dc;                        // DISP=9
    assign dbg_shadow= o_sh;                        // DISP=10
    assign dbg_bgc   = o_bc;                        // DISP=7

endmodule
