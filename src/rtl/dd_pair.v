//////////////////////////////////////////////////////////////////////////////
// dd_pair.v —— A/B 配对器（v4：去掉队列，用"帧首匹配 + 反压限速"直接逐拍对齐）
//
//   【v4 的核心思想（用户定的方案）】
//     · B 只在"A 有像素"那一拍才被收（`b_ready = a_valid`）⇒ 两边严格 1:1；
//     · **不需要我们自己做缓冲** —— VDMA 内部本来就有行缓冲：被我们反压的期间
//       它照样提前把数据取好、填满就停 ⇒ 我们一放开 ready，队首那个 beat 早就
//       摆在总线上等我们收了 ✓（这就是 v3 那个 8192 队列可以去掉的原因）；
//     · 起点用【帧首】钉死：
//         看到 b_sof（B 的帧首 beat 出现在总线上）时，看 A 在不在帧首：
//             不在 ⇒ 挂起（b_ready=0），一直等到 a_sof 才放开；
//             正在 ⇒ 直接继续，不用挂起。
//       ⇒ 从 a_sof 那一拍起 A[0] 配 B[0]，之后逐拍一一对应；
//     · 稳态下 b_sof 必然出现在【A 的消隐期】—— 因为一帧正好消费 N 个 B beat，
//       A 最后一个像素被消费掉之后队首立刻变成下一帧的 B[0] ⇒ b_sof 就在那里
//       出现，而这时 A 已经进场消隐 ⇒ 挂起期间 A 一个有效像素都没有 ⇒
//       **帧首匹配是零代价的，而且每帧自动重锚一次（自愈）** ✓
//
//   【v3 的教训（已废弃，别再走回去）】
//     v3 用"A 帧首清空 FIFO"来重新对齐 ✗ —— 那是【丢数据】：每次 a_sof 把队列里
//     积的一整批 B 像素扔掉（实测 8192 个）⇒ B 的相位每帧滑 8192 个像素
//     （= 8 行 + 416 列）⇒ 屏上就是"持续向上滚 + 一道竖缝把左右两半错开并抖动"。
//
//   【三条硬纪律（不能破）】
//     ① A 路**绝不反压**（上游 broadcaster 无缓冲，卡 A 会把原图存档和显示一起卡死）
//     ② `b_ready` **只依赖寄存器与输入**，绝不能依赖"这一拍传输发生了"（会成组合环，
//        布线直接报 [DRC LUTLP-1]，位流出不来）
//     ③ 输出**严格跟 A 的节拍**（`out_valid = a_valid` 打 1 拍）—— 这是几何正确的前提
//
//   ★ 本文件以 UTF-8（无 BOM）保存；自研代码逐行中文注释。
//////////////////////////////////////////////////////////////////////////////
`timescale 1ns / 1ps

module dd_pair #(
    parameter DW = 8                        // ★ 像素数据位宽：8 = 灰度（旧行为）；24 = 彩色原图（当前）
) (
    // ---------------- 时钟与复位 ----------------
    input  wire        clk,                 // 像素时钟（100MHz，A/B 同域，无跨时钟）
    input  wire        rst_n,               // 低有效复位

    // ---------------- 配置 ----------------
    input  wire        cfg_en,              // 差分使能（本模块不用它门控传输，只影响诊断口径）

    // ---------------- A 路：当前帧灰度（节拍基准，永不反压）----------------
    input  wire        a_valid,             // A 路像素有效
    input  wire [DW-1:0] a_pix,             // A 路像素（★ DW 位：彩色原图时 = 24 位 RGB565 补零）
    input  wire        a_sof,               // A 路帧首（相机 TUSER，带 valid 限定）
    input  wire        a_eol,               // A 路行尾
    input  wire        a_eof,               // A 路帧尾

    // ---------------- B 路：背景（来自 VDMA，可反压）----------------
    input  wire        b_valid,             // ★ 传进来的是【未门控的原始 tvalid】（挂起时也能看见数据/帧首）
    input  wire [DW-1:0] b_pix,             // B 路像素（tvalid=1 时总线上的那个像素，★ DW 位）
    input  wire        b_sof,               // B 路帧首（= tvalid & tuser，不受 ready 影响）
    output wire        b_ready,             // ★ 给 VDMA 的 tready：只在 A 有像素那一拍收一个

    // ---------------- 输出：严格跟 A 的节拍 ----------------
    output reg         out_valid,           // = a_valid 打 1 拍
    output reg  [DW-1:0] out_pix,           // A 路像素（打 1 拍，与 B 同拍，★ DW 位）
    output reg         out_sof,             // A 路帧首（跟着一起打拍）
    output reg         out_eol,             // A 路行尾
    output reg         out_eof,             // A 路帧尾
    output reg  [DW-1:0] out_b_pix,         // 与 out_pix 同拍配上的 B 像素；没配上时用 A 顶替（差分=0，★ DW 位）

    // ---------------- 诊断（给 PS 读；端口名沿用旧版，语义见注释）----------------
    output reg  [15:0] lead_max,            // 【新语义】本帧"没配上"的次数（a_valid 但没收到 B）；0 = 完美
    output reg  [15:0] stall_cnt,           // 【新语义】本帧"挂起"的拍数（看到 b_sof 后等 a_sof 的那段）
    output reg  [15:0] lap_cnt,             // 【新语义】本帧 b_sof 出现的次数（正常应该 = 1）
    output reg  [15:0] lead_last            // 【新语义】最近一次 b_sof → a_sof 的间隔（拍）
);

    // ================================================================
    // 一、挂起状态：看到 B 帧首时，A 不在帧首就挂起，等 A 帧首放开
    //   ★ `held_eff` 让 a_sof 在【组合上】立刻生效：
    //     否则 a_sof 那一拍 held 还是 1 ⇒ 收不进队首的 B[0] ⇒ 整体错 1 个像素 ✗
    // ================================================================
    reg  held;                              // 1 = 挂起中（这一段时间不收 B）
    wire held_eff = held & ~a_sof;          // a_sof 那一拍立刻放开（组合，只依赖寄存器与输入）

    always @(posedge clk) begin
        if (!rst_n) begin                   // 复位
            held <= 1'b0;                   //   不挂起
        end else if (b_sof) begin           // B 帧首出现
            // ★★ 这里必须是 `~a_sof`，**绝不能"简化"成 `1'b1`**！
            //   原因：`b_sof` 在挂起期间是【电平】（AXIS 要求主机举着不放），
            //   而这一支的优先级**高于**下一支的 a_sof ⇒ 若赋常量 1，a_sof 那一拍
            //   也会被赋 1 ⇒ held 永远清不掉 ⇒ b_ready 永远 0 ⇒ 配对永久死锁 ✗✗
            //   现在这个写法之所以安全，正是因为 `~a_sof` 在 a_sof 那一拍恰好
            //   求值为 0，与"退出挂起"的条件自洽 ✓
            //   ★ 它同时带来一个有用的"粘性"：挂起期间每拍都重新满足进入条件 ⇒
            //   若 a_sof 那一拍数据没来（队首没被收走），下一拍会自动重新挂起 ⇒
            //   队首（仍是 B[0]）不前进 ⇒ 下一帧再对齐一次，只损失一帧、不错位 ✓
            held <= ~a_sof;                 //   A 不在帧首 ⇒ 挂起；与 a_sof 同拍 ⇒ 不挂起
        end else if (a_sof) begin           // A 帧首到了
            held <= 1'b0;                   //   放开
        end
    end

    // ================================================================
    // 二、反压与传输
    //   `b_ready = a_valid & ~held_eff & ~(b_sof & ~a_sof)`
    //     · a_valid      ⇒ 只在 A 有像素那一拍收 ⇒ 严格 1:1（速率对齐）
    //     · ~held_eff    ⇒ 挂起期间一个都不收（把队首钉在 B[0] 不动）
    //     · 后一项       ⇒ b_sof 那一拍若 A 不在帧首（说明错开了），当拍也不收，
    //                       避免把 B[0] 配到帧中间的位置上
    //   ★ 只依赖寄存器与输入，不依赖 b_xfer ⇒ 不会形成组合环
    // ================================================================
    wire b_ready_i = a_valid & ~held_eff & ~(b_sof & ~a_sof);   // 这一拍收不收
    assign b_ready = b_ready_i;                                  // 回给 VDMA 的 tready

    wire b_xfer = b_valid & b_ready_i;      // 这一拍真的收到了一个 B 像素

    // ================================================================
    // 三、输出：严格跟 A 的节拍（A 有像素就必定有一个输出）
    // ================================================================
    always @(posedge clk) begin
        if (!rst_n) begin                   // 复位
            out_valid <= 1'b0;              //   输出无效
            out_pix   <= {DW{1'b0}};
            out_sof   <= 1'b0;
            out_eol   <= 1'b0;
            out_eof   <= 1'b0;
            out_b_pix <= {DW{1'b0}};
        end else if (a_valid) begin         // A 有像素
            out_valid <= 1'b1;              //   ★ 严格跟 A 的节拍
            out_pix   <= a_pix;             //   A 像素打 1 拍
            out_sof   <= a_sof;             //   sideband 五根一起打拍
            out_eol   <= a_eol;
            out_eof   <= a_eof;
            out_b_pix <= b_xfer ? b_pix : a_pix;   // 收到 B 就用它；没收到 ⇒ 用 A 顶替（差分 = 0，不误报）
        end else begin                      // A 没像素（消隐）
            out_valid <= 1'b0;              //   输出无效（下游差分 = 0，几何不受影响）
        end
    end

    // ================================================================
    // 四、诊断（给 PS 读；每个 a_sof 结账一次）
    //
    //   ★★ 必须注意：挂起期间 `b_sof` 是【电平】不是脉冲！
    //      AXIS 规定 tvalid=1 且 tready=0 时主机必须保持 TDATA/TUSER 不变 ⇒
    //      从我们按住到 a_sof 放开之间，b_sof 会**一直为 1**（可能持续整个场消隐，
    //      约 93 万拍）。⇒ 凡是"数 b_sof 次数"的地方必须用【上升沿】，直接数电平
    //      会在一个消隐期里就数到饱和 ✗
    //   ★ 同理，`stall_cnt` 只能数"挂起期间还来了 A 像素"的拍 —— 那才是真正的
    //      盲带宽度；若把消隐期也算进去，会瞬间饱和成一个没有意义的数 ✗
    // ================================================================
    reg        b_sof_d;                     // b_sof 打一拍（做边沿检测）
    reg [15:0] gap_pix;                     // 自最近一次 b_sof 起，出现了几个 A 有效像素

    wire b_sof_rise = b_sof & ~b_sof_d;     // b_sof 上升沿 = "B 这一帧的帧首到了"

    always @(posedge clk) begin
        if (!rst_n) begin
            lead_max  <= 16'd0;
            stall_cnt <= 16'd0;
            lap_cnt   <= 16'd0;
            lead_last <= 16'd0;
            gap_pix   <= 16'd0;
            b_sof_d   <= 1'b0;
        end else begin
            b_sof_d <= b_sof;                                       // 边沿检测用的延迟

            // ---- 量"这次帧首之后牺牲了几个 A 像素"（稳态应为 0）----
            if (b_sof_rise) begin
                gap_pix <= 16'd0;                                   // 新的一次帧首 ⇒ 重新数
            end else if (a_valid && gap_pix != 16'hFFFF) begin
                gap_pix <= gap_pix + 16'd1;                         // 数 A 有效像素（饱和）
            end

            // ---- 帧首结账 ----
            if (a_sof) begin                                        // A 帧首：结算上一帧
                lead_last <= gap_pix;                               //   b_sof→a_sof 之间牺牲了几个 A 像素
                lap_cnt   <= 16'd0;                                 //   本帧 b_sof 计数清零
                lead_max  <= 16'd0;                                 //   本帧"没配上"计数清零
                stall_cnt <= 16'd0;                                 //   本帧"盲带"计数清零
            end else begin
                if (b_sof_rise) begin                               // 本帧又见到一次 B 帧首（★ 用边沿！）
                    lap_cnt <= lap_cnt + 16'd1;                     //   正常应该 = 1；多了说明错开过
                end
                if (a_valid & ~b_xfer) begin                        // A 有像素但没配上 B
                    if (lead_max != 16'hFFFF) lead_max <= lead_max + 16'd1;   // 计数（饱和）
                end
                if (held_eff & a_valid) begin                       // ★ 挂起中且 A 来了像素 = 真盲带
                    if (stall_cnt != 16'hFFFF) stall_cnt <= stall_cnt + 16'd1; // 计数（饱和）
                end
            end
        end
    end

endmodule
