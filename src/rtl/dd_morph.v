// dd_morph.v
//
//   第⑥级：二值形态学 —— **闭运算**（先膨胀、后腐蚀）。
//
//   在定位流水线里的位置（由 defect_detect.v 例化）：
//       … ──► 支路A/支路B 取或 ──► [dd_morph] ──► 最终目标掩膜
//                                  第⑥级
//
//   接口与其它 dd_* 一致：五根 sideband（valid/sof/eol/eof）+ 1 位数据。
//
//   ====================================================================
//   ① 它是干嘛的 · ★作用 · ★重要性
//   ====================================================================
//
//   **一句话**：形态学是"在二值图上做几何整形"的算法 ——
//   膨胀 = 把白区往外扩 k 个像素；腐蚀 = 往内缩 k 个像素。
//
//       开运算 = 先腐蚀 → 后膨胀   ⇒ **删掉小东西**、断开细连接
//       闭运算 = 先膨胀 → 后腐蚀   ⇒ **填平小洞**、把邻近的段连起来
//
//   ★ 本模块做的是**闭运算**，这一点没有商量余地。
//     一提"形态学去噪"很多人默认开运算，但开运算是先腐蚀 ——
//     那会直接把我们要找的小目标删掉（0.3 mm ≈ 3.6 px，腐蚀一次就没了）。
//     **在这个项目里，开运算是有害的。**
//
//   ★★ 重要性：**本模块是"支路 B（Sobel）"的兑现器** ★★
//
//   支路 B 报的是"**边**"不是"目标"，直接取或之后：
//
//     目标类型         支路A(灰度阈值)   支路B(Sobel)     取或之后          后果
//     ------------------------------------------------------------------------
//     亮细线(对比够)   报中心            报两侧[注]       实心 3 列   ✓    能用
//     淡细线(A报不出)  **啥也不报**      报两侧[注]       **两条断线** ✗   一个细线被连通域
//                                                                          数成两个 ⇒ 数量翻倍
//     淡斑块(A报不出)  **啥也不报**      只报外圈         **一个空心环** ✗ 面积只算成"周长"、
//                                                                          填充率极低
//
//     [注] "两侧"是说**输入拍号** ce；RTL 输出的命中对应的永远是**窗口中心**，
//          所以画在二值图上，B 报的是细线**左右紧邻的那两个背景像素**。
//
//   ⇒ **支路 B 单独给出的东西，PS 拿去根本没法用。**
//     而"淡目标"恰恰是**加支路 B 的唯一理由** ——
//     也就是说：**不加这一级，支路 B 就是白加的。**
//
//   闭运算一进来，最后两行立刻变成第一行：
//     · 淡细线：左轮廓扩成 {c-1,c,c+1}、右轮廓扩成 {c-1,c,c+1} ⇒ **在中间碰头**
//               再腐蚀回去 ⇒ 一条**实心 3 列**的带 ⇒ 连通域数量 2 → 1 ✓
//     · 淡斑块：外圈膨胀后中心被填满 ⇒ 腐蚀后回到**实心 3×3** ✓
//
//   ====================================================================
//   ② 能带来什么提升
//   ====================================================================
//     · 淡目标连通域数量 2 → 1（不再翻倍）
//     · 淡斑块面积从"周长像素"变成实心面积
//     · 资源：**≈ +250 LUT、0 BRAM、0 DSP、+2 拍延迟**
//       —— 关键是**只做二值形态学（1 位宽）**：二值行缓冲用 SRL 推，
//          一行 972 位 ≈ 31 个 LUT；灰度形态学才需要每级一个 BRAM + 8 个 8 位比较器。
//     · 对帧率 / 吞吐 / AXIS 握手 **零影响**（纯旁听者，不碰 tready）
//
//   ====================================================================
//   ③ 要注意什么（每一条都是设计时算过的）
//   ====================================================================
//   1. **顺序绝对不能反**：先膨胀后腐蚀 = 闭运算（保目标）；
//      先腐蚀后膨胀 = 开运算（**删目标**）。这是本模块唯一"写反了全错"的地方。
//   2. **结构元是 3×3**：细线两条轮廓间距只有 1 像素，一次 3×3 膨胀刚好碰头。
//      要连间距更大的东西就得上 5×5（行缓冲从 2 行变 4 行）。
//   3. ★ **腐蚀级的行缓冲深度是 970，不是 972**：
//      膨胀级的输出每行只有 H_ACTIVE-2 = 970 个有效像素（前 2 列被屏蔽掉了），
//      所以腐蚀级"往上找一行"要走 **970 个有效像素**。写成 972 会让整幅
//      在垂直方向错 2 个像素 —— 屏幕上完全看不出来，只能靠仿真抓。
//   4. ★ **每级的"行延迟"是空间延迟，不落在 sideband 上** ——
//      和 dd_win3x3 同一条结论：本模块整体只比输入晚 **2 拍**（每级 1 拍），
//      不是 1 行、也不是 4 拍。一旦按"延迟一行"去凑 sideband，
//      空拍（反压）一出现就整幅错位。
//   5. ★ **旁路必须和闭运算"逐像素、逐拍"对齐**，否则输出多路选择的
//      两条支路 sof/eol/eof 时序不一致，会在帧边界切错 ⇒ 统计每帧差几个像素。
//      做法：旁路直接取膨胀级的 **d2b 抽头**（它正好是"窗口中心往左上两行两列"
//      那个原始像素），再打 2 拍。推导见第 4 节。
//   6. **不门控的 sideband + 门控的数据寄存器**：空拍（反压）时数据全部冻结、
//      sideband 照常往前走一拍，两条规则配合，任何空拍图案都不会错位。
//   7. **延迟线（移位寄存器）绝不加复位**：加了 Vivado 推不出 SRL，
//      会退化成几万个 FF（一行 972 位 × 4 条 = 3888 个）。
//   8. **帧首 2 行 2 列拿不到完整邻域** ⇒ 直接用 out_valid 屏蔽掉，
//      不做边界复制。两级串联后又多屏蔽 2 行 2 列 ⇒ 一共 4 行 4 列
//      （720 行的 0.55%），放置物边缘上的目标落进这一圈会漏，这是已知代价。
//   9. **闭运算去不掉比结构元还大的噪声块** —— 那要用开运算，而开运动会删小目标。
//      这个矛盾只能交给 PS 的形状判别，不是本模块能解决的。
//   10. **本模块不管**：区分"目标"和"放置物边缘/正常纹理"（PS 的包围盒掩膜）、
//      尺寸测量（闭运算会让边缘外扩 1 px，PS 量尺寸要减回去）。
//
//   ====================================================================
//   ④ 优化能起到什么效果（评估过、结论是"不做"）
//   ====================================================================
//     · **可分离结构元**（3×1 + 1×3）：OR/AND 从 8 输入降到 4 输入，
//       省约 30 个 LUT；代价是多两次打拍 + 复杂度上升 ⇒ **不做**，收益太小。
//     · **只膨胀不腐蚀**（半闭运算）：省掉第二套行缓冲和窗口
//       ⇒ 省一半逻辑、少 1 拍；代价是目标区**永久加宽 1 像素**。
//       ⇒ 有用，但会让尺寸测量整体偏大，先按完整闭运算做；要改随时可以。
//     · **两级共用一套行缓冲**：**做不到** —— 腐蚀吃的是膨胀的输出，
//       两股数据同时在管子里。
//     · **自适应结构元**（3×3/5×5 可切）：要 4 行缓冲 + 额外寄存器 ⇒ **不建议**。
//
//   ====================================================================
//   本模块延迟 **2 拍**（每级 1 拍）
//   ====================================================================
//     · 每级的 3×3 窗口在"吃下像素的那一拍"就齐了（抽头本身都是寄存器），
//       所以每级只有 1 个输出寄存器 ⇒ 每级 1 拍，两级共 2 拍。
//     · 空间上：闭运算输出的中心比输入晚 "2 行 + 2 列"（两级各 1 行 1 列）。
//
//   --------------------------------------------------------------------
//   注释规范（项目要求，2026-09-24）
//   --------------------------------------------------------------------
//       每一行有实际功能的代码，行尾都跟一条中文注释，说明"这行在做什么 / 为什么"。
//       本文件以 **UTF-8（无 BOM）** 编码保存。
//////////////////////////////////////////////////////////////////////////////

module dd_morph #(
    parameter integer H_ACTIVE = 972      // 每行有效像素数（= 一行的空间延迟，单位是"有效像素"不是"拍"）
)(
    // ------------------------------------------------------------------
    // 时钟与复位
    // ------------------------------------------------------------------
    input  wire        clk,        // aclk，100MHz
    input  wire        rst_n,      // 低有效复位；只清控制寄存器和计数器，**不清延迟线**

    // ------------------------------------------------------------------
    // 二值输入（来自 defect_detect 的 A|B 取或）
    // ------------------------------------------------------------------
    input  wire        in_hit,     // 1 = 本像素在掩膜里是白的
    input  wire        in_valid,   // 本拍有有效像素
    input  wire        in_sof,     // 帧首（已带 valid 限定）
    input  wire        in_eol,     // 行尾（已带 valid 限定）
    input  wire        in_eof,     // 帧尾（已带 valid 限定）

    // ------------------------------------------------------------------
    // 控制（来自 DEF_TH[3]）
    // ------------------------------------------------------------------
    input  wire        cfg_en,     // 0 = 整级旁路（输出退化成"原始掩膜"）
                                   // ★ 旁路**不改变延迟、不改变屏蔽范围**，
                                   //   只把"闭运算结果"换成"原始掩膜"，
                                   //   所以开关是可在线切换的、统计口径一致、可直接对比。

    // ------------------------------------------------------------------
    // 二值输出（比输入晚 2 拍）
    // ------------------------------------------------------------------
    output wire        out_hit,    // 闭运算后的掩膜（cfg_en=0 时是原始掩膜）
    output wire        out_valid,  // 本拍有有效输出
    output wire        out_sof,    // 帧首：本帧第一个有效输出
    output wire        out_eol,    // 行尾：本行最后一个有效输出
    output wire        out_eof     // 帧尾：本帧最后一个有效输出
);

    //=====================================================================
    // 第 0 节：控制参数锁存与延迟对齐
    //
    //   ★ 参数在 `in_sof` 那一拍**锁存**（帧内恒定），然后在输出级使用。
    //     通用公式（dd_sobel 那一级推导出来的）：
    //         参数延迟链的拍数 =（窗口进入到参数被使用之间的拍数）− 1
    //     本模块窗口进入到参数被使用之间是 **2 拍**（两级输出寄存器）
    //     ⇒ 参数再延迟 **1 拍**。
    //   验算：
    //     · 帧首那个像素（拍 T 进入）⇒ 拍 T+2 被使用 ⇒ en_d1 = en_cur(拍 T+1) = **新值** ✓
    //     · 前一帧最后一个像素（拍 T-1 进入）⇒ 拍 T+1 被使用
    //                                      ⇒ en_d1 = en_cur(拍 T) = **旧值** ✓
    //   ★ 如果直接拿 en_cur 去选，就会让"sof 前一个像素"用上新值
    //     ⇒ 每帧边界错 1 个像素，屏幕上完全看不出来。
    //=====================================================================
    reg en_cur;                                     // 本帧生效的使能（帧首锁存）
    reg en_d1;                                      // 再延迟 1 拍，供输出级使用

    always @(posedge clk) begin
        if (!rst_n) begin                           // 复位
            en_cur <= 1'b0;                         // 默认关闭 ⇒ 输出使用旁路
            en_d1  <= 1'b0;                         // 延迟链清零
        end else begin                              // 正常推进
            if (in_valid & in_sof) en_cur <= cfg_en;// ★ 只在帧首那一拍更新
            en_d1 <= en_cur;                        // 参数延迟链（1 拍）
        end
    end

    //=====================================================================
    // 第 1 节：膨胀级（3×3 结构元，OR of 9）
    //
    //   行缓冲怎么搭：**按 in_valid 门控的移位寄存器**，不用 RAM。
    //   为什么可以用移位寄存器（而 dd_win3x3 用的是 BRAM）：
    //     · 数据只有 **1 位**。一行 972 位的移位寄存器 ≈ 31 个 LUT（推成 SRL），
    //       而一个 1024×1 的 BRAM 至少要占掉一整块 RAMB18 ⇒ 用 RAM 反而贵 4 倍。
    //     · 门控写在 `if (in_valid)` 上 ⇒ 空拍时冻结 ⇒ 延迟是"**多少个有效像素**"
    //       而不是"多少个时钟" ⇒ 有反压也不会错位（等价于 dd_win3x3 用列号当地址）。
    //   ★★ 绝对不给延迟线加复位 ★★
    //     加了以后 Vivado 推不出 SRL（SRL 没有复位端），会退化成 972 个 FF。
    //=====================================================================
    reg [9:0] d_row_cnt;        // 膨胀级：帧内行号
    reg [9:0] d_col_cnt;        // 膨胀级：行内列号
    reg [1:0] d_rows_seen;      // 本帧**已经走完**的行数，饱和在 3（判边界，省比较器）
    reg [1:0] d_cols_seen;      // 本行**已经走过**的像素数，饱和在 3

    always @(posedge clk) begin
        if (!rst_n) begin                               // 复位
            d_row_cnt   <= 10'd0;                       // 行号归零
            d_col_cnt   <= 10'd0;                       // 列号归零
            d_rows_seen <= 2'd0;                        // 一行都还没走完
            d_cols_seen <= 2'd0;                        // 一个像素都还没走
        end else if (in_valid) begin                    // ★ 只在有效像素拍推进，空拍全部冻结
            // ★★ 坐标系在**帧尾**清零，不在帧首清零 ★★（dd_win3x3 用一整轮返工换来的）
            //   计数器在时钟沿更新、更新的是"下一拍"的值；写在 in_sof 里会让
            //   含 sof 的那一整行地址整体错一列，只有以该行为上行的那条输出行出错。
            if (in_eof) begin                           // 帧尾：整帧坐标系归零
                d_row_cnt   <= 10'd0;                   // 下一帧从第 0 行开始
                d_col_cnt   <= 10'd0;                   // 下一帧从第 0 列开始
                d_rows_seen <= 2'd0;                    // 边界计数器清零
                d_cols_seen <= 2'd0;                    // 边界计数器清零
            end else if (in_eol) begin                  // 行尾：本行结束
                d_row_cnt   <= d_row_cnt + 1'b1;        // 行号 +1
                d_col_cnt   <= 10'd0;                   // 下一拍从新行的第 0 列开始
                d_cols_seen <= 2'd0;                    // 新行重新数像素
                if (d_rows_seen != 2'd3) d_rows_seen <= d_rows_seen + 2'd1;  // 已走完行数 +1，饱和在 3
            end else begin                              // 行内普通像素
                d_col_cnt <= d_col_cnt + 1'b1;          // 列号 +1
                if (d_cols_seen != 2'd3) d_cols_seen <= d_cols_seen + 2'd1;  // 已走像素数 +1，饱和在 3
            end
        end
    end

    // ---- 行延迟：两条 972 位的移位链（★ 不加复位、★ 只在有效像素拍推进）----
    //   sr[i] 在第 k 拍等于"第 k-1-i 拍进来的值" ⇒ 取最高位 sr[N-1] 正好延迟 **N** 个像素。
    //   所以位宽取 H_ACTIVE，抽最高位 = 延迟 972 个有效像素 = **整整一行** ✓
    (* srl_style = "srl" *) reg [H_ACTIVE-1:0] d_ln1;   // 延迟 1 行
    (* srl_style = "srl" *) reg [H_ACTIVE-1:0] d_ln2;   // 延迟 2 行

    always @(posedge clk) begin
        if (in_valid) begin                             // ★ 只在有效像素拍推进
            d_ln1 <= {d_ln1[H_ACTIVE-2:0], in_hit};                     // 新像素从最低位进
            d_ln2 <= {d_ln2[H_ACTIVE-2:0], d_ln1[H_ACTIVE-1]};          // 再延迟一行
        end
    end

    wire d_row0 = in_hit;                   // 第 r   行 · 当前列（本拍刚进来的像素）
    wire d_row1 = d_ln1[H_ACTIVE-1];        // 第 r-1 行 · 当前列
    wire d_row2 = d_ln2[H_ACTIVE-1];        // 第 r-2 行 · 当前列

    // ---- 列延迟链：每行再取出"左一列""左二列"（每行 2 个 FF）----
    reg d0a, d0b;                           // 第 r   行：左一列、左二列
    reg d1a, d1b;                           // 第 r-1 行：左一列、左二列
    reg d2a, d2b;                           // 第 r-2 行：左一列、左二列

    always @(posedge clk) begin
        if (in_valid) begin                             // ★ 同样只在有效像素拍推进
            d0a <= d_row0; d0b <= d0a;                  // 第 r   行的列延迟链
            d1a <= d_row1; d1b <= d1a;                  // 第 r-1 行的列延迟链
            d2a <= d_row2; d2b <= d2a;                  // 第 r-2 行的列延迟链
        end
    end

    // ---- 3×3 窗口（抽头全部是寄存器 ⇒ 本拍就齐了）----
    //   窗口中心 = d1a = (r-1, c-1)，与 dd_win3x3 的 w11 约定一致
    wire d_w00 = d2b, d_w01 = d2a, d_w02 = d_row2;      // 第 r-2 行：左二列 / 左一列 / 当前列
    wire d_w10 = d1b, d_w11 = d1a, d_w12 = d_row1;      // 第 r-1 行：左二列 / 左一列 / 当前列 ← 中心
    wire d_w20 = d0b, d_w21 = d0a, d_w22 = d_row0;      // 第 r   行：左二列 / 左一列 / 当前列

    // ---- 膨胀 = 9 个抽头取或（8 输入 OR 树，深度 4 级 LUT）----
    wire d_dil = d_w00 | d_w01 | d_w02                  // 上上行的三个
               | d_w10 | d_w11 | d_w12                  // 上一行的三个（含中心）
               | d_w20 | d_w21 | d_w22;                 // 当前行的三个

    // ---- 膨胀级的边界判定（在**输入那一拍**算好，再跟窗口一起打拍）----
    //   d_cols_seen[1] = "本行已经走过 ≥2 个像素" ⇒ 第 c-2 列是真实像素 ⇒ 3×3 邻域完整
    //   d_rows_seen[1] = "本帧已经走完 ≥2 行"     ⇒ 第 r-2 行是真实行   ⇒ 否则行缓冲里是上一帧的残留
    wire d_in_ok    = in_valid & d_cols_seen[1] & d_rows_seen[1];                    // 本拍窗口完整
    wire d_in_first = in_valid & (d_cols_seen == 2'd2) & (d_rows_seen == 2'd2);      // 本帧第一个完整窗口

    // ---- 膨胀级的输出寄存器（★ 本级的唯一寄存器级 = 1 拍）----
    //
    //   ★★ 这里的门控为什么用"本拍"的 in_valid & d_in_ok，而不像 dd_win3x3
    //      那样用延迟 1 拍的 v1 & ok1 ★★（第一次写就栽在这里，被 tb 抓出来）
    //
    //   dd_win3x3 的窗口抽头**全是寄存器**（BRAM 输出寄存器、row_c_d、列延迟链）
    //   ⇒ 在拍 t+1 才凑齐"输入拍 t 的窗口" ⇒ 必须拿延迟 1 拍的 v1&ok1 去对齐。
    //   本模块的抽头里 `d_row0 = in_hit` 是**线网**（本拍刚进来的值直接进窗口）
    //   ⇒ 窗口在**拍 t 就描述输入拍 t** ⇒ 门控必须用**本拍**的 in_valid & d_in_ok。
    //   照抄 dd_win3x3 的 v1&ok1 会让两级各多错 1 拍，合起来整整错 2 拍：
    //   现象是**每行开头少 2 拍有效、行尾多 2 拍**、sof 晚 2 拍 —— 屏幕上完全看不出来。
    //   ★ 一句话规律：**门控的拍数 = 窗口抽头相对输入延迟了几拍**。
    reg dil_r, dil_v, dil_sof, dil_eol, dil_eof;        // 膨胀结果 + 四根 sideband

    always @(posedge clk) begin
        if (!rst_n) begin                               // 复位
            dil_r <= 1'b0; dil_v <= 1'b0;               // 结果清零
            dil_sof <= 1'b0; dil_eol <= 1'b0; dil_eof <= 1'b0;  // sideband 清零
        end else if (in_valid & d_in_ok) begin          // ★ 本拍窗口完整 ⇒ 采下本拍的 d_dil
            dil_r   <= d_dil;                           // 膨胀结果进寄存器（组合链到此为止）
            dil_v   <= 1'b1;                            // 有窗口 ⇒ 输出 valid
            dil_sof <= d_in_first;                      // 帧首：只在本帧第一个有效窗口上拉高
            dil_eol <= in_eol;                          // 行尾：同一拍一起进来
            dil_eof <= in_eof;                          // 帧尾：同一拍一起进来
        end else begin                                  // 本拍没有有效窗口
            dil_v   <= 1'b0;                            // valid 拉低（其余保持，反正被掩掉）
            dil_sof <= 1'b0; dil_eol <= 1'b0; dil_eof <= 1'b0;  // sideband 拉低
        end
    end
    // ★ 说明：`dil_eol` 只在"本拍窗口完整"时才拉高。这在本设计里是安全的 ——
    //   屏蔽只砍掉每行**最前面 2 列**，最后一列（第 971 列）永远是完整窗口，
    //   所以"行的最后一个有效窗口"和"行尾"必然同拍，不会丢行尾。

    //=====================================================================
    // 第 2 节：腐蚀级（3×3 结构元，AND of 9）
    //
    //   结构与膨胀级**完全相同**，只有两点不同：
    //     ① 归约从 OR 换成 AND（这就是"闭运算"里的第二步）
    //     ② ★ 行缓冲深度是 **H_ACTIVE-2 = 970**，不是 972 ★
    //        因为膨胀级的输出每行只有 970 个有效像素
    //        （原图第 0、1 列被 d_in_ok 屏蔽掉了）。
    //        写成 972 会让整幅在垂直方向错 2 个像素 —— 屏幕上完全看不出来。
    // ====================================================================
    reg [9:0] e_row_cnt;        // 腐蚀级：输入流（= 膨胀级输出）的行号
    reg [9:0] e_col_cnt;        // 腐蚀级：输入流的列号
    reg [1:0] e_rows_seen;      // 已走完的行数，饱和在 3
    reg [1:0] e_cols_seen;      // 本行已走过的像素数，饱和在 3

    always @(posedge clk) begin
        if (!rst_n) begin                               // 复位
            e_row_cnt   <= 10'd0;                       // 行号归零
            e_col_cnt   <= 10'd0;                       // 列号归零
            e_rows_seen <= 2'd0;                        // 一行都还没走完
            e_cols_seen <= 2'd0;                        // 一个像素都还没走
        end else if (dil_v) begin                       // ★ 只有在膨胀级输出有效的拍才推进
            if (dil_eof) begin                          // 帧尾：坐标系归零（同样写在帧尾）
                e_row_cnt   <= 10'd0;                   // 下一帧从第 0 行开始
                e_col_cnt   <= 10'd0;                   // 下一帧从第 0 列开始
                e_rows_seen <= 2'd0;                    // 边界计数器清零
                e_cols_seen <= 2'd0;                    // 边界计数器清零
            end else if (dil_eol) begin                 // 行尾
                e_row_cnt   <= e_row_cnt + 1'b1;        // 行号 +1
                e_col_cnt   <= 10'd0;                   // 下一拍从新行第 0 列开始
                e_cols_seen <= 2'd0;                    // 新行重新数像素
                if (e_rows_seen != 2'd3) e_rows_seen <= e_rows_seen + 2'd1;  // 已走完行数 +1，饱和在 3
            end else begin                              // 行内普通像素
                e_col_cnt <= e_col_cnt + 1'b1;          // 列号 +1
                if (e_cols_seen != 2'd3) e_cols_seen <= e_cols_seen + 2'd1;  // 已走像素数 +1，饱和在 3
            end
        end
    end

    // ---- 行延迟：两条 **970** 位的移位链（★ 不加复位）----
    localparam integer ERO_LINE = H_ACTIVE - 2;     // 膨胀级每行的有效像素数

    (* srl_style = "srl" *) reg [ERO_LINE-1:0] e_ln1;   // 延迟 1 行（970 个有效像素）
    (* srl_style = "srl" *) reg [ERO_LINE-1:0] e_ln2;   // 延迟 2 行

    always @(posedge clk) begin
        if (dil_v) begin                                // ★ 只在膨胀级输出有效的拍推进
            e_ln1 <= {e_ln1[ERO_LINE-2:0], dil_r};                      // 新像素从最低位进
            e_ln2 <= {e_ln2[ERO_LINE-2:0], e_ln1[ERO_LINE-1]};          // 再延迟一行
        end
    end

    wire e_row0 = dil_r;                    // 输入流 · 当前列
    wire e_row1 = e_ln1[ERO_LINE-1];        // 输入流 · 上一行同列
    wire e_row2 = e_ln2[ERO_LINE-1];        // 输入流 · 上上行同列

    // ---- 列延迟链（每行 2 个 FF）----
    reg e0a, e0b;                           // 当前行：左一列、左二列
    reg e1a, e1b;                           // 上一行：左一列、左二列
    reg e2a, e2b;                           // 上上行：左一列、左二列

    always @(posedge clk) begin
        if (dil_v) begin                                // ★ 同样只在有效拍推进
            e0a <= e_row0; e0b <= e0a;                  // 当前行的列延迟链
            e1a <= e_row1; e1b <= e1a;                  // 上一行的列延迟链
            e2a <= e_row2; e2b <= e2a;                  // 上上行的列延迟链
        end
    end

    // ---- 3×3 窗口（抽头全部是寄存器）----
    wire e_w00 = e2b, e_w01 = e2a, e_w02 = e_row2;      // 上上行：左二列 / 左一列 / 当前列
    wire e_w10 = e1b, e_w11 = e1a, e_w12 = e_row1;      // 上一行：左二列 / 左一列 / 当前列 ← 中心
    wire e_w20 = e0b, e_w21 = e0a, e_w22 = e_row0;      // 当前行：左二列 / 左一列 / 当前列

    // ---- 腐蚀 = 9 个抽头取与（★ 这就是闭运算的第二步）----
    //   注意：**不能**在这里再判一次"窗口不完整就输出 0" ——
    //   输出 valid 已经由 e_ok1 那一级统一掩掉了（见下面），
    //   在这里再判一次只是白花 LUT。
    wire e_ero = e_w00 & e_w01 & e_w02                  // 上上行的三个
               & e_w10 & e_w11 & e_w12                  // 上一行的三个（含中心）
               & e_w20 & e_w21 & e_w22;                 // 当前行的三个

    // ---- 腐蚀级的边界判定 ----
    //   要求：膨胀级的输出流里"已经走完 ≥2 行"且"本行已走过 ≥2 个像素"。
    //   换算成原图坐标，这就是"原图行 ≥4、列 ≥4" —— 正好等于两级各屏蔽 2 行 2 列的叠加 ✓
    wire e_in_ok    = dil_v & e_cols_seen[1] & e_rows_seen[1];                      // 本拍窗口完整
    wire e_in_first = dil_v & (e_cols_seen == 2'd2) & (e_rows_seen == 2'd2);        // 本帧第一个完整窗口

    // ---- 腐蚀级的输出寄存器（本模块最后一级）----
    //   门控同样用**本拍**的 dil_v & e_in_ok：本级的抽头同样含线网（e_row0 = dil_r 是
    //   寄存器，但窗口描述的就是**本拍**消费掉的那个 dil 像素）⇒ 不需要再延迟一拍。
    reg ero_r, ero_v, ero_sof, ero_eol, ero_eof;        // 闭运算结果 + 四根 sideband

    always @(posedge clk) begin
        if (!rst_n) begin                               // 复位
            ero_r <= 1'b0; ero_v <= 1'b0;               // 结果清零
            ero_sof <= 1'b0; ero_eol <= 1'b0; ero_eof <= 1'b0;  // sideband 清零
        end else if (dil_v & e_in_ok) begin             // ★ 本拍窗口完整 ⇒ 采下本拍的 e_ero
            ero_r   <= e_ero;                           // 闭运算结果进寄存器
            ero_v   <= 1'b1;                            // 有窗口 ⇒ 输出 valid
            ero_sof <= e_in_first;                      // 帧首
            ero_eol <= dil_eol;                         // 行尾：与 dil 的最后一个有效窗口同拍
            ero_eof <= dil_eof;                         // 帧尾：同上
        end else begin                                  // 本拍没有有效窗口
            ero_v   <= 1'b0;                            // valid 拉低
            ero_sof <= 1'b0; ero_eol <= 1'b0; ero_eof <= 1'b0;  // sideband 拉低
        end
    end

    //=====================================================================
    // 第 3 节：旁路延迟线 —— 为什么直接取 d2b，为什么只打 2 拍
    //
    //   ★ 这一步是本模块最容易写错的地方，把推导写下来。
    //
    //   记号：设输入像素在拍 T 的坐标是 (R, C)。
    //     · 膨胀级窗口在拍 T 的中心 = (R-1, C-1)，其中 d2b = (R-2, C-2)
    //     · 膨胀结果 dil_r 在拍 T+1 = 位置 (R-1, C-1) 的膨胀值
    //     · 腐蚀级在拍 u 的窗口中心 = dil 流的 (P-1, Q-1)，
    //       其中 (P,Q) 是拍 u 消费掉的那个 dil 像素 = 拍 u-1 的输入对应的 (R-1,C-1)
    //       ⇒ 腐蚀级在拍 u 的中心 = (R(u-1)-2, C(u-1)-2)
    //       ⇒ ero_r 在拍 u+1 = 位置 (R(u-1)-2, C(u-1)-2) 的闭运算值
    //
    //   我们要旁路在**同一拍 u+1** 输出**同一位置**的原始掩膜，
    //   也就是要拿到"输入像素 (R(u-1)-2, C(u-1)-2)"。
    //   而在拍 v = u-1，膨胀级的抽头 **d2b 正好就是 (R(v)-2, C(v)-2)**
    //   ⇒ d2b 再打 **2 拍** 就落在拍 u+1 上 ✓（u+1 = v+2）
    //
    //   ★ 所以旁路 = d2b 延迟 2 拍 ⇒ **与闭运算输出逐像素、逐拍完全对齐** ✓
    //     这个"对齐"是必须的：两条路径的 sof/eol/eof 必须同拍，
    //     否则输出多路选择会在帧边界切错，统计每帧差几个像素（屏幕上看不出来）。
    //     而且因为它俩位置相同，**开/关形态学时的差异就纯粹来自算法本身**，
    //     可以直接拿 0x24 的计数做 A/B 对比 —— 这正是上板标定要的证据。
    //
    //   ★ 旁路**不需要**自己的行缓冲：d2b 抽头已经白拿了 ✓
    //   ★ 空拍（反压）不会拆散它俩：d2b 在空拍冻结，而 byp_d1/d2 虽然照常移位，
    //     但取到的还是那个冻结值；同时闭运算那条路的 valid 也是 0 ⇒
    //     那一拍根本不会被消费 ✓
    //=====================================================================
    //   ★★★ 2026-10-11 修正：旁路原来取 `d2b`，**是错的** ★★★
    //   错在哪：`d2b` = 膨胀级列链上"**2 行前、2 列前**"的抽头 ⇒ 那是**空间延迟**（4 行 4 列的整流位移 ✗），
    //           而闭运算那条路的数据延迟只有 **4 个有效拍**（dil_r 1 + 列链 2 + ero_r 1）。
    //   ⇒ 两条路的位置对不上：默认配置 morph_en=0 下，掩膜整体偏 (2 行, 2 列) ✗
    //     —— 集成测试实测：图案画在原图行 6..22 的两条竖线，旁路只有 26 个命中、而模型/几何都是 34 ✗，
    //        差的正是被推移到有效区之外的 4 行。
    //   ⇒ 正解：旁路送**原始掩膜 in_hit**，按**与 dil_r 完全相同的门控**（in_valid & d_in_ok）
    //     延迟 **4 个有效拍** ✓ —— 4 拍这个数是用模块单元测试台 `tb_dd_morph` 定的：
    //     2 拍时在那 8 个格子上整体早 2 列（[ERR] pos=(2..5,398/402)），改 4 拍后 **455157 次比对 0 错** ✓。
    //   ★ 门控必须是 `in_valid & d_in_ok`（不是裸 in_valid）：闭运算那条路的寄存器都在这个域里，
    //     旁路也要同域，空拍才不会多推、帧间才不会漂。
    //   ★ 空拍（反压）不会拆散它俩：两条路共用同一门控，空拍一起冻结 ✓
    //=====================================================================
    reg byp_d1, byp_d2, byp_d3, byp_d4;                 // 旁路数据：原始掩膜延迟 4 个有效拍

    always @(posedge clk) begin
        if (in_valid & d_in_ok) begin                   // ★ 与 dil_r 同一门控（同域才不漂）
            byp_d1 <= in_hit;                           // 原始掩膜（★ 不是 d2b）
            byp_d2 <= byp_d1;                           // …
            byp_d3 <= byp_d2;                           // …
            byp_d4 <= byp_d3;                           // …共 4 拍
        end
    end

    //=====================================================================
    // 第 4 节：输出
    //
    //   ★ 五根 sideband **一律取闭运算那一条路的**（ero_*），不管开不开形态学。
    //     理由：旁路与闭运算的位置和拍数已经对齐（第 3 节证明过），
    //     所以两条路共用同一组 sideband 是成立的；共用之后，
    //     输出侧的 valid/sof/eol/eof 在任何开关状态下**都是同一组信号**，
    //     从根上杜绝了"切开关时帧边界切错"这一类问题。
    //   ★ 数据才做多路选择，选择信号用 en_d1（与数据同拍、帧内恒定）。
    //=====================================================================
    assign out_hit   = en_d1 ? ero_r : byp_d4;          // 闭运算 或 原始掩膜（二选一）
    assign out_valid = ero_v;                           // 与 out_hit 同拍
    assign out_sof   = ero_sof;                         // 帧首，晚 2 拍
    assign out_eol   = ero_eol;                         // 行尾，晚 2 拍
    assign out_eof   = ero_eof;                         // 帧尾，晚 2 拍

    //=====================================================================
    // 仿真初值（★ 不是复位）
    //   两条 SRL 行缓冲在"被写过之前"是 X。虽然输出侧有 mor_valid 把关，
    //   但 out_hit 本身还是 X，集成测试（tb_defect_detect）会直接读到它。
    //   用 initial 清零 ⇒ Vivado 落到 SRL 的 INIT 上，不占资源、
    //   也不影响 SRL 推断（★ 给 SRL 加**复位**才会退化成 FF）。
    //=====================================================================
    integer mi;                                         // 初始化循环变量

    initial begin
        d_ln1 = {H_ACTIVE{1'b0}};                       // 膨胀级 1 行缓冲清零
        d_ln2 = {H_ACTIVE{1'b0}};                       // 膨胀级 2 行缓冲清零
        e_ln1 = {ERO_LINE{1'b0}};                       // 腐蚀级 1 行缓冲清零
        e_ln2 = {ERO_LINE{1'b0}};                       // 腐蚀级 2 行缓冲清零
    end

endmodule
