// size_detect.v
//
//   **目标**尺寸统计 —— 包围盒（宽 / 高 / 面积）。
//
//   *** 负责人：队友。请在下面实现模块体。***
//
//   本文件交付时是**只有端口、内部留空**的空壳：顶层已经把它实例化好、
//   每个端口都接好了线，但内部还是占位逻辑，好让工程能编译通过。
//
//   --------------------------------------------------------------------
//   这个模块该做什么（分工契约里约定的）
//   --------------------------------------------------------------------
//     1) 二值化：hit = (gray > th)，极性可以由 polarity 取反。
//        gray 用 RGB565 左对齐补 0 的 px_data 算出来：
//            gray = px_data[23:19] + px_data[15:10] + px_data[7:3]
//        （注意 px_data 不是真 RGB888，见下面的格式说明）
//     2) 在一帧内跟踪所有命中像素的包围盒：
//            min_x, max_x, min_y, max_y   以及   area = 命中像素个数
//     3) 帧末输出：
//            w = max_x - min_x + 1
//            h = max_y - min_y + 1
//        并让 done 拉高一个时钟。
//     4) 整帧一个命中像素都没有时，输出 w = 0、h = 0。
//
//   --------------------------------------------------------------------
//   接口约定（改动前必须先告知另一位负责人）
//   --------------------------------------------------------------------
//     * 本模块是**纯旁听者**，没有 tready，所以永远不可能卡住视频流。
//       不要在这里加任何握手信号。
//     * rst_n 是**低有效**复位。
//     * 坐标约定：x 在一行内数 0..H_ACTIVE-1，遇到 px_eol 归零；
//       y 数 0..V_ACTIVE-1，遇到 px_sof 归零。
//     * px_sof / px_eol / px_eof 在顶层**已经带 px_valid 限定**，
//       所以直接写 "if (px_sof)" 就够了 —— 不要再与一次 px_valid
//       （与了也不错，只是两个模块的写法要统一）。
//
//   --------------------------------------------------------------------
//   px_data 数据格式 —— 重要
//   --------------------------------------------------------------------
//     采集 IP 输出的是 RGB565 **左对齐补 0** 塞进 24 位：
//         px_data[23:16] = {R5, 3'b000}     低位 3 位恒为 0
//         px_data[15: 8] = {G6, 2'b00}      低位 2 位恒为 0
//         px_data[ 7: 0] = {B5, 3'b000}     低位 3 位恒为 0
//
//     所以它**不是**真 RGB888，直接取高位就是 R5 / G6 / B5。
//
//     ★ 灰度公式必须与 defect_detect.v 完全一致（合体交叉验证点）：
//           S    = 2·(R5 + G6) + B5      权重 2:4:1，范围 0..219
//           gray = S + (S>>3)            ≈ S×9/8，范围 0..246
//       3 个加法器、0 个 DSP；可区分灰度档位 **220 级**（不是 126 级）。
//
//   --------------------------------------------------------------------
//   注释规范（项目要求，2026-09-24）
//   --------------------------------------------------------------------
//       每一行有实际功能的代码，行尾都跟一条中文注释，说明"这行在做什么 / 为什么"。
//       本文件以 **UTF-8（无 BOM）** 编码保存。
//       纯声明、空行、end / endmodule / begin 之类不强制加注释。
//////////////////////////////////////////////////////////////////////////////

module size_detect #(
    parameter integer H_ACTIVE = 972,   // 每行有效像素数
    parameter integer V_ACTIVE = 720    // 每帧有效行数
)(
    // ------------------------------------------------------------------
    // 时钟与复位
    // ------------------------------------------------------------------
    input  wire        clk,        // aclk，100MHz
    input  wire        rst_n,      // 低有效复位

    // ------------------------------------------------------------------
    // 视频观测口（两个检测模块完全一致）
    // ------------------------------------------------------------------
    input  wire [23:0] px_data,    // RGB565 左对齐补 0 的 24 位像素
    input  wire        px_valid,   // = s_axis_tvalid & s_axis_tready
    input  wire        px_sof,     // 帧首（已带 px_valid 限定）
    input  wire        px_eol,     // 行尾（已带 px_valid 限定）
    input  wire        px_eof,     // 帧尾（已带 px_valid 限定）

    // ------------------------------------------------------------------
    // 控制口（由 SIZE_TH 寄存器 0x0C 驱动）
    // ------------------------------------------------------------------
    input  wire        en,         // SIZE_TH[0]，使能
    input  wire        polarity,   // SIZE_TH[1]：0 = 放置物比背景亮
    input  wire [7:0]  th,         // SIZE_TH[15:8]，灰度阈值

    // ------------------------------------------------------------------
    // 结果口
    // ------------------------------------------------------------------
    output wire [15:0] w,          // 放置物宽（像素）
    output wire [15:0] h,          // 放置物高（像素）
    output wire [31:0] area,       // 本帧放置物像素个数
    output wire        done,       // 帧末单拍脉冲
    output wire        px_hit      // 1 = 当前像素被判为放置物
                                   //（供 DISP 显示二值图调试用）
);

    //=====================================================================
    // 哑活 —— 实现真逻辑时**整块删掉**
    //
    // 为什么要放这个：如果真的是全空，所有结果寄存器都读回 0，
    // 而"0"和"通路断了"根本分不出来。这个计数器让读回的值**会变**，
    // 于是 PS 读一次就能证明：帧边界认得对、寄存器通路也是通的。
    //
    //   预期现象：area 每帧 +1（约 28.6 次/秒）
    //             done 每帧一个脉冲（会把 STATUS bit0 置起来）
    //=====================================================================
    reg [31:0] dummy_frame_cnt;                         // 帧计数器，纯占位用

    always @(posedge clk) begin
        if (!rst_n)
            dummy_frame_cnt <= 32'd0;                   // 复位清零
        else if (px_eof)
            dummy_frame_cnt <= dummy_frame_cnt + 32'd1; // 每见到一次帧尾就加一
    end

    assign w      = 16'd0;              // 哑活
    assign h      = 16'd0;              // 哑活
    assign area   = dummy_frame_cnt;    // 哑活（删掉，换成真实面积）
    assign done   = px_eof;             // 哑活（删掉，换成真实的帧末锁存脉冲）
    assign px_hit = 1'b0;               // 哑活（删掉，换成真实的二值化结果）

    //=====================================================================
    // TODO（队友）：真实实现写在这里。
    //
    // 建议的结构（完整讨论见分工契约）：
    //   1) 灰度   ：gray = px_data[23:19] + px_data[15:10] + px_data[7:3]
    //   2) 二值化 ：hit  = polarity ? (gray < th) : (gray > th)
    //   3) ROI 投限：只统计画面中间区域内的命中像素，这样角落上一粒亮噪点
    //                就不会把包围盒撑到整幅画面
    //   4) 行内连续段：只有同一行内连续命中 >= N 个像素才算数（便宜的降噪）
    //   5) 包围盒 ：min_x / max_x / min_y / max_y 以及 area 计数
    //   6) 帧末   ：w = max_x-min_x+1 ；h = max_y-min_y+1 ；并脉冲 done
    //   7) 影子寄存器：在 done 那一拍把 w/h/area 锁存进影子寄存器，
    //                这样 PS 永远不会读到"半新半旧"的一组值
    //
    // 记住：x 遇 px_eol 归零、y 遇 px_sof 归零，而 eol/sof 脉冲
    // 与它所属的那个像素**在同一拍**到达，所以必须在评估完当前像素
    // **之后**才更新计数器。
    //=====================================================================

endmodule
