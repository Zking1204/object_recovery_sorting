//////////////////////////////////////////////////////////////////////////////
// dd_thresh.v
//
//   第⑤级：二值化（当前是最简版，单阈值）。
//
//   在定位流水线里的位置（由 defect_detect.v 例化）：
//       dd_gray ──► [dd_thresh] ──► px_hit
//
//   ★ 后面中值 / Sobel / 背景 / 形态学会插在 dd_gray 和本模块**之间**，
//     届时本模块的输入不再是原始灰度，而是形态学的输出，本模块本身不用改。
//
//   ★ 像素通路是**纯组合逻辑（0 拍延迟）**：out_hit 与 in_pix 严格同拍。
//     （参数锁存器是寄存器，但它只影响"用哪个阈值"，不在像素通路上。）
//
//   ★★ 将来如果要在这一级插流水寄存器：
//     必须把 in_valid / in_sof / in_eol / in_eof **一起延迟同样拍数**。
//
//   --------------------------------------------------------------------
//   阈值与极性的两个必须知道的事实
//   --------------------------------------------------------------------
//     1) 阈值寄存器是 8 位，但灰度只有 220 个有效档位（0..246，且不连续），
//        所以并不是 256 个阈值都"生效" —— 这是正常的，不是寄存器坏了。
//     2) 阈值 / 极性 / 使能都在**帧首**才锁存。PS 随时可能改这些寄存器，
//        如果直接用组合值，改参数的那一拍会落在画面中间，
//        结果就是"同一帧上半部分一个阈值、下半部分另一个阈值"（撕裂）。
//
//   --------------------------------------------------------------------
//   注释规范（项目要求，2026-09-24）
//   --------------------------------------------------------------------
//       每一行有实际功能的代码，行尾都跟一条中文注释，说明"这行在做什么 / 为什么"。
//       本文件以 **UTF-8（无 BOM）** 编码保存。
//////////////////////////////////////////////////////////////////////////////

module dd_thresh (
    // ------------------------------------------------------------------
    // 时钟与复位
    //   clk/rst_n 被参数锁存器使用。
    // ------------------------------------------------------------------
    input  wire        clk,        // aclk，100MHz
    input  wire        rst_n,      // 低有效复位

    // ------------------------------------------------------------------
    // 像素输入
    // ------------------------------------------------------------------
    input  wire        in_valid,   // 本拍有有效像素
    input  wire [7:0]  in_pix,     // 8 位灰度
    input  wire        in_sof,     // 帧首
    input  wire        in_eol,     // 行尾
    input  wire        in_eof,     // 帧尾

    // ------------------------------------------------------------------
    // 控制（来自顶层 AXI-Lite 寄存器，PS 随时可能改）
    // ------------------------------------------------------------------
    input  wire        cfg_en,     // 使能
    input  wire        cfg_pol,    // 极性：0 = 比阈值亮算命中
    input  wire [7:0]  cfg_th,     // 灰度阈值

    // ------------------------------------------------------------------
    // 像素输出
    // ------------------------------------------------------------------
    output wire        out_valid,  // 与 in_valid 同拍（0 拍延迟）
    output wire        out_hit,    // 1 = 本像素命中（判为目标）
    output wire        out_sof,    // 与 in_sof 同拍
    output wire        out_eol,    // 与 in_eol 同拍
    output wire        out_eof     // 与 in_eof 同拍
);

    //=====================================================================
    // 参数锁存：阈值 / 极性 / 使能只在**帧首**更新
    //   这样一帧之内参数不变，不会出现"半帧一个阈值"的撕裂。
    //=====================================================================
    reg [7:0] th_cur;                                   // 本帧实际使用的灰度阈值
    reg       pol_cur;                                  // 本帧实际使用的极性
    reg       en_cur;                                   // 本帧实际使用的使能

    always @(posedge clk) begin
        if (!rst_n) begin
            th_cur  <= 8'd0;                            // 复位后阈值为 0
            pol_cur <= 1'b0;                            // 复位后极性为 0（亮的算命中）
            en_cur  <= 1'b0;                            // 复位后模块关闭
        end else if (in_sof) begin
            th_cur  <= cfg_th;                          // 帧首更新阈值，一帧内保持不变
            pol_cur <= cfg_pol;                         // 帧首更新极性，一帧内保持不变
            en_cur  <= cfg_en;                          // 帧首更新使能，一帧内保持不变
        end
    end

    //=====================================================================
    // 二值化（纯组合，0 拍延迟）
    //
    //   pol = 0：灰度大于阈值算命中（目标比放置物亮）
    //   pol = 1：灰度小于阈值算命中（目标比放置物暗）
    //   极性做成运行时可配，换打光方式不用重新编译位流。
    //
    //   ★★ 帧首那一个像素必须用**新**参数判定 ★★
    //
    //     参数是在帧首那一拍的**时钟沿**锁存的，而这个像素是在**同一拍的
    //     组合通路**上判定的 —— 如果这里直接用 th_cur / pol_cur / en_cur，
    //     帧首这个像素用的会是**上一帧**的参数。
    //     后果：每帧第 1 个像素判错。最明显的是刚把使能关掉时，下一帧的
    //     第 1 个像素仍会被判成命中，把整帧的计数和"有无目标"标志带偏。
    //     （这一条是被 tb_defect_detect.v 仿真抓出来的，不是推理出来的。）
    //
    //     修法：帧首那一拍直接取 cfg_*，之后的像素才用锁存值。
    //=====================================================================
    wire [7:0] th_use  = in_sof ? cfg_th  : th_cur;     // 帧首像素用新阈值，其余用锁存值
    wire       pol_use = in_sof ? cfg_pol : pol_cur;    // 帧首像素用新极性，其余用锁存值
    wire       en_use  = in_sof ? cfg_en  : en_cur;     // 帧首像素用新使能，其余用锁存值

    wire hit_c = pol_use ? (in_pix < th_use) : (in_pix > th_use);   // 二值化，1 bit
    wire hit   = en_use & hit_c;                        // 使能为 0 时强制不命中

    //=====================================================================
    // 输出：命中标志 + sideband 原样直通（0 拍延迟）
    //=====================================================================
    assign out_hit   = hit;                             // 二值化结果
    assign out_valid = in_valid;                        // 同拍直通
    assign out_sof   = in_sof;                          // 同拍直通
    assign out_eol   = in_eol;                          // 同拍直通
    assign out_eof   = in_eof;                          // 同拍直通

endmodule
